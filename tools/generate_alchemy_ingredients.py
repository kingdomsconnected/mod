#!/usr/bin/env python3
"""Compile the native alchemy resource quality category from shipped tables.

CalculateQuality at 0x1806C4184 uses the Herb class category and whether its
food descriptor's DecayTime is positive. This differs from DriedItemId:
ginger/elderberry are non-decaying herbs without a fresh/dried pair.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import re
import xml.etree.ElementTree as ET
import zipfile


def extract(pak):
    rows = {}
    for name in sorted(pak.namelist()):
        if not re.fullmatch(r"Libs/Tables/item/item(?:__[a-zA-Z_]+)?\.xml", name):
            continue
        for row in ET.fromstring(pak.read(name)).find("ItemClasses"):
            if row.attrib["Id"] in rows:
                raise ValueError("Duplicate item class: " + row.attrib["Id"])
            rows[row.attrib["Id"]] = row

    def resolve(key, visited=()):
        if key in visited:
            raise ValueError("ItemAlias cycle: " + key)
        row = rows[key]
        if row.tag == "ItemAlias":
            if "DecayTime" in row.attrib:
                raise ValueError("Unsupported alias decay override: " + key)
            return resolve(row.attrib["SourceItemId"], visited + (key,))
        if row.tag != "Herb":
            return None
        decay = float(row.attrib["DecayTime"])
        if not 0 <= decay < float("inf"):
            raise ValueError("Invalid herb decay: " + key)
        return decay > 0

    return [(key, resolve(key)) for key in sorted(rows) if resolve(key) is not None]


def extract_crushable(pak):
    path = 'Libs/Tables/minigame/AlchemyCrushableSpecialIngredient.xml'
    result = []
    for row in ET.fromstring(pak.read(path)).find('AlchemyCrushableSpecialIngredients'):
        item = row.attrib['ItemId']
        if not re.fullmatch(r'[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}', item):
            raise ValueError('Invalid crushable ingredient GUID: ' + item)
        if item in result:
            raise ValueError('Duplicate crushable ingredient: ' + item)
        result.append(item)
    if not result:
        raise ValueError('Empty crushable ingredient catalog')
    return sorted(result)


def generate(rows, output, crushable=()):
    lines = ['// Generated by tools/generate_alchemy_ingredients.py; do not edit.', '#include "shared/game/alchemy_ingredients.h"', '', '#include <algorithm>', '', 'namespace KCDC::Shared::Game {', '    const std::vector<AlchemyHerbClass> g_AlchemyHerbClasses = {']
    lines.extend(f'        {{"{key}", {str(decays).lower()}}},' for key, decays in rows)
    lines += ['    };', '', '    const std::vector<std::string_view> g_AlchemyCrushableSpecialIngredients = {']
    lines.extend(f'        "{item}",' for item in crushable)
    lines += ['    };', '', '    bool IsCrushableAlchemyIngredient(std::string_view item) {', '        return std::binary_search(g_AlchemyCrushableSpecialIngredients.begin(), g_AlchemyCrushableSpecialIngredients.end(), item);', '    }', '', '    const AlchemyHerbClass *FindAlchemyHerbClass(std::string_view item) {', '        const auto found = std::lower_bound(g_AlchemyHerbClasses.begin(), g_AlchemyHerbClasses.end(), item, [](const AlchemyHerbClass &entry, std::string_view key) { return entry.item < key; });', '        return found != g_AlchemyHerbClasses.end() && found->item == item ? &*found : nullptr;', '    }', '} // namespace KCDC::Shared::Game', '']
    Path(output).write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('game_directory', type=Path)
    parser.add_argument('--output', default='code/shared/generated/alchemy_ingredients.cpp')
    args = parser.parse_args()
    with zipfile.ZipFile(args.game_directory / 'Data/Tables.pak') as pak:
        rows = extract(pak)
        crushable = extract_crushable(pak)
    generate(rows, args.output, crushable)
    print(f'Generated {len(rows)} alchemy herb quality classes')
