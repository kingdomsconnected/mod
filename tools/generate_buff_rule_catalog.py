#!/usr/bin/env python3
"""Compile native buff implementation inputs and explicit perk/item edges.

This carries authored data, not a claim that every native implementation has
an evaluator. Missing fields remain distinguishable from authored emptiness.
Only active and relevant rows are queried by the authoritative evaluator.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import uuid
import xml.etree.ElementTree as ET
import zipfile

BUFF_TABLE = re.compile(r"^Libs/Tables/rpg/buff(__[A-Za-z0-9_]+)?\.xml$")
ITEM_TABLE = re.compile(r"^Libs/Tables/item/item(__[A-Za-z0-9_]+)?\.xml$")


def guid(value):
    return str(uuid.UUID(value))


def extract(pak):
    buffs = {}
    items = {}
    for name in sorted(pak.namelist()):
        if BUFF_TABLE.fullmatch(name):
            rows = ET.fromstring(pak.read(name)).find('buffs')
            if rows is None:
                raise ValueError(f'Missing buff rows: {name}')
            for row in rows:
                key = guid(row.attrib['buff_id'])
                if key in buffs:
                    raise ValueError(f'Duplicate buff GUID: {key}')
                attrs = row.attrib
                buffs[key] = (attrs['implementation'], attrs.get('buff_params', ''), 'buff_params' in attrs)
        elif ITEM_TABLE.fullmatch(name):
            rows = ET.fromstring(pak.read(name)).find('ItemClasses')
            if rows is None:
                raise ValueError(f'Missing item rows: {name}')
            for row in rows:
                key = guid(row.attrib['Id'])
                if key in items:
                    raise ValueError(f'Duplicate item GUID: {key}')
                items[key] = row

    resolved_items = {}

    def item_buff(key, visited=()):
        if key in visited:
            raise ValueError(f'ItemAlias cycle: {key}')
        if key in resolved_items:
            return resolved_items[key]
        item = items[key]
        if item.tag == 'ItemAlias':
            if 'BuffDefinitionId' in item.attrib:
                raise ValueError(f'Unproven ItemAlias buff override: {key}')
            value = item_buff(guid(item.attrib['SourceItemId']), visited + (key,))
        else:
            value = guid(item.attrib['BuffDefinitionId']) if item.attrib.get('BuffDefinitionId') else None
        if value is not None and value not in buffs:
            raise ValueError(f'Unknown item buff: {key} -> {value}')
        resolved_items[key] = value
        return value

    item_edges = [(key, value) for key in sorted(items) if (value := item_buff(key)) is not None]
    perk_edges = []
    for row in ET.fromstring(pak.read('Libs/Tables/rpg/perk_buff.xml')).find('perk_buffs'):
        perk, buff = guid(row.attrib['perk_id']), guid(row.attrib['buff_id'])
        if buff not in buffs:
            raise ValueError(f'Unknown perk buff: {buff}')
        perk_edges.append((perk, buff))
    remaps = []
    for row in ET.fromstring(pak.read('Libs/Tables/rpg/perk_buff_override.xml')).find('perk_buff_overrides'):
        perk, source, target = (guid(row.attrib[key]) for key in ('perk_id', 'source_buff_id', 'target_buff_id'))
        if source not in buffs or target not in buffs:
            raise ValueError(f'Unknown buff remap: {source} -> {target}')
        remaps.append((perk, source, target))
    if len(set(perk_edges)) != len(perk_edges) or len(set(remaps)) != len(remaps):
        raise ValueError('Duplicate perk effect edge')
    result = {'buffs': sorted(buffs.items()), 'perkBuffs': sorted(perk_edges), 'perkRemaps': sorted(remaps), 'itemBuffs': item_edges}
    result['digest'] = hashlib.sha256(json.dumps(result, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    return result


def generate(data, output):
    lines = ['// Generated by tools/generate_buff_rule_catalog.py; do not edit.', '#include "shared/game/buff_rule_catalog.h"', '', '#include <algorithm>', '', 'namespace KCDC::Shared::Game {', f'    const std::string_view g_BuffRuleCatalogHash = "{data["digest"]}";', '    const std::vector<BuffRuleDefinition> g_BuffRules = {']
    for key, (implementation, parameters, authored) in data['buffs']:
        lines.append('        {%s, %s, %s, %s},' % (json.dumps(key), json.dumps(implementation), json.dumps(parameters), str(authored).lower()))
    lines += ['    };', '    const std::vector<PerkBuffRule> g_PerkBuffRules = {']
    for perk, buff in data['perkBuffs']:
        lines.append('        {%s, %s},' % (json.dumps(perk), json.dumps(buff)))
    lines += ['    };', '    const std::vector<PerkBuffRemap> g_PerkBuffRemaps = {']
    for perk, source, target in data['perkRemaps']:
        lines.append('        {%s, %s, %s},' % (json.dumps(perk), json.dumps(source), json.dumps(target)))
    lines += ['    };', '    const std::vector<ItemBuffRule> g_ItemBuffRules = {']
    for item, buff in data['itemBuffs']:
        lines.append('        {%s, %s},' % (json.dumps(item), json.dumps(buff)))
    lines += ['    };', '', '    const BuffRuleDefinition *FindBuffRule(std::string_view guid) {', '        const auto found = std::lower_bound(g_BuffRules.begin(), g_BuffRules.end(), guid, [](const BuffRuleDefinition &row, std::string_view value) { return row.guid < value; });', '        return found != g_BuffRules.end() && found->guid == guid ? &*found : FindCustomBuffRule(guid);', '    }', '} // namespace KCDC::Shared::Game', '']
    Path(output).write_text('\n'.join(lines), encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('game_directory', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    with zipfile.ZipFile(args.game_directory / 'Data/Tables.pak') as pak:
        data = extract(pak)
    generate(data, args.output)
    print({key: len(data[key]) for key in ('buffs', 'perkBuffs', 'perkRemaps', 'itemBuffs')})
    print(data['digest'])


if __name__ == '__main__':
    main()
