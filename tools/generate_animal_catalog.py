#!/usr/bin/env python3
"""Compile animal identities and level AnimalSpawner markers from the game paks.

Soul archetypes determine the entity class. Layer XML is included, and GUIDs
deduplicate copies of the same placement. Marker positions are deliberately
kept as authored: users must project them onto navigation before spawning.
Chickens are boids, not actors, and are not included in this NPC catalog.
"""

import argparse
import collections
import json
import math
from pathlib import Path
import re
import xml.etree.ElementTree as ET
import zipfile

from generate_gate_catalog import DEFAULT_GAME, entity_guid, zread

CLASSES = frozenset(("SheepEwe", "SheepRam", "CattleCow", "CattleBull", "Pig", "Boar", "Hare", "RedDeerStag", "RedDeerDoe", "RoeDeerBuck", "RoeDeerHind", "Wolf", "WildDog"))
LEVELS = ("trosecko", "kutnohorsko", "klaster")


def read_defaults(game):
    with zipfile.ZipFile(game / "Data/Scripts.pak") as archive:
        text = zread(archive, "Scripts/Entities/WH/Others/AnimalSpawner.lua").decode()
    defaults = {}
    for field in ("AnimalCount", "RespawnDays", "SpawnInFlock"):
        match = re.search(r"\b" + field + r"\s*=\s*(\d+|true|false)", text)
        if not match:
            raise ValueError(f"Missing AnimalSpawner default: {field}")
        defaults[field] = match[1]
    return defaults


def collect(game):
    defaults = read_defaults(game)
    with zipfile.ZipFile(game / "Data/Tables.pak") as archive:
        archetypes = {e.get("soul_archetype_id"): e.get("soul_archetype_name") for e in ET.fromstring(zread(archive, "Libs/Tables/rpg/soul_archetype.xml")).iter("soul_archetype")}
        animals = {}
        for name in sorted(archive.namelist()):
            if not re.fullmatch(r"Libs/Tables/rpg/soul(?:__[^/]+)?\.xml", name):
                continue
            for soul in ET.fromstring(zread(archive, name)).iter("soul"):
                actor_class = archetypes.get(soul.get("soul_archetype_id"))
                if actor_class in CLASSES:
                    animals[soul.get("soul_id")] = (soul.get("soul_name"), soul.get("soul_id"), actor_class)
    points = []
    for level in LEVELS:
        with zipfile.ZipFile(game / f"Data/Levels/{level}/level.pak") as archive:
            entities = {}
            for name in sorted(archive.namelist()):
                if name != "objects_mission0.xml" and not (name.startswith("layers/") and name.endswith(".xml")):
                    continue
                for entity in ET.fromstring(zread(archive, name)).iter("Entity"):
                    guid = entity_guid(entity.get("EntityGuid", ""))
                    if guid:
                        entities[guid] = entity
            by_id = {e.get("EntityId"): guid for guid, e in entities.items()}
            for guid, entity in sorted(entities.items()):
                if entity.get("EntityClass") != "AnimalSpawner":
                    continue
                properties = dict(defaults)
                props = entity.find("Properties")
                if props is not None:
                    properties.update(props.attrib)
                soul = properties.get("guidSoul", "")
                animal = animals.get(soul)
                # Explicit class-only spawners remain usable with a blank soul.
                actor_class = properties.get("EntityClass", "") or (animal[2] if animal else "")
                if actor_class not in CLASSES:
                    continue
                if soul and animal is None:
                    raise ValueError(f"Unresolved animal soul {soul} on {level}/{guid:x}")
                if animal and actor_class != animal[2]:
                    raise ValueError(f"Mismatched animal class on {level}/{guid:x}")
                position = tuple(float(v) for v in entity.get("Pos", "0,0,0").split(","))
                if len(position) != 3 or not all(math.isfinite(v) for v in position):
                    raise ValueError(f"Invalid position on {level}/{guid:x}")
                spawn_area = 0
                for link in entity.findall("EntityLinks/Link"):
                    if link.get("Name") == "spawnArea":
                        spawn_area = entity_guid(link.get("TargetGuid", "")) or by_id.get(link.get("TargetId"), 0)
                points.append((level, f"{guid:016x}", entity.get("Name", ""), entity.get("EditorLayer", ""), soul, actor_class, position, int(properties["AnimalCount"]), int(properties["RespawnDays"]), properties["SpawnInFlock"].lower() not in ("0", "false"), f"{spawn_area:016x}" if spawn_area else ""))
    return sorted(animals.values()), points


def render(animals, points):
    quote = lambda value: json.dumps(value, ensure_ascii=True)
    lines = ['// Generated by tools/generate_animal_catalog.py. Do not edit by hand.', '#include "shared/game/animal_catalog.h"', '', 'namespace KCDC::Shared::Game {', '    const std::vector<AnimalDefinition> g_Animals = {']
    lines += ['        {' + ', '.join(quote(v) for v in row) + '},' for row in animals]
    lines += ['    };', '', '    const std::vector<AnimalSpawnpoint> g_AnimalSpawnpoints = {']
    for row in points:
        position = '{' + ', '.join(f'{v:.7f}F' for v in row[6]) + '}'
        fields = [*(quote(v) for v in row[:6]), position, str(row[7]), str(row[8]), str(row[9]).lower(), quote(row[10])]
        lines.append('        {' + ', '.join(fields) + '},')
    lines += ['    };', '', '    const AnimalDefinition *FindAnimal(std::string_view nameOrGuid) {', '        for (const auto &animal : g_Animals) {', '            if (animal.name == nameOrGuid || animal.soulGuid == nameOrGuid) {', '                return &animal;', '            }', '        }', '        return nullptr;', '    }', '} // namespace KCDC::Shared::Game', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--game', type=Path, default=Path(DEFAULT_GAME))
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'code/shared/generated/animal_catalog.cpp')
    args = parser.parse_args()
    animals, points = collect(args.game)
    args.output.write_text(render(animals, points), encoding='utf-8', newline='\n')
    print(f'{len(animals)} animal souls; {len(points)} spawnpoints: {dict(collections.Counter(p[0] for p in points))}')


if __name__ == '__main__':
    main()
