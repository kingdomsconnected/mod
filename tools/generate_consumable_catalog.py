#!/usr/bin/env python3
"""Compile the native food and potion base effects for server decisions."""

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile

from generate_gate_catalog import DEFAULT_GAME


def collect(archive):
    rows = {}
    for name in sorted(archive.namelist()):
        if name.startswith("Libs/Tables/item/item") and name.endswith(".xml"):
            for row in ET.fromstring(archive.read(name)).iter("Food"):
                if row.get("Id"):
                    rows[row.get("Id")] = row
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game", default=DEFAULT_GAME)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "code/shared/generated/consumable_catalog.cpp")
    args = parser.parse_args()
    with zipfile.ZipFile(Path(args.game) / "Data/Tables.pak") as archive:
        rows = collect(archive)
    lines = ['// Generated by tools/generate_consumable_catalog.py. Do not edit.', '#include "shared/game/consumable_catalog.h"', '#include <algorithm>', '', 'namespace KCDC::Shared::Game {', '    const std::vector<ConsumableEntry> g_Consumables {']
    for guid, row in sorted(rows.items()):
        values = [format(float(row.get(key, "0")), ".9f") + "F" for key in ("HealthBenefit", "RefreshBenefit", "NutritionBenefit", "AlcoholContent")]
        lines.append('        {"%s", "%s", %s, %s},' % (guid, row.get("BuffDefinitionId", ""), str(row.get("Type") == "1").lower(), ", ".join(values)))
    lines += ['    };', '', '    const ConsumableEntry *FindConsumable(std::string_view item) {', '        const auto found = std::lower_bound(g_Consumables.begin(), g_Consumables.end(), item, [](const auto &entry, auto id) { return entry.item < id; });', '        return found != g_Consumables.end() && found->item == item ? &*found : nullptr;', '    }', '} // namespace KCDC::Shared::Game', '']
    args.output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Compiled {len(rows)} food and potion definitions")


if __name__ == "__main__":
    main()
