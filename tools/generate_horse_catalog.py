#!/usr/bin/env python3
"""Generate the KCDC horse catalog from an installed Kingdom Come: Deliverance II.

A horse is spawned against a soul, and the game ships 570 horse souls
(`soul_class_id` 7, "horse"; class 8, "war horse", has none). Almost all of
them are one quest's extras -- `finale_battle_horse_12`, `kgru_horse_6` -- that
share the generic animal's look and stats. What makes a horse one a player
would pick is a `skald_character_name`: that is where its coat, its build and
its name come from, and it is exactly the set the game's own traders sell
(`*_horseForSale_*`) plus the named horses of its quests.

So the catalog is every horse soul that names a character, keyed by that
character's English UI name (resolved against `Localization/English_xml.pak`)
turned into a script identifier -- `pebbles`, `kluger_hans` -- plus `horse`,
the generic `animal_horse` a spawn falls back to. Two souls sharing one
character keep the first by soul name: they are the same animal.

Emitted as `code/shared/generated/horse_catalog.cpp`, because the server has no game
module to read the tables from.

Usage:
    python tools/generate_horse_catalog.py <game directory>
"""

from __future__ import annotations

import argparse
import html
import os
import re
import sys
import zipfile

TABLES_PAK = os.path.join("Data", "Tables.pak")
LOCALIZATION_PAK = os.path.join("Localization", "English_xml.pak")
SOUL_TABLE_PREFIX = "Libs/Tables/rpg/soul__"
CHARACTER_TABLE = "Libs/Tables/skald/skald_character.xml"

# `soul_class.xml`: 7 is "horse", 8 is "war horse".
HORSE_SOUL_CLASSES = {"7", "8"}

# What `HorseEntity::kDefaultSoulGuid` names, listed first under a plain name.
GENERIC_SOUL_NAME = "animal_horse"
GENERIC_BREED_NAME = "horse"

DEFAULT_OUTPUT = os.path.join("code", "shared", "generated", "horse_catalog.cpp")

ATTR_RE = re.compile(r'(\w+)="([^"]*)"')
ROW_RE = re.compile(r"<Row><Cell>([^<]*)</Cell><Cell>[^<]*</Cell><Cell>([^<]*)</Cell></Row>")


def read_rows(raw, tag):
    return [dict(ATTR_RE.findall(match.group(0))) for match in re.finditer(r"<%s\b[^>]*/>" % tag, raw)]


def read_horse_souls(tables):
    souls = []
    for entry in sorted(tables.namelist()):
        if not entry.startswith(SOUL_TABLE_PREFIX) or not entry.endswith(".xml"):
            continue
        for row in read_rows(tables.read(entry).decode("utf-8", "replace"), "soul"):
            if row.get("soul_class_id") in HORSE_SOUL_CLASSES and row.get("soul_id"):
                souls.append(row)
    souls.sort(key=lambda row: row.get("soul_name", "").lower())
    return souls


def read_english(game_dir):
    strings = {}
    with zipfile.ZipFile(os.path.join(game_dir, LOCALIZATION_PAK)) as pak:
        for name in pak.namelist():
            for match in ROW_RE.finditer(pak.read(name).decode("utf-8", "replace")):
                strings[match.group(1)] = html.unescape(match.group(2))
    return strings


def ascii_text(value):
    """Typographic punctuation flattened, so the emitted source stays ASCII."""
    for fancy, plain in (("’", "'"), ("‘", "'"), ("“", '"'), ("”", '"'), ("–", "-"), ("—", "-")):
        value = value.replace(fancy, plain)
    return value.encode("ascii", "ignore").decode("ascii")


def identifier(display):
    """`Hide'n'hair` -> `hide_n_hair`: what a chat command or a script types."""
    return re.sub(r"[^a-z0-9]+", "_", display.lower()).strip("_")


def cpp_string(value):
    return '"%s"' % value.replace("\\", "\\\\").replace('"', '\\"')


def build_catalog(game_dir):
    with zipfile.ZipFile(os.path.join(game_dir, TABLES_PAK)) as tables:
        souls = read_horse_souls(tables)
        characters = {row["skald_character_name"]: row for row in read_rows(tables.read(CHARACTER_TABLE).decode("utf-8", "replace"), "skald_character")}
    english = read_english(game_dir)

    generic = next((row for row in souls if row.get("soul_name") == GENERIC_SOUL_NAME), None)
    if generic is None:
        raise SystemExit("error: no %s soul; the default horse is gone" % GENERIC_SOUL_NAME)

    breeds = [(GENERIC_BREED_NAME, "Horse", generic["soul_id"], GENERIC_SOUL_NAME)]
    seen_characters = set()
    seen_names = {GENERIC_BREED_NAME}
    for row in souls:
        character = row.get("skald_character_name", "")
        if not character or character in seen_characters:
            continue
        display = ascii_text(english.get(characters.get(character, {}).get("ui_name_string_name", ""), "")).strip()
        name = identifier(display)
        if not name or name in seen_names:
            continue
        seen_characters.add(character)
        seen_names.add(name)
        breeds.append((name, display, row["soul_id"], row["soul_name"]))

    breeds[1:] = sorted(breeds[1:], key=lambda breed: breed[0])
    return breeds


def render(breeds):
    lines = [
        "// Generated by tools/generate_horse_catalog.py from Data/Tables.pak and",
        "// Localization/English_xml.pak. Do not edit by hand.",
        "",
        '#include "shared/game/horse_catalog.h"',
        "",
        "namespace KCDC::Shared::Game {",
        "    const std::vector<HorseBreedEntry> g_HorseBreeds = {",
    ]
    for name, display, soul_id, soul_name in breeds:
        lines.append("        {%s, %s, %s, %s}," % (cpp_string(name), cpp_string(display), cpp_string(soul_id), cpp_string(soul_name)))
    lines += [
        "    };",
        "",
        "    const HorseBreedEntry *FindHorseBreed(std::string_view name) {",
        "        for (const HorseBreedEntry &breed : g_HorseBreeds) {",
        "            if (breed.name == name) {",
        "                return &breed;",
        "            }",
        "        }",
        "        return nullptr;",
        "    }",
        "} // namespace KCDC::Shared::Game",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("game_dir", help="Kingdom Come: Deliverance II installation directory")
    parser.add_argument("-o", "--output", default=DEFAULT_OUTPUT, help="where to write the generated table")
    args = parser.parse_args()

    breeds = build_catalog(args.game_dir)
    with open(args.output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(breeds))

    print("Wrote %d horse breeds to %s" % (len(breeds), args.output))
    return 0


if __name__ == "__main__":
    sys.exit(main())
