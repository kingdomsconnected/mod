#!/usr/bin/env python3
"""Compile authored human NPC placements; a placement is not a live schedule.

Reads objects_mission0.xml and matches entity names to the existing soul TSV.
Unknown souls are omitted, never guessed. No game assets are copied.
"""
import argparse
import json
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile


def generate(game, root):
    souls = {}
    for line in (root / 'files/kcdc/souls.tsv').read_text(encoding='utf-8').splitlines():
        if line.startswith('#') or not line:
            continue
        name, actor, guid, *_ = line.split('\t')
        souls[name] = (actor, guid)
    rows = []
    for level in ('trosecko', 'kutnohorsko', 'klaster'):
        with zipfile.ZipFile(game / f'Data/Levels/{level}/level.pak') as pak:
            for entity in ET.fromstring(pak.read('objects_mission0.xml')).iter('Entity'):
                name = entity.get('Name', '')
                actor = entity.get('EntityClass')
                if actor not in ('NPC', 'NPC_Female') or name not in souls or souls[name][0] != actor:
                    continue
                position = [float(v) for v in entity.attrib['Pos'].split(',')]
                rotation = [float(v) for v in entity.get('Rotate', '1,0,0,0').split(',')]
                rows.append((level, name, entity.attrib['EntityGuid'], actor, souls[name][1], entity.get('EditorLayer', ''), *position, *rotation))
    lines = ['// Generated by tools/generate_npc_placement_catalog.py; do not edit.', '#include "shared/game/npc_placement_catalog.h"', '', 'namespace KCDC::Shared::Game {', '    const std::vector<NpcPlacement> g_NpcPlacements = {']
    for row in sorted(rows):
        fields = [json.dumps(v) if isinstance(v, str) else f'{v:.7f}F' for v in row]
        lines.append('        {' + ', '.join(fields) + '},')
    lines += ['    };', '} // namespace KCDC::Shared::Game', '']
    (root / 'code/shared/generated/npc_placement_catalog.cpp').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'Generated {len(rows)} NPC placements.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('game', type=Path)
    args = parser.parse_args()
    generate(args.game, Path(__file__).resolve().parents[1])
