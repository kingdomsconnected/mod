#!/usr/bin/env python3
"""Compile clothing slots and their dependencies from KCD2's shipped tables.

CharacterComponent inherits ArmorType and ArmorArchetypeId. Exclusive armor
coverage supplies body layer and equipment part; EquipmentSlots filters those
pairs by ArmorTypes and names RequiresFilledSlot/RequiresEmptySlot. Keep both
ends of each dependency so removing an underlayer cannot leave an impossible
equipped set on the server. No game files are needed at runtime.
"""
import argparse
from pathlib import Path
import re
import xml.etree.ElementTree as ET
from zipfile import ZipFile


def generate(game_directory):
    with ZipFile(game_directory / 'Data/Tables.pak') as pak:
        def table(name):
            return ET.fromstring(pak.read('Libs/Tables/' + name))

        slots = {row.attrib['Name']: row for row in table('item/equipment_slot.xml').iter('EquipmentSlot')}
        ids = [int(row.attrib['Id']) for row in slots.values()]
        if len(set(ids)) != len(ids) or any(not 0 < value < 64 for value in ids):
            raise ValueError('Equipment slot identities must be unique bits')

        def bit(name):
            return 1 << int(slots[name].attrib['Id']) if name else 0

        def depth(name, visiting=()):
            if not name:
                return 0
            if name in visiting:
                raise ValueError('Cyclic equipment dependency')
            required = slots[name].get('RequiresFilledSlot')
            return 1 + depth(required, visiting + (name,)) if required else 0

        layers = {row.attrib['body_layer_id']: row.attrib['body_layer_type_id'] for row in table('item/body_layer.xml').iter('body_layer')}
        parts = {row.attrib['body_subpart_id']: row.attrib['equipment_part_id'] for row in table('item/body_subpart.xml').iter('body_subpart')}
        coverage = {}
        for row in table('item/armor_archetype2body_subpart.xml').iter('armor_archetype2body_subpart'):
            if row.get('is_exclusive') == 'true':
                coverage.setdefault(row.attrib['armor_archetype_id'], set()).add((parts[row.attrib['body_subpart_id']], layers[row.attrib['body_layer_id']]))

        clothing = {}

        def visit(node, armor_type=None, archetype=None):
            armor_type = node.get('ArmorType', armor_type)
            archetype = node.get('ArmorArchetypeId', archetype)
            if node.tag == 'Clothing' and node.get('Name'):
                key = node.attrib['Name']
                value = (armor_type, archetype)
                if key in clothing and clothing[key] != value:
                    raise ValueError(f'Conflicting clothing definition: {key}')
                clothing[key] = value
            for child in node:
                visit(child, armor_type, archetype)

        visit(table('Character/CharacterComponent.xml'))
        items = {}
        for name in sorted(pak.namelist()):
            if re.fullmatch(r'Libs/Tables/item/item(?:__[a-zA-Z_]+)?\.xml', name, re.I):
                for item in ET.fromstring(pak.read(name)).find('ItemClasses'):
                    key = item.attrib['Id'].lower()
                    if key in items:
                        raise ValueError(f'Duplicate item: {key}')
                    items[key] = item

        def resolve(key, visiting=()):
            if key in visiting:
                raise ValueError('Cyclic item alias')
            item = items[key]
            if item.tag == 'ItemAlias':
                return resolve(item.attrib['SourceItemId'].lower(), visiting + (key,))
            component = item.get('Clothing')
            if not component:
                return None
            armor_type, archetype = clothing[component]
            matches = [name for name, slot in slots.items()
                       if (slot.attrib['EquipmentPartId'], slot.attrib['BodyLayerTypeId']) in coverage.get(archetype, ())
                       and ('ArmorTypes' not in slot.attrib or armor_type in slot.attrib['ArmorTypes'].split())]
            if not matches:
                return None
            occupied = required = excluded = order = 0
            for name in matches:
                occupied |= bit(name)
                required |= bit(slots[name].get('RequiresFilledSlot'))
                excluded |= bit(slots[name].get('RequiresEmptySlot'))
                order = max(order, depth(name))
            return occupied, required, excluded, order

        rows = [(key, *value) for key in sorted(items) if (value := resolve(key)) is not None]
        text = ['// Generated by tools/generate_equipment_catalog.py; do not edit.',
                '#include "shared/game/equipment_catalog.h"', '', '#include <algorithm>', '',
                'namespace KCDC::Shared::Game {',
                '    const std::vector<EquipmentClass> g_EquipmentClasses = {']
        for key, occupied, required, excluded, order in rows:
            text.append(f'        {{"{key}", 0x{occupied:X}ULL, 0x{required:X}ULL, 0x{excluded:X}ULL, {order}}},')
        text += ['    };', '', '    const EquipmentClass *FindEquipmentClass(std::string_view guid) {',
                 '        const auto found = std::lower_bound(g_EquipmentClasses.begin(), g_EquipmentClasses.end(), guid, [](const EquipmentClass &entry, std::string_view value) { return entry.guid < value; });',
                 '        return found != g_EquipmentClasses.end() && found->guid == guid ? &*found : nullptr;',
                 '    }', '} // namespace KCDC::Shared::Game', '']
        return '\n'.join(text), len(rows)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('game_directory', type=Path)
    parser.add_argument('--output', type=Path, default=Path('code/shared/generated/equipment_catalog.cpp'))
    args = parser.parse_args()
    text, count = generate(args.game_directory)
    args.output.write_text(text, encoding='utf-8', newline='\n')
    print(f'Generated {count} equipment classes')
