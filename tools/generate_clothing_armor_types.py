#!/usr/bin/env python3
"""Compile which clothing components the game marks immutable.

`Libs/Tables/item/armor_type.xml` names a few armor types whose items never
change condition (spurs, belts, pouches, horse tack...), and
`Libs/Tables/Character/CharacterComponent.xml` gives every clothing component
an `ArmorType`, inherited down its tree. `tools/generate_inventory_properties.py`
folds that into the compiled property table for every shipped item class. A
streamed mod's item class is read at runtime instead, so the runtime reader
needs the same two facts for a component the mod did not define itself: this
script writes them as `code/shared/generated/clothing_armor_types.cpp`.

Usage:
    python tools/generate_clothing_armor_types.py <game directory>
"""
from __future__ import annotations

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile


def extract(pak):
    armor_types = {row.attrib["Name"]: row.get("CanHealthChange", "true") == "true" for row in ET.fromstring(pak.read("Libs/Tables/item/armor_type.xml")).iter("armor_type")}
    immutable_types = sorted(name for name, mutable in armor_types.items() if not mutable)
    components = {}

    def visit(node, inherited=None):
        armor_type = node.get("ArmorType", inherited)
        if node.tag == "Clothing" and node.get("Name"):
            components[node.attrib["Name"]] = armor_type
        for child in node:
            visit(child, armor_type)

    visit(ET.fromstring(pak.read("Libs/Tables/Character/CharacterComponent.xml")))
    immutable_components = sorted(name for name, armor_type in components.items() if armor_type in immutable_types)
    return immutable_types, immutable_components


def generate(immutable_types, immutable_components, destination):
    text = [
        "// Generated by tools/generate_clothing_armor_types.py from Data/Tables.pak.",
        "// Do not edit by hand.",
        "",
        '#include "shared/game/clothing_armor_types.h"',
        "",
        "#include <algorithm>",
        "",
        "namespace KCDC::Shared::Game {",
        "    namespace {",
        "        // Sorted, for the binary searches below.",
        "        constexpr std::string_view kImmutableArmorTypes[] = {",
    ]
    text += [f'            "{name}",' for name in immutable_types]
    text += ["        };", "", f"        // {len(immutable_components)} of the game's clothing components carry one of those types.", "        constexpr std::string_view kImmutableClothingComponents[] = {"]
    text += [f'            "{name}",' for name in immutable_components]
    text += [
        "        };",
        "    } // namespace",
        "",
        "    bool IsImmutableArmorType(std::string_view armorType) {",
        "        return std::binary_search(std::begin(kImmutableArmorTypes), std::end(kImmutableArmorTypes), armorType);",
        "    }",
        "",
        "    bool IsImmutableClothingComponent(std::string_view component) {",
        "        return std::binary_search(std::begin(kImmutableClothingComponents), std::end(kImmutableClothingComponents), component);",
        "    }",
        "} // namespace KCDC::Shared::Game",
        "",
    ]
    Path(destination).write_text("\n".join(text), encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("game_directory", type=Path)
    parser.add_argument("--output", default="code/shared/generated/clothing_armor_types.cpp")
    args = parser.parse_args()
    with zipfile.ZipFile(args.game_directory / "Data/Tables.pak") as pak:
        immutable_types, immutable_components = extract(pak)
    generate(immutable_types, immutable_components, args.output)
    print(f"Generated {len(immutable_types)} immutable armor types and {len(immutable_components)} immutable clothing components")


if __name__ == "__main__":
    main()
