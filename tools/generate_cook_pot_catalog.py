#!/usr/bin/env python3
"""Extract placed stew pots and their kettle/cauldron links from base levels."""

import argparse
from pathlib import Path
import re
import xml.etree.ElementTree as ET
import zipfile

from generate_combat_catalog import item_class_halves
from generate_gate_catalog import DEFAULT_GAME, entity_guid, escape, zread

FOODS = ("goulash", "lentil", "soup")


def food_items(script):
    """The item class FireplaceSmartObject:GetEatItemClassId answers per cauldron type."""
    body = script.split("function FireplaceSmartObject:GetEatItemClassId()", 1)[1].split("\nend", 1)[0]
    named = dict(re.findall(r"== '(\w+)' then\s*return '([0-9a-f-]{36})'", body))
    fallback = re.search(r"else\s*return '([0-9a-f-]{36})'", body)
    if fallback is None or set(named) | {"soup"} != set(FOODS):
        raise ValueError("GetEatItemClassId no longer maps exactly goulash, lentil and soup")
    named.setdefault("soup", fallback.group(1))
    return [named[food] for food in FOODS]


def pot_consumables(archive, items):
    rows = {}
    for name in sorted(archive.namelist()):
        if name.startswith("Libs/Tables/item/item") and name.endswith(".xml"):
            for row in ET.fromstring(archive.read(name)).iter():
                if row.tag in ("Food", "Poison") and row.get("Id"):
                    rows[row.get("Id")] = row
    nutrition = [int(rows[item].get("NutritionBenefit")) for item in items]
    poisons = sorted((guid, row.get("BuffDefinitionId")) for guid, row in rows.items() if row.tag == "Poison" and row.get("BuffDefinitionId"))
    return nutrition, poisons


def collect(entities):
    by_id = {e.get("EntityId"): e for e in entities if e.get("EntityId")}
    by_guid = {e.get("EntityGuid"): e for e in entities if e.get("EntityGuid")}
    rows = []
    for e in entities:
        if e.get("EntityClass") != "FireplaceSmartObject":
            continue
        links = {}
        for link in e.findall("EntityLinks/Link"):
            target = by_guid.get(link.get("TargetGuid"))
            if target is None:
                target = by_id.get(link.get("TargetId"))
            if target is not None:
                links[link.get("Name")] = target
        trigger = links.get("kettleTrigger['kettle']")
        cauldron = links.get("proceduralObject['cauldron']")
        # so_fireplace.xml switches both with the fire: phase 1 out, 2 burning.
        fire = links.get("proceduralObject['fire']")
        steam = links.get("proceduralObject['steam']")
        named_links = {link.get("Name") for link in e.findall("EntityLinks/Link")}
        if "kettleTrigger['kettle']" not in named_links and "proceduralObject['cauldron']" not in named_links:
            # Some quest campfires have only fire and steam, with no pot.
            continue
        if trigger is None or cauldron is None or fire is None or steam is None:
            raise ValueError(f"Unresolved pot links: {e.get('EntityGuid')}")
        if trigger.get("EntityClass") != "KettleActionTrigger":
            raise ValueError("Pot has a non-kettle eating trigger")
        props = e.find("Properties/Fireplace")
        food = props.get("esFireplaceCauldronType", "goulash") if props is not None else "goulash"
        full = props.get("bFullOnInit", "1") if props is not None else "1"
        if food not in FOODS:
            raise ValueError(f"Unknown food {food}")
        misc = e.find("Properties/Script")
        home = misc is not None and "isHomeFireplace:true" in misc.get("Misc", "").replace(" ", "")
        rows.append((entity_guid(e.get("EntityGuid")), entity_guid(trigger.get("EntityGuid")), entity_guid(cauldron.get("EntityGuid")), tuple(float(x) for x in trigger.get("Pos").split(",")), food, home, full not in ("0", "false"), entity_guid(fire.get("EntityGuid")), entity_guid(steam.get("EntityGuid"))))
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game", default=DEFAULT_GAME)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "code/shared/generated/cook_pot_catalog.cpp")
    args = parser.parse_args()
    with zipfile.ZipFile(Path(args.game) / "Data/Scripts.pak") as archive:
        items = food_items(archive.read("Scripts/Entities/WH/Fireplace/FireplaceSmartObject.lua").decode("utf-8"))
    lines = ['// Generated by tools/generate_cook_pot_catalog.py. Do not edit.', '#include "shared/game/cook_pot_catalog.h"', '', 'namespace KCDC::Shared::Game {', '    const CookPotItemClass g_CookPotFoodItemClasses[3] = {']
    for food, item in zip(FOODS, items):
        hi, lo = item_class_halves(item)
        lines.append(f'        {{0x{hi:016X}ULL, 0x{lo:016X}ULL}}, // {food} {item}')
    lines += ['    };', '']
    with zipfile.ZipFile(Path(args.game) / "Data/Tables.pak") as archive:
        nutrition, poisons = pot_consumables(archive, items)
    lines += ['    const std::uint16_t g_CookPotNutrition[3] = {' + ', '.join(map(str, nutrition)) + '};', '', '    namespace {',
              '        // Constant arrays rather than std::vector initializer lists: at this',
              '        // size those compile into per-element dynamic initialisation.',
              '        constexpr CookPotPoison kPoisons[] = {']
    for item, buff in poisons:
        hi, lo = item_class_halves(buff)
        lines.append(f'            {{"{item}", {{0x{hi:016X}ULL, 0x{lo:016X}ULL}}}},')
    lines += ['        };', '', '        constexpr CookPotPlacement kPlacements[] = {']
    for level in ("klaster", "kutnohorsko", "trosecko"):
        unique = {}
        with zipfile.ZipFile(Path(args.game) / "Data/Levels" / level / "level.pak") as archive:
            for member in archive.namelist():
                if not member.lower().endswith(".xml"):
                    continue
                blob = zread(archive, member)
                if b'"FireplaceSmartObject"' not in blob:
                    continue
                for row in collect(list(ET.fromstring(blob).iter("Entity"))):
                    if row[0] in unique and unique[row[0]] != row:
                        raise ValueError(f"Conflicting pot {row[0]:016x}")
                    unique[row[0]] = row
        print(f"{level}: {len(unique)} pots")
        for guid, trigger, cauldron, pos, food, home, full, fire, steam in sorted(unique.values()):
            xyz = ", ".join(f"{x:.6f}F" for x in pos)
            lines.append(f'            {{"{escape(level)}", 0x{guid:016X}ULL, 0x{trigger:016X}ULL, 0x{cauldron:016X}ULL, {{{xyz}}}, CookPotFood::{food.capitalize()}, {str(home).lower()}, {str(full).lower()}, 0x{fire:016X}ULL, 0x{steam:016X}ULL}},')
    lines += ['        };', '    } // namespace', '', '    const std::span<const CookPotPoison> g_CookPotPoisons = kPoisons;', '    const std::span<const CookPotPlacement> g_CookPotPlacements = kPlacements;', '} // namespace KCDC::Shared::Game', '']
    args.output.write_bytes("\n".join(lines).encode("utf8"))


if __name__ == "__main__":
    main()
