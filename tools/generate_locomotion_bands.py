#!/usr/bin/env python3
"""Compile the travel-speed range each player locomotion blendspace covers.

A locomotion blendspace only animates the MoveSpeed range its `Dimensions`
state: CAnimatedCharacter feeds it the body's requested travel speed
(`eMotionParamID_TravelSpeed`), and a speed outside the range is played at
the range's edge while the body moves on regardless. The combined
blendspaces the player databases play (`*.comb`) blend a strafe and a turn
blendspace; both have to cover a speed for it to be animated, so a
combination's band is the intersection of its members'.
"""

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile

LOCOMOTION = "Animations/humans/{}/blendSpace/locomotion/{}"

# (female, gait, source). The male player's relaxed sets are the `_player`
# combinations; the female body has no `_player` variants, and its sprint is
# the one blendspace wh_female_database.adb plays under the `sprint` tag.
# Stealth is the crouched set (kcd_male_database.adb: stealth+walk+player and
# stealth+run+player); there is no female stealth locomotion to read.
SOURCES = (
    (False, "Walk", LOCOMOTION.format("male", "3d_relaxed_walk_turn_strafe_player.comb")),
    (False, "Run", LOCOMOTION.format("male", "3d_relaxed_run_turn_strafe_player.comb")),
    (False, "Sprint", LOCOMOTION.format("male", "3d_relaxed_sprint_turn_strafe.comb")),
    (False, "StealthWalk", LOCOMOTION.format("male", "2d_stealth_walk_strafe_spd_fwd_player.bspace")),
    (False, "StealthRun", LOCOMOTION.format("male", "2d_stealth_run_strafe_spd_fwd_player.bspace")),
    (True, "Walk", LOCOMOTION.format("female", "3d_relaxed_walk_turn_strafe.comb")),
    (True, "Run", LOCOMOTION.format("female", "3d_relaxed_run_turn_strafe.comb")),
    (True, "Sprint", LOCOMOTION.format("female", "2d_sprint_turn.bspace")),
)


def read(pak, names, path):
    name = names.get(path.lower())
    if name is None:
        raise ValueError(f"Animations.pak has no {path}")
    return ET.fromstring(pak.read(name))


def attribute(element, key):
    for name, value in element.attrib.items():
        if name.lower() == key:
            return value
    return None


def move_speed(pak, names, path):
    for param in read(pak, names, path).iter():
        if param.tag.lower() == "param" and (attribute(param, "name") or "").lower() == "movespeed":
            low, high = attribute(param, "min"), attribute(param, "max")
            if low is None or high is None:
                break
            low, high = float(low), float(high)
            if not 0.0 <= low < high:
                raise ValueError(f"{path}: invalid MoveSpeed range {low}..{high}")
            return low, high
    raise ValueError(f"{path} states no MoveSpeed range")


def band(pak, names, path):
    if not path.lower().endswith(".comb"):
        return move_speed(pak, names, path)
    members = [attribute(element, "aname") for element in read(pak, names, path).iter() if element.tag.lower() == "blendspace"]
    if not members or any(member is None for member in members):
        raise ValueError(f"{path} names no blendspaces")
    ranges = [move_speed(pak, names, member) for member in members]
    low, high = max(r[0] for r in ranges), min(r[1] for r in ranges)
    if not low < high:
        raise ValueError(f"{path}: its blendspaces share no MoveSpeed range")
    return low, high


def generate(game):
    rows = []
    with zipfile.ZipFile(game / "Data/Animations.pak") as pak:
        names = {name.lower(): name for name in pak.namelist()}
        for female, gait, path in SOURCES:
            low, high = band(pak, names, path)
            rows.append(f'        {{{"true" if female else "false"}, LocomotionGait::{gait}, "{Path(path).name}", {low:.6f}F, {high:.6f}F}},')
    target = Path(__file__).resolve().parents[1] / "code/shared/generated/locomotion_bands.cpp"
    target.write_text("\n".join([
        "// Generated by tools/generate_locomotion_bands.py from Animations.pak; do not edit.",
        '#include "shared/game/locomotion_bands.h"', "",
        "namespace KCDC::Shared::Game {",
        "    const std::vector<LocomotionBand> g_LocomotionBands = {",
        *rows,
        "    };",
        "} // namespace KCDC::Shared::Game", "",
    ]), encoding="utf-8", newline="\n")
    print(target)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("game", type=Path, help="the KingdomComeDeliverance2 install directory")
    generate(parser.parse_args().game)
