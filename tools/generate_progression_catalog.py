#!/usr/bin/env python3
"""Generate the KCDC progression tables from an installed Kingdom Come: Deliverance II.

A player's progression is three tables the game keeps in
`Libs/Tables/rpg/`: the skills (`skill.xml`), the stats (`stat.xml`) and the
perks (`perk*.xml`), plus the curve every level of them is bought along
(`rpg_param.xml` over the defaults `InitRPGParamDefaults1810BC164` writes).
The server has no game module to read any of it from, and both peers must
agree on which catalog index names which perk, so the tables are generated
offline and compiled in as `code/shared/generated/progression_catalog.cpp`.

Tracks are the 15 skills `skill.xml` does not hide and the 5 stats
`stat.xml` lists, skills first, each in native id order. The track index is
what the wire carries; the native id is what the engine takes.

Perks are every row of the six perk tables, sorted by name. The index is what
the wire carries, so a change in the game's tables is a protocol change like
any other, and both targets have to be regenerated together.

Usage:
    python tools/generate_progression_catalog.py <game directory>
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import xml.etree.ElementTree as ET
import zipfile

TABLES_PAK = os.path.join("Data", "Tables.pak")
PERK_TABLE_RE = re.compile(r"^Libs/Tables/rpg/perk(__[a-zA-Z0-9_]+)?\.xml$", re.IGNORECASE)
RPG = "Libs/Tables/rpg/"

DEFAULT_OUTPUT = os.path.join("code", "shared", "generated", "progression_catalog.cpp")

GUID_RE = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$")

# The same byte order `tools/generate_buff_catalog.py` and
# `code/shared/game/cry_guid_text.h` use; `progression_catalog.h` pins it.
GUID_BYTE_DIGITS = (6, 4, 2, 0, 11, 9, 16, 14, 19, 21, 24, 26, 28, 30, 32, 34)

# E_SoulSkill and E_SoulStat "none" sentinels, as `S_Perk` stores them.
SKILL_NONE = 35
STAT_NONE = 10

# `InitRPGParamDefaults1810BC164` writes every curve pair as 20/30 (Q7 2560 and
# 3840) and both caps as 30; `rpg_param.xml` then overrides some of them by key.
# The stat pairs sit at RPGParams +0x108..+0x134, selected per stat by
# `GetStatXPLevelParams180469CA0`: agility, strength, vitality, speech, (8),
# prestige.
DEFAULT_XP_BASE = 20
DEFAULT_XP_DIFF = 30
DEFAULT_CAP = 30
STAT_PARAM_PREFIX = {0: "Strength", 1: "Agility", 2: "Vitality", 3: "Speech", 9: "Prestige"}

# Side tables that decide what a perk becomes when it is applied, in the order
# `PerkKind` in progression_catalog.h numbers its bits.
KIND_TABLES = (
    ("perk_buff", "Buff"),
    ("perk_script", "Script"),
    ("perk_combat_technique", "Technique"),
    ("perk_soul_ability", "Ability"),
    ("perk_rpg_param_override", "Param"),
    ("perk_companion", "Companion"),
    ("perk_recipe", "Recipe"),
    ("perk_codex", "Codex"),
)

HEADER = """// Generated by tools/generate_progression_catalog.py from Data/Tables.pak.
// Do not edit by hand.

#include "shared/game/progression_catalog.h"

namespace KCDC::Shared::Game {{
    namespace {{
        // Constant arrays rather than std::vector initializer lists: those
        // compile into per-element dynamic initialisation.

        // {skills} skills and {stats} stats: the tracks a player's own tables
        // show, skills first, each in native id order.
        constexpr ProgressionTrack kTracks[] = {{
"""

PERKS_HEAD = """        }};

        // {count} perks across {files} of the game's perk tables, sorted by name.
        // The index is the wire's name for a perk.
        constexpr PerkEntry kPerks[] = {{
"""

EXCLUSIVITY_HEAD = """        };

        // perk2perk_exclusivity.xml: pairs of which a soul may own one.
        constexpr PerkExclusivity kExclusivity[] = {
"""

FOOTER = """        };
    } // namespace

    const std::span<const ProgressionTrack> g_ProgressionTracks = kTracks;
    const std::span<const PerkEntry> g_Perks = kPerks;
    const std::span<const PerkExclusivity> g_PerkExclusivity = kExclusivity;
} // namespace KCDC::Shared::Game
"""


def guid_halves(guid):
    halves = [0, 0]
    for index, digit in enumerate(GUID_BYTE_DIGITS):
        halves[index // 8] |= int(guid[digit : digit + 2], 16) << ((index % 8) * 8)
    return halves[0], halves[1]


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def rows(pak, path, tag):
    return list(ET.fromstring(pak.read(path)).iter(tag))


def read_params(pak):
    params = {}
    for row in rows(pak, RPG + "rpg_param.xml", "rpg_param"):
        params[row.get("rpg_param_key")] = row.get("rpg_param_value")
    return params


def param_int(params, key, default):
    value = params.get(key)
    return int(round(float(value))) if value is not None else default


def read_tracks(pak, params):
    skill_base = param_int(params, "SkillXPLevelBase", DEFAULT_XP_BASE)
    skill_diff = param_int(params, "SkillXPLevelDiff", DEFAULT_XP_DIFF)
    skill_cap = param_int(params, "SkillCap", DEFAULT_CAP)
    stat_cap = param_int(params, "StatCap", DEFAULT_CAP)

    tracks = []
    for row in sorted(rows(pak, RPG + "skill.xml", "skill"), key=lambda r: int(r.get("skill_id"))):
        if row.get("hidden", "false").lower() == "true":
            continue
        tracks.append(
            {
                "name": row.get("skill_name"),
                "kind": "Skill",
                "native": int(row.get("skill_id")),
                "base": skill_base,
                "diff": skill_diff,
                "cap": skill_cap,
                "ui": row.get("ui_string_name", ""),
            }
        )
    for row in sorted(rows(pak, RPG + "stat.xml", "stat"), key=lambda r: int(r.get("stat_id"))):
        native = int(row.get("stat_id"))
        prefix = STAT_PARAM_PREFIX.get(native, "")
        tracks.append(
            {
                "name": row.get("stat_name"),
                "kind": "Stat",
                "native": native,
                "base": param_int(params, prefix + "XPLevelBase", DEFAULT_XP_BASE),
                "diff": param_int(params, prefix + "XPLevelDiff", DEFAULT_XP_DIFF),
                "cap": stat_cap,
                "ui": row.get("ui_string_name", ""),
            }
        )
    return tracks


def read_perks(pak):
    files = sorted(name for name in pak.namelist() if PERK_TABLE_RE.match(name))
    perks = {}
    for path in files:
        for row in rows(pak, path, "perk"):
            guid = row.get("perk_id", "").lower()
            if not GUID_RE.match(guid):
                print("Skipping a perk with a malformed id in {}".format(path), file=sys.stderr)
                continue
            perks[guid] = row

    kinds = {guid: 0 for guid in perks}
    for bit, (table, _) in enumerate(KIND_TABLES):
        for row in rows(pak, RPG + table + ".xml", table):
            guid = (row.get("perk_id") or "").lower()
            if guid in kinds:
                kinds[guid] |= 1 << bit
    return files, perks, kinds


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("game", help="Kingdom Come: Deliverance II install directory")
    parser.add_argument("--output", default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    with zipfile.ZipFile(os.path.join(args.game, TABLES_PAK)) as pak:
        params = read_params(pak)
        tracks = read_tracks(pak, params)
        files, perks, kinds = read_perks(pak)
        exclusivity = [(r.get("first_perk_id").lower(), r.get("second_perk_id").lower()) for r in rows(pak, RPG + "perk2perk_exclusivity.xml", "perk2perk_exclusivity")]

    track_of_skill = {t["native"]: i for i, t in enumerate(tracks) if t["kind"] == "Skill"}
    track_of_stat = {t["native"]: i for i, t in enumerate(tracks) if t["kind"] == "Stat"}

    ordered = sorted(perks.items(), key=lambda item: item[1].get("perk_name").lower())
    index_of = {guid: index for index, (guid, _) in enumerate(ordered)}

    out = []
    out.append(HEADER.format(skills=sum(t["kind"] == "Skill" for t in tracks), stats=sum(t["kind"] == "Stat" for t in tracks)))
    for track in tracks:
        out.append(
            '            {{"{}", ProgressionTrackKind::{}, {}, {}, {}, {}, "{}"}},\n'.format(escape(track["name"]), track["kind"], track["native"], track["base"], track["diff"], track["cap"], escape(track["ui"]))
        )

    out.append(PERKS_HEAD.format(count=len(ordered), files=len(files)))
    for guid, row in ordered:
        low, high = guid_halves(guid)
        stat = int(row.get("stat_selector", STAT_NONE))
        skill = int(row.get("skill_selector", SKILL_NONE))
        if stat != STAT_NONE:
            tree = track_of_stat.get(stat, -1)
        elif skill != SKILL_NONE:
            tree = track_of_skill.get(skill, -1)
        else:
            tree = -2  # the main-level tree
        parent = (row.get("parent_id") or "").lower()
        parent_index = index_of.get(parent, -1)
        out.append(
            '            {{"{}", "{}", {{0x{:016X}ULL, 0x{:016X}ULL}}, "{}", {}, {}, {}, {}, {}, {}, 0x{:02X}, {}}},\n'.format(
                escape(row.get("perk_name")),
                guid,
                low,
                high,
                escape(row.get("perk_ui_name", "")),
                parent_index,
                tree,
                stat,
                skill,
                int(row.get("level", "0")),
                int(row.get("visibility", "0")),
                kinds[guid],
                "true" if row.get("autolearnable", "false").lower() == "true" else "false",
            )
        )

    out.append(EXCLUSIVITY_HEAD)
    for first, second in exclusivity:
        if first in index_of and second in index_of:
            out.append("            {{{}, {}}},\n".format(index_of[first], index_of[second]))
    out.append(FOOTER)

    with open(args.output, "w", newline="\n", encoding="utf-8") as handle:
        handle.write("".join(out))
    print("Wrote {} tracks and {} perks to {}".format(len(tracks), len(ordered), args.output))


if __name__ == "__main__":
    main()
