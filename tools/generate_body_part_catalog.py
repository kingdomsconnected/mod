#!/usr/bin/env python3
"""Generate the KCDC body-part tables from an installed Kingdom Come: Deliverance II.

Three tables decide where a blow lands and what it does there:

- `Libs/Tables/item/body_part.xml` -- every limb of every race, and the
  injury buff hitting it applies (`injury_buff_id`).
- `Libs/Tables/item/body_subpart.xml` -- the finer zones a hit resolves to.
  The hit calculation writes a *subpart* id into the damage effect
  (`C_HealthValueEffect +0x30`, stored at WHGame.dll 0x180C64131), so this is
  the step from what the engine reports to a limb.
- `Libs/Tables/rpg/rpg_context_tag.xml` -- the game's own camelCase spelling
  of the six human limbs (`leftArm`, `rightLeg`, ...), the rows whose
  `rpg_context_type_id` is 3 (`injuredBodyPart`). The scripting API names
  limbs with these.

Emitted offline as `code/shared/generated/body_part_catalog.cpp` because the server
has no game module to read the tables from.

Usage:
    python tools/generate_body_part_catalog.py <game directory>
"""

from __future__ import annotations

import argparse
import os
import sys
import xml.etree.ElementTree as ET
import zipfile

# The same GUID-to-halves encoding the buff catalog uses, so a limb's injury
# compares directly against the id a buff report carries.
from generate_buff_catalog import guid_halves

TABLES_PAK = os.path.join("Data", "Tables.pak")
BODY_PART_TABLE = "Libs/Tables/item/body_part.xml"
BODY_SUBPART_TABLE = "Libs/Tables/item/body_subpart.xml"
CONTEXT_TAG_TABLE = "Libs/Tables/rpg/rpg_context_tag.xml"

# `rpg_context_type.xml`: 3 is `injuredBodyPart`.
INJURED_BODY_PART_CONTEXT = 3

DEFAULT_OUTPUT = os.path.join("code", "shared", "generated", "body_part_catalog.cpp")


def read_table(pak, path, row_tag):
    root = ET.fromstring(pak.read(path).decode("utf-8-sig"))
    return list(root.iter(row_tag))


def read_rows(game_dir):
    with zipfile.ZipFile(os.path.join(game_dir, TABLES_PAK)) as pak:
        parts = read_table(pak, BODY_PART_TABLE, "body_part")
        subparts = read_table(pak, BODY_SUBPART_TABLE, "body_subpart")
        tags = read_table(pak, CONTEXT_TAG_TABLE, "rpg_context_tag")

    script_names = {}
    for tag in tags:
        if int(tag.get("rpg_context_type_id", "-1")) == INJURED_BODY_PART_CONTEXT and tag.get("rpg_context_body_part_id"):
            script_names[int(tag.get("rpg_context_body_part_id"))] = tag.get("rpg_context_name")

    part_rows = []
    for part in parts:
        part_id = int(part.get("body_part_id"))
        part_rows.append(
            {
                "id": part_id,
                "name": part.get("body_part_name"),
                "script_name": script_names.get(part_id, ""),
                "injury_buff": part.get("injury_buff_id", "").lower(),
                "race": int(part.get("race_id", "0")),
            }
        )
    part_rows.sort(key=lambda row: row["id"])

    subpart_rows = [
        {
            "id": int(subpart.get("body_subpart_id")),
            "part": int(subpart.get("body_part_id")),
            "name": subpart.get("body_subpart_name"),
        }
        for subpart in subparts
    ]
    subpart_rows.sort(key=lambda row: row["id"])

    return part_rows, subpart_rows, script_names


def cpp_string(value):
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return '"%s"' % escaped


def cpp_buff_id(guid):
    low, high = guid_halves(guid) if guid else (0, 0)
    return "{0x%016XULL, 0x%016XULL}" % (low, high)


def render(part_rows, subpart_rows):
    lines = [
        "// Generated by tools/generate_body_part_catalog.py from Data/Tables.pak.",
        "// Do not edit by hand.",
        "",
        '#include "shared/game/body_part_catalog.h"',
        "",
        "namespace KCDC::Shared::Game {",
        "    // Libs/Tables/item/body_part.xml, sorted by id. Script names from",
        "    // Libs/Tables/rpg/rpg_context_tag.xml (injuredBodyPart rows).",
        "    const std::vector<BodyPartEntry> g_BodyParts = {",
    ]
    for row in part_rows:
        lines.append(
            "        {%s, %s, %s, %d, %d},"
            % (cpp_string(row["name"]), cpp_string(row["script_name"]), cpp_buff_id(row["injury_buff"]), row["id"], row["race"])
        )
    lines += [
        "    };",
        "",
        "    // Libs/Tables/item/body_subpart.xml, sorted by id.",
        "    const std::vector<BodySubpartEntry> g_BodySubparts = {",
    ]
    for row in subpart_rows:
        lines.append("        {%s, %d, %d}," % (cpp_string(row["name"]), row["id"], row["part"]))
    lines += [
        "    };",
        "} // namespace KCDC::Shared::Game",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("game_dir", help="Kingdom Come: Deliverance II installation directory")
    parser.add_argument("-o", "--output", default=DEFAULT_OUTPUT, help="where to write the generated table")
    args = parser.parse_args()

    part_rows, subpart_rows, script_names = read_rows(args.game_dir)
    if not part_rows or not subpart_rows:
        print("error: the body-part tables carried no rows", file=sys.stderr)
        return 1

    # The scripting API promises exactly these six; a patch that renames or
    # drops one has to be noticed here, not by a resource.
    expected = {1: "head", 2: "torso", 3: "leftArm", 4: "rightArm", 5: "leftLeg", 6: "rightLeg"}
    if script_names != expected:
        print("error: %s no longer names the six human limbs as expected: %s" % (CONTEXT_TAG_TABLE, script_names), file=sys.stderr)
        return 1

    if any(row["id"] > 255 for row in part_rows + subpart_rows):
        print("error: a body-part id no longer fits the catalog's byte", file=sys.stderr)
        return 1

    with open(args.output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(part_rows, subpart_rows))

    print("Wrote %d body parts and %d subparts to %s" % (len(part_rows), len(subpart_rows), args.output))
    return 0


if __name__ == "__main__":
    sys.exit(main())
