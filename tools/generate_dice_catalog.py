#!/usr/bin/env python3
"""Extract dice tables and their sitting smart objects from the level paks."""

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile

from generate_gate_catalog import DEFAULT_GAME, entity_guid, zread


def world_position(entity, by_id):
    position = tuple(float(value) for value in entity.get("Pos", "0,0,0").split(","))
    visited = set()
    while entity.get("ParentId"):
        parent_id = entity.get("ParentId")
        if parent_id in visited:
            raise ValueError("Cyclic entity parent chain")
        visited.add(parent_id)
        entity = by_id[parent_id]
        scale = tuple(float(value) for value in entity.get("Scale", "1,1,1").split(","))
        x, y, z = (value * factor for value, factor in zip(position, scale))
        w, qx, qy, qz = (float(value) for value in entity.get("Rotate", "1,0,0,0").split(","))
        tx, ty, tz = 2 * (qy * z - qz * y), 2 * (qz * x - qx * z), 2 * (qx * y - qy * x)
        rotated = (x + w * tx + qy * tz - qz * ty, y + w * ty + qz * tx - qx * tz, z + w * tz + qx * ty - qy * tx)
        translation = (float(value) for value in entity.get("Pos", "0,0,0").split(","))
        position = tuple(a + b for a, b in zip(rotated, translation))
    return position


def tables_in_level(archive):
    tables = {}
    for member in archive.namelist():
        if not member.lower().endswith(".xml"):
            continue
        blob = zread(archive, member)
        if b'dice_cup' not in blob:
            continue
        entities = list(ET.fromstring(blob).iter("Entity"))
        by_guid = {entity.get("EntityGuid"): entity for entity in entities if entity.get("EntityGuid")}
        by_id = {entity.get("EntityId"): entity for entity in entities if entity.get("EntityId")}
        for entity in entities:
            links = {link.get("Name"): link.get("TargetGuid") for link in entity.findall("EntityLinks/Link")}
            if not all(name in links for name in ("seat1", "seat2", "dice_cup", "seat1_SO", "seat2_SO")):
                continue
            # seat1/seat2 are alignment tagpoints. BodyStanceState publishes
            # the sitting smart object's GUID, named by seat1_SO/seat2_SO.
            if entity.get("ParentId"):
                raise ValueError("A parented dice table needs its world transform resolved")
            guid = entity_guid(entity.get("EntityGuid"))
            seats = [entity_guid(links[name]) for name in ("seat1_SO", "seat2_SO")]
            # The behavior marker can sit behind the table. Interaction uses
            # the centre between its two alignment points, at sitting height.
            alignment = [by_guid[links[name]] for name in ("seat1", "seat2")]
            positions = [world_position(seat, by_id) for seat in alignment]
            position = tuple((a + b) / 2 for a, b in zip(*positions))
            marker = tuple(float(value) for value in entity.get("Pos").split(","))
            if sum((a - b) ** 2 for a, b in zip(marker, position)) > 9:
                raise ValueError("Dice marker is outside the three-metre station lookup")
            if not guid or not all(seats) or len(set(seats)) != 2 or len(position) != 3:
                raise ValueError("Invalid dice table: " + ET.tostring(entity).decode())
            if guid in tables:
                raise ValueError(f"Duplicate dice table {guid:016x}")
            tables[guid] = (*seats, position)
    return sorted(tables.items())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game", default=DEFAULT_GAME)
    arguments = parser.parse_args()
    rows = []
    for pak in sorted((Path(arguments.game) / "Data" / "Levels").glob("*/level.pak")):
        with zipfile.ZipFile(pak) as archive:
            tables = tables_in_level(archive)
        print(f"{pak.parent.name}: {len(tables)} dice tables")
        for guid, (first, second, position) in tables:
            coordinates = ", ".join(f"{value:.6f}F" for value in position)
            rows.append(f'        {{"{pak.parent.name}", 0x{guid:016x}ULL, 0x{first:016x}ULL, 0x{second:016x}ULL, {coordinates}}},')
    if not rows:
        raise ValueError("No dice tables found")
    output = Path(__file__).resolve().parents[1] / "code/shared/generated/dice_catalog.cpp"
    output.write_text('// Generated by tools/generate_dice_catalog.py; do not edit.\n#include "shared/game/dice_catalog.h"\n\nnamespace KCDC::Shared::Game {\n    const std::vector<DiceTable> g_DiceTables {\n' + "\n".join(rows) + '\n    };\n} // namespace KCDC::Shared::Game\n', encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
