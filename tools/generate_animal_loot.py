#!/usr/bin/env python3
"""Compile animal loot presets and their soul identities from KCD2 tables.

Class-to-preset associations come from Storm's animals.xml, including WildDog
and the named white-deer exception. Preset references are expanded recursively;
unsupported modes, missing classes, ambiguous associations and cycles fail the
generation. AmountFraction's authored parameters remain in the compiled table.
"""
import argparse
import math
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path
from zipfile import ZipFile


def generate(game_dir):
    with ZipFile(game_dir / 'Data/Tables.pak') as tables, ZipFile(game_dir / 'Data/IPL_GameData.pak') as storm:
        items = {}
        for name in sorted(tables.namelist()):
            if re.fullmatch(r'Libs/Tables/item/item(?:__[\w]+)?\.xml', name, re.I):
                root = ET.fromstring(tables.read(name))
                for row in root.findall('.//ItemClasses/*'):
                    items.setdefault(row.attrib['Name'], (row.attrib['Id'].lower(), row.tag == 'Food', 'harvester' in row.get('Tags', '').split()))
        presets = {}
        for path in ('Libs/Tables/item/InventoryPreset__animals.xml', 'Libs/Tables/item/InventoryPreset__system.xml'):
            for row in ET.fromstring(tables.read(path)).findall('.//InventoryPreset'):
                if row.attrib['Name'] in presets:
                    raise ValueError('duplicate inventory preset')
                presets[row.attrib['Name']] = row
        def expand(name, path=(), fraction=1.0, variation=0.0):
            if name in path:
                raise ValueError(f'cyclic animal preset: {path + (name,)}')
            row = presets[name]
            mode = row.get('Mode', 'All')
            if mode == 'AmountFraction':
                if len(row) != 1 or row[0].tag != 'PresetItem':
                    raise ValueError('fractional animal preset must have one item')
                if fraction != 1.0 or variation != 0.0:
                    raise ValueError('nested AmountFraction requires native evaluation')
                fraction, variation = float(row.attrib['ModeValue']), float(row.get('ModeValueVariation', '0'))
                if not math.isfinite(fraction) or not math.isfinite(variation) or fraction < 0 or variation < 0:
                    raise ValueError(f'invalid animal quantity fraction: {name}')
            elif mode == 'OneChild' and len(row) == 1:
                pass
            elif mode != 'All':
                raise ValueError(f'unsupported animal preset mode: {mode}')
            result = []
            for child in row:
                if child.tag == 'PresetItem':
                    guid, food, harvester = items[child.attrib['Name']]
                    amount = int(child.attrib['Amount'])
                    if not 0 < amount <= 1000000:
                        raise ValueError(f'invalid animal quantity: {name}')
                    result.append((guid, amount, fraction, variation, food, harvester))
                elif child.tag == 'InventoryPresetRef':
                    result.extend(expand(child.attrib['Name'], path + (name,), fraction, variation))
                else:
                    raise ValueError(f'unsupported animal preset element: {child.tag}')
            return result

        associations = {}
        excluded = set()
        for rule in ET.fromstring(storm.read('Libs/Storm/equipment/world/animals.xml')).findall('.//rule'):
            preset = rule.find('operations/setLootInventory').attrib['preset']
            for selector in rule.findall('.//hasSoulArchetype'):
                actor_class = selector.attrib['name']
                if actor_class in associations:
                    raise ValueError(f'ambiguous animal class: {actor_class}')
                associations[actor_class] = expand(preset)
            for selector in rule.findall('selectors/not/hasName'):
                excluded.add(selector.get('Name', selector.get('name')))
        archetypes = {row.attrib['soul_archetype_id']: row.attrib['soul_archetype_name'] for row in ET.fromstring(tables.read('Libs/Tables/rpg/soul_archetype.xml')).findall('.//soul_archetype')}
        souls = {}
        for name in sorted(tables.namelist()):
            if re.fullmatch(r'Libs/Tables/rpg/soul(?:__[\w]+)?\.xml', name):
                # Some shipped rows contain unescaped ampersands in comments.
                raw = tables.read(name).decode('utf-8')
                raw = re.sub(r'&(?!#?\w+;)', '&amp;', raw)
                for row in ET.fromstring(raw).findall('.//soul'):
                    actor_class = archetypes.get(row.get('soul_archetype_id'))
                    if actor_class in associations:
                        souls[row.attrib['soul_id'].lower()] = (actor_class, row.get('soul_name') not in excluded, row.attrib['soul_name'])

    out = ['// Generated by tools/generate_animal_loot.py; do not edit.', '#include "shared/game/animal_loot.h"', '', '#include <algorithm>', '', 'namespace KCDC::Shared::Game {', '    const std::vector<AnimalLootDefinition> g_AnimalLoot = {']
    for name, rows in sorted(associations.items()):
        ingredients = ', '.join(f'{{"{guid}", {amount}U, {fraction:.1f}F, {variation:.1f}F, {str(food).lower()}, {str(harvester).lower()}}}' for guid, amount, fraction, variation, food, harvester in rows)
        line = f'        {{"{name}", {{{ingredients}}}}},'
        if len(line) <= 280:
            out.append(line)
        else:
            out += [f'        {{"{name}",', '         {']
            for ingredient in rows:
                guid, amount, fraction, variation, food, harvester = ingredient
                out.append(f'             {{"{guid}", {amount}U, {fraction:.1f}F, {variation:.1f}F, {str(food).lower()}, {str(harvester).lower()}}},')
            out.append('         }},')
    out += ['    };', '    const std::vector<AnimalSoulDefinition> g_AnimalSouls = {']
    for guid, (name, lootable, soul_name) in sorted(souls.items()):
        out.append(f'        {{"{guid}", "{name}", {str(lootable).lower()}, {json.dumps(soul_name)}}},')
    out += ['    };', '', '    const AnimalLootDefinition *FindAnimalLoot(std::string_view actorClass) {', '        const auto found = std::find_if(g_AnimalLoot.begin(), g_AnimalLoot.end(), [actorClass](const auto &row) { return row.actorClass == actorClass; });', '        return found != g_AnimalLoot.end() ? &*found : nullptr;', '    }', '    const AnimalSoulDefinition *FindAnimalSoul(std::string_view soul) {', '        const auto found = std::lower_bound(g_AnimalSouls.begin(), g_AnimalSouls.end(), soul, [](const auto &row, std::string_view value) { return row.soul < value; });', '        return found != g_AnimalSouls.end() && found->soul == soul ? &*found : nullptr;', '    }', '''
    const AnimalSoulDefinition *FindAnimalSoulByName(std::string_view name) {
        const AnimalSoulDefinition *found = nullptr;
        for (const auto &row : g_AnimalSouls) {
            if (row.name != name)
                continue;
            if (found != nullptr && (row.actorClass != found->actorClass || row.lootable != found->lootable))
                return nullptr;
            found = &row;
        }
        return found;
    }
''', '} // namespace KCDC::Shared::Game', '']
    return '\n'.join(out)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('game_dir', type=Path)
    parser.add_argument('--output', type=Path, default=Path('code/shared/generated/animal_loot.cpp'))
    args = parser.parse_args()
    args.output.write_text(generate(args.game_dir), encoding='utf-8')
