#!/usr/bin/env python3
"""Compile verified character-rule constants and authored perk ability edges."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import uuid
import xml.etree.ElementTree as ET
import zipfile

# Character-rule defaults use native units.
DEFAULTS = {
    'SkillCap': 30, 'SkillXPLevelBase': 20, 'SkillXPLevelDiff': 30,
    'AlchemyXPOverride': 1, 'AlchemyXPPerFailedBrewing': 5,
    'AlchemyToleranceBase': .2, 'AlchemyToleranceMaxLevel': .7,
    'AlchemyRecipeStepsTolerance': 2, 'AlchemyTrialEndErrorPerkTolerance': 1,
    'AlchemyFreshHerbQuality': 1, 'AlchemyDryHerbQuality': .5,
    'AlchemyDecayedHerbQuality': .1, 'BundleAlchemistPerkAdd': 1,
    # BlackArts constructor1816A87B4 copies S_Constants E7C/E80.
    # Defaults1810BE430/1810BE43B; reflection180CF099B/180CF09D3.
    'BlackArtsApprenticeBuffStartTime': 0, 'BlackArtsApprenticeBuffEndTime': 4.5,
    # S_Constants ctor 1810BD398 (FinishingXP, fixed128 at +728) and
    # 1810BD3BB/1810BD3D3 (+734/+738); read by RPG slots 73 and 76.
    'BlacksmithingFinishingXP': 20, 'BlacksmithingMinCondition': .1, 'BlacksmithingMaxCondition': .8,
    # Survival XP per item a drying rack, smokehouse or fire converts:
    # S_Constants ctor 1810BC164 writes fixed128 0x780 to +3E8 and +3EC
    # (1810BCBF4/BFB) and 0x500 to +3E4 (1810BCC08); reflection
    # 180CE7583/75BB/754B; read by C_RPGInventory::PrepareItems 182CFC2AC
    # for Dry, Smoke and Cook.
    'SurvivalXpRewardPerDriedItem': 15, 'SurvivalXpRewardPerSmokedItem': 15, 'SurvivalXpRewardPerCookedItem': 10,
}


def extract(pak):
    parameters = dict(DEFAULTS)
    for row in ET.fromstring(pak.read('Libs/Tables/rpg/rpg_param.xml')).find('rpg_params'):
        key = row.attrib['rpg_param_key']
        if key in parameters:
            parameters[key] = float(row.attrib['rpg_param_value'])
    integer_names = {'SkillCap', 'AlchemyRecipeStepsTolerance', 'AlchemyTrialEndErrorPerkTolerance', 'BundleAlchemistPerkAdd'}
    for name, value in parameters.items():
        if not math.isfinite(value) or value < 0 or value > 1000000:
            raise ValueError(f'Invalid native parameter: {name}')
        if name in integer_names and int(value) != value:
            raise ValueError(f'Nonintegral native parameter: {name}')
        if name in {'AlchemyToleranceBase', 'AlchemyToleranceMaxLevel', 'BlacksmithingMinCondition', 'BlacksmithingMaxCondition'} and value > 1:
            raise ValueError(f'Native normalized parameter outside range: {name}')
    abilities = [(str(uuid.UUID(row.attrib['perk_id'])), int(row.attrib['soul_ability_id']))
                 for row in ET.fromstring(pak.read('Libs/Tables/rpg/perk_soul_ability.xml')).find('perk_soul_abilitys')]
    if len(set(abilities)) != len(abilities):
        raise ValueError('Duplicate perk ability edge')
    data = {'parameters': sorted(parameters.items()), 'abilities': sorted(abilities)}
    data['digest'] = hashlib.sha256(json.dumps(data, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    return data


def generate(data, output):
    lines = ['// Generated by tools/generate_soul_rule_catalog.py; do not edit.', '#include "shared/game/soul_rule_catalog.h"', '', 'namespace KCDC::Shared::Game {',
             '    const std::string_view g_SoulRuleCatalogHash = ' + json.dumps(data['digest']) + ';', '    const std::vector<SoulRuleParameter> g_SoulRuleParameters = {']
    for name, value in data['parameters']:
        lines.append('        {%s, %sF},' % (json.dumps(name), repr(float(value))))
    lines += ['    };', '    const std::vector<SoulPerkAbility> g_SoulPerkAbilities = {']
    for perk, ability in data['abilities']:
        lines.append('        {%s, %d},' % (json.dumps(perk), ability))
    lines += ['    };', '} // namespace KCDC::Shared::Game', '']
    Path(output).write_text('\n'.join(lines), encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('game_directory', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    with zipfile.ZipFile(args.game_directory / 'Data/Tables.pak') as pak:
        data = extract(pak)
    generate(data, args.output)
    print(data['digest'])


if __name__ == '__main__':
    main()
