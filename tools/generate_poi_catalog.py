#!/usr/bin/env python3
"""Generate the KCDC point-of-interest table from an installed Kingdom Come: Deliverance II.

A point of interest is somewhere worth teleporting to, in the world
coordinates of the level that contains it.

What the places are: `Libs/Tables/rpg/location.xml` names every location the
map can show and binds it to a `SmartAreaShape` by `Properties.guidLocationId`,
with the English name in `Localization/English_xml.pak`; and the settlement
districts of the levels' own `EditorLayer` paths -- `ttro_trosky/quarry`,
`ssed_sedlcko/monastery/church`. `eventPlace_*` districts are dropped: they are
the random-event spots out in the fields, and "Forest Edge" is not a place.

Where to stand is the densest cluster of ground markers -- entities whose
placement means "a person stands exactly here". Their origin is on the floor,
which an ordinary prop's is not; a percentile over every entity ran three to
thirteen metres out. A location's polygon covers its fields as well as its
houses, so its centroid is often a hundred metres out in a meadow, and the
same cluster fixes that too.

The height is then clamped into the walkable band the navmesh reports for the
cell, which is an independent source in the same coordinate space.
`Data/Levels/<level>/recast.pak` holds Detour tiles; each header starts with
the magic `DNAV` and carries its grid coordinates at `+0x08`/`+0x0C` and its
bounds -- `bmin` at `+0x54`, `bmax` at `+0x60` -- on a 16 m grid. `bmin.z` and
`bmax.z` are the walkable surface's extent rather than the agent volume, so a
cell with several entries is somewhere with more than one storey and the entry
nearest the marker height is the right one.

The table is compiled in as `code/shared/generated/poi_catalog.cpp`. See AGENTS.md --
nothing mined out of the game is read from a file at runtime.

Usage:
    python tools/generate_poi_catalog.py <game directory>
"""

from __future__ import annotations

import argparse
import os
import re
import statistics
import struct
import sys
import zipfile

# The pak name is the level name the engine reports for a loaded level, which
# is what the panel matches a point against.
LEVELS = ("trosecko", "kutnohorsko", "klaster")

LOCATION_TABLE = "Libs/Tables/rpg/location.xml"
LOCATION_TEXT = "text_ui_quest.xml"

ENTITY_RE = re.compile(r"<Entity ([^>]*?)(/?)>")
POS_RE = re.compile(r'Pos="([-\d.eE+]+),([-\d.eE+]+),([-\d.eE+]+)"')
LAYER_RE = re.compile(r'EditorLayer="([^"]*)"')
CLASS_RE = re.compile(r'EntityClass="([^"]*)"')
LOCATION_ID_RE = re.compile(r'guidLocationId="([0-9a-fA-F-]+)"')
AREA_POINT_RE = re.compile(r'<Point Pos="([-\d.eE+]+),([-\d.eE+]+),([-\d.eE+]+)"')
ROW_RE = re.compile(r"<Row><Cell>([^<]*)</Cell><Cell>[^<]*</Cell><Cell>([^<]*)</Cell></Row>")

# `ttro_trosky`, `kboh_bohounovice`, `ssed_sedlcko`: a settlement layer is a
# short area code, an underscore, and the settlement's own name.
SETTLEMENT_RE = re.compile(r"^([a-z]{3,5})_([A-Za-z0-9]+)$")

# Entities whose placement means "a person stands, sits or sleeps exactly
# here", so their origin is on the floor.
GROUND_MARKERS = frozenset(
    {
        "TagPoint",
        "TagPointWithScript",
        "SmartObjectHolder",
        "StanceSmartObject",
        "DetailMovementSmartObject",
        "SO_WaitingSpot",
        "FireplaceSmartObject",
        "NPC",
        "NPC_Female",
        "Horse",
        "Shop",
        "Stash",
        "Chair",
        "BedTrigger",
        "ActionTrigger",
        "InteractionTrigger",
        "AnimalSpawner",
        "Ladder",
    }
)

# `eventPlace_*` are the wilderness spots the random-event system picks from;
# the rest hold a settlement's own scenery, scripting or lighting, which its
# map location already covers.
DISTRICT_SKIP_PREFIXES = ("eventPlace_", "series_", "_")
DISTRICT_SKIP = ("_common", "_enviro", "_script", "_audio", "_navigation")

# Below the entity count the cluster centre is noise; above the span it is a
# quest layer that happens to be filed under a settlement.
DISTRICT_MIN_ENTITIES = 12
DISTRICT_MAX_SPAN = 260.0

CELL = 16.0  # the navmesh's own tile size, reused for the density grid
MARKER_RADII = (20.0, 45.0, 90.0)
NAV_MAGIC = b"DNAV"[::-1]  # stored little-endian, so the bytes read `VAND`
NAV_VERSION = 14

DEFAULT_OUTPUT = os.path.join("code", "shared", "generated", "poi_catalog.cpp")

HEADER = """// Generated by tools/generate_poi_catalog.py from Data/Levels/*/level.pak,
// Data/Levels/*/recast.pak, Data/Tables.pak and Localization/English_xml.pak.
// Do not edit by hand.

#include "shared/game/poi_catalog.h"

namespace KCDC::Shared::Game {{
    // {count} points of interest across {levels} levels and {groups} groups.
    const std::vector<PointOfInterest> g_PointsOfInterest = {{
"""

FOOTER = """    };
} // namespace KCDC::Shared::Game
"""


def read_pak(path: str, entry: str) -> str:
    with zipfile.ZipFile(path) as archive:
        return archive.read(entry).decode("utf-8", "replace")


def pretty(name: str) -> str:
    """`podseminskyMlyn` -> `Podseminsky Mlyn`, `loggingCamp2` -> `Logging Camp2`."""
    spaced = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", name).replace("_", " ")
    spaced = " ".join(spaced.split())
    return spaced[:1].upper() + spaced[1:]


def district_name(parts) -> str:
    """`('monastery', 'church')` -> `Monastery Church`, without repeating a word."""
    words: list[str] = []
    for part in parts:
        for word in pretty(part.removeprefix("poi_")).split():
            if not words or word.lower() != words[-1].lower():
                words.append(word)
    name = " ".join(words)
    return name[:1].upper() + name[1:]


def load_locations(game: str) -> dict[str, dict[str, str]]:
    text = read_pak(os.path.join(game, "Data", "Tables.pak"), LOCATION_TABLE)
    locations = {}
    for match in re.finditer(r"<location ([^>]*?)/>", text):
        attributes = dict(re.findall(r'(\w+)="([^"]*)"', match.group(1)))
        locations[attributes["location_id"]] = attributes
    return locations


def load_english(game: str) -> dict[str, str]:
    text = read_pak(os.path.join(game, "Localization", "English_xml.pak"), LOCATION_TEXT)
    return {key: value for key, value in ROW_RE.findall(text)}


def load_navmesh(game: str, level: str) -> dict[tuple[int, int], list[tuple[float, float]]]:
    """The walkable height bands of every 16 m cell, from every navmesh variant."""
    cells: dict[tuple[int, int], list[tuple[float, float]]] = {}
    with zipfile.ZipFile(os.path.join(game, "Data", "Levels", level, "recast.pak")) as archive:
        for name in archive.namelist():
            if not name.endswith(".nav"):
                continue
            data = archive.read(name)
            offset = data.find(NAV_MAGIC)
            while offset >= 0:
                version, tx, ty = struct.unpack_from("<3i", data, offset + 4)
                if version == NAV_VERSION and offset + 0x6C <= len(data):
                    bounds = struct.unpack_from("<6f", data, offset + 0x54)
                    # The magic can appear inside tile data, so a header only
                    # counts when its bounds agree with its tile index.
                    if abs(bounds[0] - tx * CELL) < 1.0 and abs(bounds[1] - ty * CELL) < 1.0:
                        band = (bounds[2], bounds[5])
                        if band not in cells.setdefault((tx, ty), []):
                            cells[(tx, ty)].append(band)
                offset = data.find(NAV_MAGIC, offset + 4)
    return cells


def snap_to_navmesh(cells, x: float, y: float, height: float) -> float:
    """The walkable band nearest `height`, with `height` clamped into it."""
    tx, ty = int(x // CELL), int(y // CELL)
    for reach in (0, 1, 2):
        bands = []
        for dx in range(-reach, reach + 1):
            for dy in range(-reach, reach + 1):
                bands += cells.get((tx + dx, ty + dy), [])
        if not bands:
            continue
        # By the band's edges rather than its middle: a marker sits on the
        # floor, which is where the right storey's band starts.
        low, high = min(bands, key=lambda b: min(abs(b[0] - height), abs(b[1] - height)))
        return min(max(height, low), high)
    return height


class Level:
    """One level's entities, indexed for the spatial queries below."""

    def __init__(self, game: str, name: str):
        self.name = name
        text = read_pak(os.path.join(game, "Data", "Levels", name, "level.pak"), "objects_mission0.xml")
        self.entities = []
        self.markers: dict[tuple[int, int], list[tuple[float, float, float]]] = {}

        for match in ENTITY_RE.finditer(text):
            head = match.group(1)
            if match.group(2) == "/":
                body = ""
            else:
                end = text.find("</Entity>", match.end())
                body = text[match.end() : end] if end >= 0 else ""

            found = POS_RE.search(head)
            if not found:
                continue
            position = (float(found.group(1)), float(found.group(2)), float(found.group(3)))
            layer = LAYER_RE.search(head)
            klass = CLASS_RE.search(head)
            self.entities.append((position, layer.group(1) if layer else "", klass.group(1) if klass else "", body))

            if klass is not None and klass.group(1) in GROUND_MARKERS:
                self.markers.setdefault((int(position[0] // CELL), int(position[1] // CELL)), []).append(position)

        self.navmesh = load_navmesh(game, name)

    def markers_near(self, x: float, y: float, radius: float):
        found = []
        reach = int(radius // CELL) + 1
        cx, cy = int(x // CELL), int(y // CELL)
        for dx in range(-reach, reach + 1):
            for dy in range(-reach, reach + 1):
                for mx, my, mz in self.markers.get((cx + dx, cy + dy), ()):
                    if (mx - x) ** 2 + (my - y) ** 2 <= radius * radius:
                        found.append((mx, my, mz))
        return found

    def standable(self, spot) -> bool:
        """
        Whether a spot is somewhere a person can actually be.

        A location table entry can name a place that only exists in another
        level -- the monastery is in `kutnohorsko`'s table and in `klaster`'s
        world -- leaving a handful of entities on no navmesh at all.
        """
        if spot is None:
            return False
        x, y, z = spot
        cx, cy = int(x // CELL), int(y // CELL)
        walkable = any(
            self.navmesh.get((cx + dx, cy + dy)) for dx in range(-2, 3) for dy in range(-2, 3)
        )
        return walkable and len(self.markers_near(x, y, 25.0)) >= 1

    def place(self, points):
        """
        Where to stand, given the entities that make up a place.

        The densest 16 m cell of the cluster is its built-up middle; the
        markers around it give the spot and the height, and the navmesh has
        the last word on the height.
        """
        if not points:
            return None

        cells: dict[tuple[int, int], list] = {}
        for x, y, _z in points:
            cells.setdefault((int(x // CELL), int(y // CELL)), []).append((x, y))
        (cx, cy), _ = max(cells.items(), key=lambda item: len(item[1]))
        seed = (cx + 0.5) * CELL, (cy + 0.5) * CELL

        for radius in MARKER_RADII:
            near = self.markers_near(seed[0], seed[1], radius)
            if len(near) >= 3:
                x = statistics.median(p[0] for p in near)
                y = statistics.median(p[1] for p in near)
                z = statistics.median(p[2] for p in near)
                return x, y, snap_to_navmesh(self.navmesh, x, y, z)

        # Nowhere anyone walks: fall back to the cluster itself.
        xs = sorted(p[0] for p in points)
        ys = sorted(p[1] for p in points)
        zs = sorted(p[2] for p in points)
        x, y, z = xs[len(xs) // 2], ys[len(ys) // 2], zs[len(zs) // 4]
        return x, y, snap_to_navmesh(self.navmesh, x, y, z)


def inside(polygon, x: float, y: float) -> bool:
    """Ray-cast point-in-polygon; the area shapes are simple and closed."""
    hit = False
    count = len(polygon)
    for index in range(count):
        ax, ay = polygon[index]
        bx, by = polygon[(index + 1) % count]
        if (ay > y) != (by > y) and x < ax + (y - ay) / (by - ay) * (bx - ax):
            hit = not hit
    return hit


def collect_map_locations(level: Level, locations, english):
    """One entry per location area, placed in the middle of its built-up part."""
    found = []
    for position, _layer, _klass, body in level.entities:
        located = LOCATION_ID_RE.search(body)
        if not located:
            continue
        info = locations.get(located.group(1))
        if info is None:
            continue

        polygon = [(position[0] + float(p[0]), position[1] + float(p[1])) for p in AREA_POINT_RE.findall(body)]
        if len(polygon) >= 3:
            xs = [p[0] for p in polygon]
            ys = [p[1] for p in polygon]
            inner = [
                point
                for point, _l, klass, _b in level.entities
                if klass in GROUND_MARKERS
                and min(xs) <= point[0] <= max(xs)
                and min(ys) <= point[1] <= max(ys)
                and inside(polygon, point[0], point[1])
            ]
        else:
            inner = level.markers_near(position[0], position[1], 60.0)

        spot = level.place(inner) or level.place([position])
        internal = info.get("location_name", "")
        name = english.get(internal, pretty(internal.removeprefix("location_")))
        found.append({"name": name, "group": "Map locations", "level": level.name, "pos": spot})
    return found


def collect_districts(level: Level):
    """
    One entry per settlement district that is an actual place.

    Layers nest to different depths -- `tvez_vezicko/poacherCamp` is a place
    while `ssed_sedlcko/monastery` is a dozen of them -- so both are offered
    and a parent stands down once two or more of its children qualify.
    """
    clusters: dict[tuple[str, tuple[str, ...]], list] = {}
    for position, layer, _klass, _body in level.entities:
        segments = layer.split("/")
        settlement = SETTLEMENT_RE.match(segments[1]) if len(segments) > 1 else None
        if settlement is None:
            continue
        for depth in (2, 3):
            if len(segments) <= depth:
                continue
            parts = tuple(segments[2 : depth + 1])
            if any(part in DISTRICT_SKIP or part.startswith(DISTRICT_SKIP_PREFIXES) for part in parts):
                continue
            clusters.setdefault((settlement.group(2), parts), []).append(position)

    def qualifies(points):
        if len(points) < DISTRICT_MIN_ENTITIES:
            return False
        xs = sorted(p[0] for p in points)
        ys = sorted(p[1] for p in points)
        return xs[-1] - xs[0] <= DISTRICT_MAX_SPAN and ys[-1] - ys[0] <= DISTRICT_MAX_SPAN

    kept = {key for key, points in clusters.items() if qualifies(points)}
    children: dict[tuple[str, tuple[str, ...]], int] = {}
    for settlement, parts in kept:
        if len(parts) == 2:
            children[(settlement, parts[:1])] = children.get((settlement, parts[:1]), 0) + 1

    found = []
    for key in kept:
        settlement, parts = key
        if len(parts) == 1 and children.get(key, 0) >= 2:
            continue
        found.append(
            {
                "name": district_name(parts),
                "group": pretty(settlement),
                "level": level.name,
                "pos": level.place(clusters[key]),
            }
        )
    return found


def deduplicate(entries):
    """Two areas can carry the same name; number them rather than lose one."""
    seen: dict[tuple, list] = {}
    for entry in entries:
        seen.setdefault((entry["level"], entry["group"], entry["name"]), []).append(entry)
    for group in seen.values():
        if len(group) > 1:
            for index, entry in enumerate(group, start=1):
                entry["name"] = f"{entry['name']} ({index})"
    return entries


def escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("game", help="Kingdom Come: Deliverance II installation directory")
    parser.add_argument("-o", "--output", default=DEFAULT_OUTPUT, help=f"output file (default: {DEFAULT_OUTPUT})")
    args = parser.parse_args(argv)

    locations = load_locations(args.game)
    english = load_english(args.game)

    entries = []
    for name in LEVELS:
        level = Level(args.game, name)
        mapped = collect_map_locations(level, locations, english)
        districts = collect_districts(level)
        kept = [entry for entry in mapped + districts if level.standable(entry["pos"])]
        entries += kept
        print(
            f"{name}: {len(level.entities)} entities, {sum(len(v) for v in level.markers.values())} ground markers, "
            f"{len(level.navmesh)} navmesh cells -> {len(mapped)} locations, {len(districts)} districts, "
            f"{len(mapped) + len(districts) - len(kept)} dropped as unreachable",
            file=sys.stderr,
        )

    deduplicate(entries)

    # Map locations first inside a level, then districts by settlement: the
    # panel lists rows in table order and the named places are what it should
    # open on.
    entries.sort(key=lambda e: (LEVELS.index(e["level"]), e["group"] != "Map locations", e["group"], e["name"]))

    groups = {(e["level"], e["group"]) for e in entries}
    lines = [HEADER.format(count=len(entries), levels=len(LEVELS), groups=len(groups))]
    for entry in entries:
        x, y, z = entry["pos"]
        lines.append(
            '        {{"{name}", "{group}", "{level}", {x:.3f}F, {y:.3f}F, {z:.3f}F}},\n'.format(
                name=escape(entry["name"]), group=escape(entry["group"]), level=entry["level"], x=x, y=y, z=z
            )
        )
    lines.append(FOOTER)

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("".join(lines))

    print(f"{len(entries)} points of interest in {len(groups)} groups -> {args.output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
