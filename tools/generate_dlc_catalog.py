#!/usr/bin/env python3
"""Generate the KCDC DLC table from an installed Kingdom Come: Deliverance II.

Every DLC is a row in `Libs/Tables/dlc.xml`, keyed by `dlc_id` -- the
`wh::shared::E_DLC::Type` value the engine's `IsDLCInstalled` takes. Emitted
offline as `code/shared/generated/dlc_catalog.cpp` because the server has no game
module to read the table from.

Two things the table does not carry are folded in: the display name, whose
`ui_name` key is resolved against `Localization/English_xml.pak`, and
ownability, determined by the Steam app IDs in STEAM_APP_IDS below.
The generated table contains ownability flags, not storefront-specific IDs.

Usage:
    python tools/generate_dlc_catalog.py <game directory>
"""

from __future__ import annotations

import argparse
import os
import sys
import xml.etree.ElementTree as ET
import zipfile

TABLES_PAK = os.path.join("Data", "Tables.pak")
DLC_TABLE = "Libs/Tables/dlc.xml"

LOCALIZATION_PAK = os.path.join("Localization", "English_xml.pak")
LOCALIZATION_TABLE = "text_ui_menu.xml"

DEFAULT_OUTPUT = os.path.join("code", "shared", "generated", "dlc_catalog.cpp")

# Steam app IDs by DLC ID. Other storefronts use different mappings.
STEAM_APP_IDS = {
    1: 3118100,
    2: 219957777,
    3: 219957777,
    4: 219957777,
    5: 3368610,
    6: 0,
    7: 3368620,
    8: 0,
    9: 3368600,
    10: 3118120,
    11: 3118110,
}

# The app id C_DLCPackage_PC::IsInstalled (0x1839C344C) short-circuits to owned
# without asking the platform. It is how the free DLCs are free.
ALWAYS_OWNED_APP_ID = 219957777


def read_dlc_rows(game_dir):
    """Every `<dlc>` row of the table, in id order."""
    with zipfile.ZipFile(os.path.join(game_dir, TABLES_PAK)) as pak:
        root = ET.fromstring(pak.read(DLC_TABLE).decode("utf-8-sig"))

    rows = []
    for dlc in root.iter("dlc"):
        rows.append(
            {
                "id": int(dlc.get("dlc_id")),
                "name": dlc.get("dlc_name"),
                "ui_name": dlc.get("ui_name", ""),
                "affects_savegame": dlc.get("affects_savegame") == "true",
            }
        )
    rows.sort(key=lambda row: row["id"])
    return rows


def read_english_strings(game_dir, keys):
    """The English text for each wanted key, as `text_ui_menu.xml` writes it."""
    path = os.path.join(game_dir, LOCALIZATION_PAK)
    if not os.path.exists(path):
        print("warning: %s is missing; display names will be empty" % path, file=sys.stderr)
        return {}

    strings = {}
    with zipfile.ZipFile(path) as pak:
        names = [name for name in pak.namelist() if name.lower().endswith(LOCALIZATION_TABLE)]
        for name in names:
            root = ET.fromstring(pak.read(name))
            for row in root.iter("Row"):
                cells = [cell.text or "" for cell in row]
                # Key, then the short form, then the long one. Prefer the
                # long one: the two reward rows abbreviate to "Season pass"
                # and "Gold Edition", which name an edition rather than the
                # thing a server is asking the player to own.
                if cells and cells[0] in keys:
                    text = cells[2] if len(cells) > 2 and cells[2] else (cells[1] if len(cells) > 1 else "")
                    strings[cells[0]] = ascii_punctuation(text)
    return strings


def ascii_punctuation(value):
    """Typographic quotes and dashes flattened, so the emitted source stays ASCII."""
    for fancy, plain in (("’", "'"), ("‘", "'"), ("“", '"'), ("”", '"'), ("–", "-"), ("—", "-"), ("…", "...")):
        value = value.replace(fancy, plain)
    return value


def cpp_string(value):
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return '"%s"' % escaped


def render(rows, strings):
    lines = [
        "// Generated by tools/generate_dlc_catalog.py from Data/Tables.pak and",
        "// Localization/English_xml.pak. Do not edit by hand.",
        "",
        '#include "shared/game/dlc_catalog.h"',
        "",
        "namespace KCDC::Shared::Game {",
        "    // Libs/Tables/dlc.xml. Ownability derived from the app-id list at",
        "    // WHGame.dll 0x180387D20; see STEAM_APP_IDS in the generator.",
        "    const std::vector<DLCEntry> g_DLCs = {",
    ]

    for row in rows:
        app_id = STEAM_APP_IDS.get(row["id"], 0)
        display = strings.get(row["ui_name"], "") if row["ui_name"] else ""
        # No trailing per-row comment: clang-format aligns consecutive ones,
        # and matching that by hand here would couple the generator to it.
        lines.append(
            "        {%s, %s, %d, %s},"
            % (
                cpp_string(row["name"]),
                cpp_string(display),
                row["id"],
                "true" if app_id != 0 else "false",
            )
        )

    lines += [
        "    };",
        "",
        "    const DLCEntry *FindDLCByName(std::string_view name) {",
        "        for (const DLCEntry &dlc : g_DLCs) {",
        "            if (dlc.name == name) {",
        "                return &dlc;",
        "            }",
        "        }",
        "        return nullptr;",
        "    }",
        "",
        "    std::string DLCMaskToLabels(std::uint16_t mask) {",
        "        std::string labels;",
        "        for (const DLCEntry &dlc : g_DLCs) {",
        "            if ((mask & DLCBit(dlc.id)) == 0) {",
        "                continue;",
        "            }",
        "            if (!labels.empty()) {",
        '                labels += ", ";',
        "            }",
        "            labels += dlc.displayName.empty() ? dlc.name : dlc.displayName;",
        "        }",
        "        return labels;",
        "    }",

        "} // namespace KCDC::Shared::Game",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("game_dir", help="Kingdom Come: Deliverance II installation directory")
    parser.add_argument("-o", "--output", default=DEFAULT_OUTPUT, help="where to write the generated table")
    args = parser.parse_args()

    rows = read_dlc_rows(args.game_dir)
    if not rows:
        print("error: %s carried no rows" % DLC_TABLE, file=sys.stderr)
        return 1

    missing = [row["id"] for row in rows if row["id"] not in STEAM_APP_IDS]
    if missing:
        print("error: no Steam app ID mapping for dlc_id %s; update STEAM_APP_IDS" % missing, file=sys.stderr)
        return 1

    strings = read_english_strings(args.game_dir, {row["ui_name"] for row in rows if row["ui_name"]})

    with open(args.output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(rows, strings))

    print("Wrote %d DLC rows to %s" % (len(rows), args.output))
    return 0


if __name__ == "__main__":
    sys.exit(main())
