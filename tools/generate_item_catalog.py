#!/usr/bin/env python3
"""Generate the KCDC item class table from an installed Kingdom Come: Deliverance II.

Every item a KCD2 actor can own is an item class with a GUID, and that GUID is
what `C_Inventory::CreateItems` takes. The classes live in
`Libs/Tables/item/item*.xml` as direct children of `<ItemClasses>`, where the
element name is the category:

    <ItemClasses version="8">
        <MeleeWeapon ... Id="000a72ec-..." Name="shieldCuman_06" />
        <Armor ... Id="..." Name="..." />
    </ItemClasses>

The children are parsed as XML rather than matched with a regex on purpose:
several classes carry nested elements of their own (`Phase`, `Image`,
`DocumentContent`), and only the direct children of `<ItemClasses>` are real
item classes.

The item database has no recovered in-process enumerator, so the table is
generated offline and compiled in as `code/shared/generated/item_classes.cpp` --
names, GUIDs, categories, the authored `Price` and the `UIName` localization
key only, never assets.

`Price` is what `C_Item::GetBasePrice` (0x180469510) reads and what
`C_RPGInventory`'s unit price slots scale by condition. An `ItemAlias`
authors none and is written as 0: every shipped alias is a quest item, which
no inventory operation accepts. `UIName` is the key the game shows a class's
name through, and several classes routinely share one.

Usage:
    python tools/generate_item_catalog.py <game directory>
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import xml.etree.ElementTree as ET
import zipfile

TABLES_PAK = os.path.join("Data", "Tables.pak")
ITEM_TABLE_RE = re.compile(r"^Libs/Tables/item/item(__[a-zA-Z_]+)?\.xml$", re.IGNORECASE)

DEFAULT_OUTPUT = os.path.join("code", "shared", "generated", "item_classes.cpp")

HEADER = """// Generated by tools/generate_item_catalog.py from Data/Tables.pak.
// Do not edit by hand.

#include "shared/game/item_classes.h"
#include "shared/game/custom_item_registry.h"
#include "shared/game/mod_item_tables.h"

#include <algorithm>

namespace KCDC::Shared::Game {{
    namespace {{
        // Constant arrays rather than std::vector initializer lists: at this
        // size those compile into per-element dynamic initialisation.
        // {count} item classes across {files} of the game's item tables.
        constexpr ItemClassEntry kItemClasses[] = {{
"""

FOOTER = """        };
    } // namespace

    const std::span<const ItemClassEntry> g_ItemClasses = kItemClasses;

    const ItemClassEntry *FindShippedItemClass(std::string_view guid) {
        // Every inventory row resolves its class here, so the table is indexed
        // by GUID once. Stable: a GUID two tables share keeps its first entry.
        static const std::vector<const ItemClassEntry *> byGuid = [] {
            std::vector<const ItemClassEntry *> sorted;
            sorted.reserve(g_ItemClasses.size());
            for (const auto &item : g_ItemClasses) {
                sorted.push_back(&item);
            }
            std::stable_sort(sorted.begin(), sorted.end(), [](const ItemClassEntry *left, const ItemClassEntry *right) { return left->guid < right->guid; });
            return sorted;
        }();
        const auto found = std::lower_bound(byGuid.begin(), byGuid.end(), guid, [](const ItemClassEntry *item, std::string_view value) { return item->guid < value; });
        return found != byGuid.end() && (*found)->guid == guid ? *found : nullptr;
    }

    const ItemClassEntry *FindItemClass(std::string_view guid) {
        if (const auto *custom = CustomItemRegistry::Get().Find(guid)) {
            return &custom->item;
        }
        // A streamed mod never stands in for a class the game ships: its entry
        // comes and goes with a resource, and a shipped one is held for good.
        if (const auto *shipped = FindShippedItemClass(guid)) {
            return shipped;
        }
        return ModItemRegistry::Get().Find(guid);
    }
} // namespace KCDC::Shared::Game
"""


def read_item_classes(pak_path):
    """Every item class in the pak, as (name, guid, category, price, name key)."""
    items = []
    files = 0
    with zipfile.ZipFile(pak_path) as pak:
        for entry in sorted(pak.namelist()):
            if not ITEM_TABLE_RE.match(entry):
                continue

            try:
                root = ET.fromstring(pak.read(entry))
            except ET.ParseError as error:
                print("Skipping {}: {}".format(entry, error), file=sys.stderr)
                continue

            classes = root.find("ItemClasses")
            if classes is None:
                continue

            files += 1
            for element in list(classes):
                name = element.get("Name") or ""
                guid = element.get("Id") or ""
                if not name or not guid:
                    continue
                price = int(element.get("Price") or "0")
                if not 0 <= price <= 0x7FFFFFFF:
                    raise ValueError("Price out of range: {} {}".format(name, price))
                # Kept byte for byte: three shipped classes author trailing
                # newlines, and the key the game asks with is what it parsed.
                name_key = element.get("UIName") or ""
                if '"' in name_key or "\\" in name_key or any(ord(c) < 0x20 and c not in "\r\n\t" for c in name_key):
                    raise ValueError("Unquotable UIName: {} {!r}".format(name, name_key))
                name_key = name_key.replace("\r", "\\r").replace("\n", "\\n").replace("\t", "\\t")
                items.append((name, guid, element.tag, price, name_key))
    return items, files


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("game_directory", help="Kingdom Come: Deliverance II install directory")
    parser.add_argument("-o", "--output", default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)

    pak_path = os.path.join(args.game_directory, TABLES_PAK)
    if not os.path.isfile(pak_path):
        print("Not found: {}".format(pak_path), file=sys.stderr)
        return 1

    items, files = read_item_classes(pak_path)
    if not items:
        print("No item classes found in {}".format(pak_path), file=sys.stderr)
        return 1

    # Sorted by category then name so the browser's list is stable across
    # regenerations and groups related items together.
    items.sort(key=lambda row: (row[2].lower(), row[0].lower()))

    os.makedirs(os.path.dirname(args.output) or ".", exist_ok=True)
    with open(args.output, "w", encoding="us-ascii", errors="replace", newline="\n") as out:
        out.write(HEADER.format(count=len(items), files=files))
        for name, guid, category, price, name_key in items:
            out.write('            {{"{}", "{}", "{}", {}, "{}"}},\n'.format(name, guid, category, price, name_key))
        out.write(FOOTER)

    print("Wrote {} item classes from {} tables to {}".format(len(items), files, args.output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
