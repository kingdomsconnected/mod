#!/usr/bin/env python3
"""Generate the KCDC particle effect table from an installed Kingdom Come: Deliverance II.

A particle effect is a name `CParticleManager::FindEffect` resolves -- what the
game's own `Particle.SpawnEffect` and `entity:LoadParticleEffect` take. The
library is the part before the first dot, and the manager loads
`Libs/Particles/<library>.xml` on demand, so the spawnable set is exactly the
top-level `<Particles Name="...">` elements across those files, each prefixed
with its library's own `Name`.

Only the top level is listed: the `<Childs>` below are sub-emitters of the
effect above them, and spawning one plays a fragment of an effect without the
rest.

Two facts travel with each name because the server has no game to ask:
`continuous`, since a continuous emitter never ends on its own and a spawn of
one has to carry a duration; and `viewDistance`, the largest
`CameraMaxDistance` in the tree, which is where the engine stops drawing it and
so where sending a burst stops buying anything.

Usage:
    python tools/generate_vfx_catalog.py <game directory>
"""

from __future__ import annotations

import argparse
import os
import posixpath
import sys
import xml.etree.ElementTree as ET
import zipfile

GAME_DATA_PAK = posixpath.join("Data", "IPL_GameData.pak")

PARTICLE_LIBRARY_DIR = "libs/particles/"

DEFAULT_OUTPUT = os.path.join("code", "shared", "generated", "vfx_catalog.cpp")

HEADER = """// Generated by tools/generate_vfx_catalog.py from Data/IPL_GameData.pak.
// Do not edit by hand.

#include "shared/game/vfx_catalog.h"

namespace KCDC::Shared::Game {{
    // {count} effects across {libraries} libraries, {continuous} of them continuous.
    const std::vector<VfxEffectEntry> g_VfxEffects = {{
"""

FOOTER = """    };
} // namespace KCDC::Shared::Game
"""


def particle_libraries(pak):
    """Every `Libs/Particles/*.xml` entry in the pak, by archive path."""
    return sorted(name for name in pak.namelist() if name.lower().startswith(PARTICLE_LIBRARY_DIR) and name.lower().endswith(".xml"))


def tree_facts(effect):
    """`(continuous, viewDistance)` over an effect and every sub-emitter under it."""
    continuous = False
    view_distance = 0.0
    for params in effect.iter("Params"):
        if params.get("Continuous", "").lower() == "true":
            continuous = True
        declared = params.get("CameraMaxDistance")
        if declared:
            # A particle field may carry a random or curve suffix after a
            # comma; the base value is the one the renderer culls against.
            view_distance = max(view_distance, float(declared.split(",")[0]))
    return continuous, view_distance


def collect(pak):
    rows = []
    libraries = 0
    for archive_path in particle_libraries(pak):
        root = ET.fromstring(pak.read(archive_path))
        if root.tag != "ParticleLibrary":
            continue
        library = root.get("Name")
        if not library:
            raise ValueError(f"{archive_path} declares no library name")
        libraries += 1
        for effect in root.findall("Particles"):
            # "group.effect": the game authors the two together in one
            # attribute, and FindEffect only ever splits off the library.
            qualified = effect.get("Name")
            if not qualified:
                raise ValueError(f"{archive_path} has a nameless top-level effect")
            group = qualified.split(".", 1)[0]
            continuous, view_distance = tree_facts(effect)
            rows.append((f"{library}.{qualified}", library, group, view_distance, continuous))
    rows.sort(key=lambda row: row[0])
    return rows, libraries


def generate(game_directory, output):
    pak_path = os.path.join(game_directory, *GAME_DATA_PAK.split("/"))
    if not os.path.isfile(pak_path):
        raise SystemExit(f"{pak_path} does not exist; point the generator at a Kingdom Come: Deliverance II install")

    with zipfile.ZipFile(pak_path) as pak:
        rows, libraries = collect(pak)

    if not rows:
        raise SystemExit(f"{pak_path} declares no particle libraries")

    lines = [HEADER.format(count=len(rows), libraries=libraries, continuous=sum(1 for row in rows if row[4]))]
    for name, library, group, view_distance, continuous in rows:
        lines.append(f'        {{"{name}", "{library}", "{group}", {view_distance:.1f}F, {"true" if continuous else "false"}}},\n')
    lines.append(FOOTER)

    with open(output, "w", encoding="ascii", newline="\n") as handle:
        handle.writelines(lines)
    print(f"Generated {len(rows)} particle effects across {libraries} libraries: {output}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("game", help="Kingdom Come: Deliverance II install directory")
    parser.add_argument("--output", default=None, help=f"where to write the table (default {DEFAULT_OUTPUT})")
    arguments = parser.parse_args()

    output = arguments.output
    if output is None:
        output = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), DEFAULT_OUTPUT)
    generate(arguments.game, output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
