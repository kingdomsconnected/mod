#!/usr/bin/env python3
"""Generate the KCDC clothing preset table from an installed Kingdom Come: Deliverance II.

A KCD2 actor wears what its inventory holds and its equipment manager has
equipped; nothing about a soul dresses it on its own. The game's own outfits
live in `Libs/Tables/item/clothing_preset*.xml`, where each preset is a named
list of item class GUIDs:

    <clothing_preset clothing_preset_id="..." clothing_preset_name="..." gender="Male">
        <Items>
            <Guid>fb15a17d-81d1-40ee-926f-f3f031234ed8</Guid>
            ...
        </Items>
    </clothing_preset>

Those GUIDs are exactly what `C_Inventory::CreateItems` takes, so a preset is
all the mod needs to dress a spawned body. The preset database has no recovered
in-process enumerator, so the table is generated offline and compiled in as
`code/shared/generated/clothing_presets.cpp` -- names and GUIDs only, never assets.

Usage:
    python tools/generate_clothing_catalog.py <game directory>
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import zipfile

TABLES_PAK = os.path.join("Data", "Tables.pak")
PRESET_TABLE_RE = re.compile(r"^Libs/Tables/item/clothing_preset.*\.xml$", re.IGNORECASE)

PRESET_RE = re.compile(r"<clothing_preset\b(?P<attrs>[^>]*?)(?:/>|>(?P<body>.*?)</clothing_preset>)", re.DOTALL)
ATTR_RE = re.compile(r'([a-zA-Z_0-9]+)="([^"]*)"')
GUID_RE = re.compile(r"<Guid>\s*([0-9a-fA-F-]{36})\s*</Guid>")

# Below this an entry is a layering override -- a single hat or glove meant to
# be applied on top of an outfit -- rather than something that dresses a body.
# A woman's outfit is a dress and a veil or shoes, so hers starts at two.
MIN_ITEMS = {"Male": 5, "Female": 2}

# The table's gender spellings, as the AppearanceGender each one is worn by.
# The game refuses a man's clothing on a woman's soul and the reverse
# (S_ArmorItemClass::IsWearableBySoul), so every preset keeps its gender.
GENDERS = {"Male": "Male", "Female": "Female"}

DEFAULT_OUTPUT = os.path.join("code", "shared", "generated", "clothing_presets.cpp")

HEADER = """// Generated by tools/generate_clothing_catalog.py from Data/Tables.pak.
// Do not edit by hand.

#include "shared/game/clothing_presets.h"

namespace KCDC::Shared::Game {{
    namespace {{
        // Constant arrays rather than std::vector initializer lists: at this
        // size those compile into per-element dynamic initialisation.
        constexpr std::string_view kItems[] = {{
"""

PRESETS = """        }};

        // {count} presets that dress a whole body, out of {total} in the
        // game's clothing_preset tables.
        constexpr ClothingPresetEntry kPresets[] = {{
"""

FOOTER = """        };
    } // namespace

    const std::span<const ClothingPresetEntry> g_ClothingPresets = kPresets;

    const ClothingPresetEntry *FindClothingPreset(std::string_view guid) {
        for (const auto &preset : g_ClothingPresets) {
            if (preset.guid == guid) {
                return &preset;
            }
        }
        return nullptr;
    }
} // namespace KCDC::Shared::Game
"""


def read_presets(pak_path):
    """Every preset in the pak, as (name, gender, preset_id, [item guids])."""
    presets = []
    with zipfile.ZipFile(pak_path) as pak:
        for entry in pak.namelist():
            if not PRESET_TABLE_RE.match(entry):
                continue
            text = pak.read(entry).decode("us-ascii", "replace")
            for match in PRESET_RE.finditer(text):
                attrs = dict(ATTR_RE.findall(match.group("attrs")))
                name = attrs.get("clothing_preset_name", "")
                preset_id = attrs.get("clothing_preset_id", "")
                if not name or not preset_id:
                    continue
                items = GUID_RE.findall(match.group("body") or "")
                presets.append((name, attrs.get("gender", ""), preset_id, items))
    return presets


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("game_directory", help="Kingdom Come: Deliverance II install directory")
    parser.add_argument("-o", "--output", default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)

    pak_path = os.path.join(args.game_directory, TABLES_PAK)
    if not os.path.isfile(pak_path):
        print("Not found: {}".format(pak_path), file=sys.stderr)
        return 1

    presets = read_presets(pak_path)
    if not presets:
        print("No clothing presets found in {}".format(pak_path), file=sys.stderr)
        return 1

    usable = [p for p in presets if p[1] in GENDERS and len(p[3]) >= MIN_ITEMS[p[1]]]
    usable.sort(key=lambda row: (row[1], row[0].lower()))

    os.makedirs(os.path.dirname(args.output) or ".", exist_ok=True)
    with open(args.output, "w", encoding="us-ascii", errors="replace", newline="\n") as out:
        out.write(HEADER.format())
        for _, _, _, items in usable:
            out.write("            {},\n".format(", ".join('"{}"'.format(g) for g in items)))
        out.write(PRESETS.format(count=len(usable), total=len(presets)))
        offset = 0
        for name, gender, preset_id, items in usable:
            out.write('            {{"{}", "{}", AppearanceGender::{}, {{kItems + {}, {}}}}},\n'.format(name, preset_id, GENDERS[gender], offset, len(items)))
            offset += len(items)
        out.write(FOOTER)

    print("Wrote {} of {} clothing presets to {}".format(len(usable), len(presets), args.output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
