#!/usr/bin/env python3
"""Generate the KCDC cart blueprint table from an installed Kingdom Come: Deliverance II.

A cart in KCD2 is not one entity. It is a small tree: a `frontPart` axel
carrying two wheels, a `backPart` body carrying two more, a `WHCart` entity
whose game-object extension holds the seats and the harness, and one or two
`WHCartMountPoint` children that raise the mount prompt. The editor builds it
from a prefab under `Prefabs/manmade/vehicles/` in `Data/IPL_GameData.pak`,
and the level then places a copy of that tree entity by entity.

The mod spawns the same tree the same way, so the shape of every cart worth
spawning is mined out of those prefabs and compiled in as
`code/shared/generated/cart_blueprints.cpp`.

Kept: the `GeomEntity` parts that give the cart its geometry, the `WHCart`
entity itself, and the `WHCartMountPoint` children. Dropped: the AI-side
fittings that need systems a spawned cart has none of -- `PrefabPort`,
`SchedulerHub`, `TagPoint` -- the wheel dust `ParticleEffect`s, and the
`Brush` cargo, which is a render node rather than an entity and so cannot be
spawned through the entity system at all.

Every part keeps its prefab `Properties`, the flat key/value pairs the level
loader assigns onto the entity's Lua `Properties` table before the entity is
initialised (CryEngine's `CScriptProperties::Assign`): the mount points'
`fUseAngle`, the `WHCart`'s smart object type, and so on. A part spawned
without them is not the part the prefab describes.

Transforms are prefab-local and relative to the part's parent. A root's own
transform is kept for the record only: the mod places the chassis root at the
cart's pose itself, and from then on the engine's cart movement poses it.

Usage:
    python tools/generate_cart_catalog.py <game directory>
"""

from __future__ import annotations

import argparse
import os
import posixpath
import sys
import zipfile
import xml.etree.ElementTree as ET

GAMEDATA_PAK = os.path.join("Data", "IPL_GameData.pak")
PREFAB_DIR = "Prefabs/manmade/vehicles/"

DEFAULT_OUTPUT = os.path.join("code", "shared", "generated", "cart_blueprints.cpp")

# The three classes a spawned cart is built out of. Everything else in a cart
# prefab belongs to a system a mod-spawned cart does not have.
KEPT_CLASSES = ("GeomEntity", "WHCart", "WHCartMountPoint")

HEADER = """// Generated by tools/generate_cart_catalog.py from Data/IPL_GameData.pak.
// Do not edit by hand.

#include "shared/game/cart_blueprints.h"

namespace KCDC::Shared::Game {
"""

FOOTER = """} // namespace KCDC::Shared::Game
"""


def parse_vec(text: str, fallback: tuple[float, float, float]) -> tuple[float, float, float]:
    if not text:
        return fallback
    parts = [float(p) for p in text.split(",")]
    return (parts[0], parts[1], parts[2])


def parse_quat(text: str) -> tuple[float, float, float, float]:
    """Prefab rotations are written w,x,y,z; the wire and the engine want x,y,z,w."""
    if not text:
        return (0.0, 0.0, 0.0, 1.0)
    w, x, y, z = (float(p) for p in text.split(","))
    return (x, y, z, w)


def fmt(value: float) -> str:
    # Enough digits to round-trip a float32, without the noise of repr().
    text = f"{value:.9g}"
    return text + "F" if ("." in text or "e" in text or "E" in text) else text + ".0F"


def blueprint_from(prefab_path: str, xml: bytes) -> dict | None:
    root = ET.fromstring(xml)
    objects = root.find("Objects")
    if objects is None:
        return None

    kept = [o for o in objects if o.get("EntityClass") in KEPT_CLASSES]
    if not any(o.get("EntityClass") == "WHCart" for o in kept):
        return None

    # Parent by prefab-object id, so the emitted table can carry indices.
    index_of = {o.get("Id"): i for i, o in enumerate(kept)}

    parts = []
    for obj in kept:
        parent = obj.get("Parent")
        if parent is not None and parent not in index_of:
            # A kept object hanging off a dropped one would come up in the
            # wrong place; nothing in the shipped prefabs does this, and a
            # blueprint that did would be wrong rather than merely incomplete.
            raise SystemExit(f"{prefab_path}: '{obj.get('Name')}' hangs off dropped object {parent}")

        geometry = (obj.get("Geometry") or "").replace("\\", "/").lower()
        entity_class = obj.get("EntityClass")
        node = obj.find("Properties")
        properties = dict(node.attrib) if node is not None else {}
        if entity_class == "WHCartMountPoint" and "bCartFrontSeat" not in properties and "back" in (obj.get("Name") or "").lower():
            # The Lua default is a front seat and the prefabs only spell the
            # back one out -- except cart_b, whose MountPointBack sets no
            # property at all and so would raise the front bench's prompt
            # twice. The name is what the designer meant, and it agrees with
            # the property everywhere the property exists.
            properties["bCartFrontSeat"] = "0"

        parts.append(
            {
                "name": obj.get("Name") or "",
                "entity_class": entity_class,
                "geometry": geometry,
                "parent": index_of[parent] if parent is not None else -1,
                "position": parse_vec(obj.get("Pos"), (0.0, 0.0, 0.0)),
                "rotation": parse_quat(obj.get("Rotate")),
                "scale": parse_vec(obj.get("Scale"), (1.0, 1.0, 1.0)),
                "properties": sorted(properties.items()),
            }
        )

    # A part may only name a parent that already exists when it is spawned.
    order = sorted(range(len(parts)), key=lambda i: depth(parts, i))
    remap = {old: new for new, old in enumerate(order)}
    parts = [parts[i] for i in order]
    for part in parts:
        if part["parent"] >= 0:
            part["parent"] = remap[part["parent"]]

    name = posixpath.splitext(posixpath.basename(prefab_path))[0]
    return {
        "name": name,
        "guid": root.get("Id") or "",
        "parts": parts,
        "seats": sum(1 for p in parts if p["entity_class"] == "WHCartMountPoint"),
    }


def depth(parts: list[dict], index: int) -> int:
    steps = 0
    while parts[index]["parent"] >= 0:
        index = parts[index]["parent"]
        steps += 1
        if steps > len(parts):
            raise SystemExit("cycle in prefab parenting")
    return steps


def emit(blueprints: list[dict]) -> str:
    out = [HEADER]
    for blueprint in blueprints:
        stem = ident(blueprint["name"])
        out.append(f"    // {blueprint['name']}: {len(blueprint['parts'])} parts, {blueprint['seats']} mount point(s).")
        for index, part in enumerate(blueprint["parts"]):
            if part["properties"]:
                pairs = ", ".join(f'{{"{cstr(key)}", "{cstr(value)}"}}' for key, value in part["properties"])
                out.append(f"    static const PrefabProperty k{stem}Part{index}Properties[] = {{{pairs}}};")
        out.append(f"    static const CartPart k{stem}Parts[] = {{")
        for index, part in enumerate(blueprint["parts"]):
            px, py, pz = part["position"]
            rx, ry, rz, rw = part["rotation"]
            sx, sy, sz = part["scale"]
            if part["properties"]:
                props = f"k{stem}Part{index}Properties, {len(part['properties'])}"
            else:
                props = "nullptr, 0"
            out.append(
                f'        {{"{cstr(part["name"])}", "{part["entity_class"]}", "{cstr(part["geometry"])}", {part["parent"]}, '
                f"{fmt(px)}, {fmt(py)}, {fmt(pz)}, {fmt(rx)}, {fmt(ry)}, {fmt(rz)}, {fmt(rw)}, "
                f"{fmt(sx)}, {fmt(sy)}, {fmt(sz)}, {props}}},"
            )
        out.append("    };")
        out.append("")

    out.append(f"    // {len(blueprints)} cart prefabs carrying a WHCart extension.")
    out.append("    const std::vector<CartBlueprint> g_CartBlueprints = {")
    for blueprint in blueprints:
        out.append(
            f'        {{"{blueprint["name"]}", "{blueprint["guid"]}", '
            f"k{ident(blueprint['name'])}Parts, "
            f"sizeof(k{ident(blueprint['name'])}Parts) / sizeof(k{ident(blueprint['name'])}Parts[0])}},"
        )
    out.append("    };")
    out.append("")
    out.append("    const CartBlueprint *FindCartBlueprint(std::string_view name) {")
    out.append("        for (const CartBlueprint &blueprint : g_CartBlueprints) {")
    out.append("            if (blueprint.name == name) {")
    out.append("                return &blueprint;")
    out.append("            }")
    out.append("        }")
    out.append("        return nullptr;")
    out.append("    }")
    out.append("")
    out.append(FOOTER)
    return "\n".join(out)


def cstr(text: str) -> str:
    """A prefab string as the inside of a C++ string literal."""
    return text.replace("\\", "\\\\").replace('"', '\\"')


def ident(name: str) -> str:
    return "".join(part.capitalize() for part in name.replace("-", "_").split("_"))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("game", help="Kingdom Come: Deliverance II installation directory")
    parser.add_argument("-o", "--output", default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    pak = os.path.join(args.game, GAMEDATA_PAK)
    if not os.path.exists(pak):
        print(f"{pak} not found", file=sys.stderr)
        return 1

    blueprints = []
    with zipfile.ZipFile(pak) as archive:
        for entry in archive.namelist():
            if not entry.startswith(PREFAB_DIR) or not entry.endswith(".xml"):
                continue
            blueprint = blueprint_from(entry, archive.read(entry))
            if blueprint is not None:
                blueprints.append(blueprint)

    blueprints.sort(key=lambda b: b["name"])
    if not blueprints:
        print("no cart prefabs found", file=sys.stderr)
        return 1

    with open(args.output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(emit(blueprints))

    print(f"{len(blueprints)} cart blueprints -> {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
