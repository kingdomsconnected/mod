#!/usr/bin/env python3
"""Compile production alchemy condition programs; reject unfamiliar syntax.

The native matcher preserves recipe order. Its ingredient predicate accepts
the requested class or that herb's DriedItemId, a directional equivalence.
Tables are read only. No expression parsing or archive access occurs in game.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET
import zipfile

from generate_gate_catalog import DEFAULT_GAME, zread


def quote(value):
    return json.dumps(value, ensure_ascii=True)


def predicates(condition):
    result = []
    guid = r"'([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})'"
    for term in re.split(r"\s+AND\s+", condition.strip()):
        term = term.strip()
        if term == "PotionBase()":
            result.append(("PotionBase", "", 0))
            continue
        match = re.fullmatch(r"IngredientCount\s*\(\s*" + guid + r"\s*\)\s*(==|>=)\s*([0-9]+)", term)
        if match:
            result.append(("CountEqual" if match[2] == "==" else "CountAtLeast", match[1], int(match[3])))
            continue
        match = re.fullmatch(r"(IsMilled|WeakBoilingTime|StrongBoilingTime)\s*\(\s*" + guid + r"\s*,\s*([0-9]+(?:\.[0-9]+)?)\s*\)", term)
        if match:
            kind = {"IsMilled": "Milled", "WeakBoilingTime": "WeakBoiling", "StrongBoilingTime": "StrongBoiling"}[match[1]]
            if kind == "Milled" and float(match[3]) not in (0, 1):
                raise ValueError("Unexpected milling flag: " + term)
            result.append((kind, match[2], float(match[3])))
            continue
        match = re.fullmatch(r"(IsBaseDistilled|IsResultMilled)\s*\(\s*([01])\s*\)", term)
        if match:
            result.append(("BaseDistilled" if match[1] == "IsBaseDistilled" else "ResultMilled", "", int(match[2])))
            continue
        raise ValueError("Unsupported alchemy condition: " + term)
    return result


def generate(game):
    digest = hashlib.sha256()
    with zipfile.ZipFile(game / "Data/Tables.pak") as archive:
        def table(path):
            data = zread(archive, "Libs/Tables/" + path)
            digest.update(path.encode() + data)
            return ET.fromstring(data)[0]

        recipes = table("minigame/AlchemyRecipe.xml")
        step_xp = {row.get("Name"): int(row.get("RewardXP")) for row in table("minigame/AlchemyRecipeStepType.xml")}
        bases = list(table("minigame/AlchemyPotionBase.xml"))
        herbs = {}
        for name in sorted(archive.namelist()):
            normalized = name.replace("\\", "/")
            if not re.fullmatch(r"Libs/Tables/item/item(?:__[^/]+)?\.xml", normalized):
                continue
            for row in ET.fromstring(zread(archive, name))[0]:
                if row.tag != "Herb" or not row.get("DriedItemId"):
                    continue
                old = herbs.get(row.get("Id"))
                if old is not None and old != row.get("DriedItemId"):
                    raise ValueError("Conflicting herb variant: " + row.get("Id"))
                herbs[row.get("Id")] = row.get("DriedItemId")
        digest.update(json.dumps(sorted(herbs.items())).encode())

    lines = ['#include "shared/game/alchemy_catalog.h"', '', '// Generated by tools/generate_alchemy_catalog.py. Do not edit by hand.', '', 'namespace KCDC::Shared::Game {']
    # Constant arrays rather than std::vector initializer lists: those compile
    # into per-element dynamic initialisation. Nested lists are flat arrays
    # each parent views through an offset and count.
    predicate_rows, step_rows, program_rows = [], [], []
    count = 0
    for recipe in recipes:
        first_step = len(step_rows)
        ids = set()
        for step in recipe.find("Steps"):
            step_id = int(step.get("StepId"))
            if step_id in ids or not 1 <= step_id <= 29:
                raise ValueError("Invalid knowledge bit/step identity")
            ids.add(step_id)
            terms = predicates(step.get("Condition"))
            first_predicate = len(predicate_rows)
            predicate_rows.extend(f'{{AlchemyPredicateKind::{kind}, {quote(item)}, {float(value):.6f}F}}' for kind, item, value in terms)
            step_rows.append(f'{{{step_id}, {step_xp[step.get("StepType")]}, {int(step.get("FeedbackPriority", "0"))}, {quote(step.get("UIText", ""))}, {{kPredicates + {first_predicate}, {len(terms)}}}}}')
            count += 1
        if not ids:
            raise ValueError("Recipe has no identification condition")
        program_rows.append(f'{{{quote(recipe.get("RecipeId"))}, {int(recipe.get("BaseQualityRewardXP"))}, {{kSteps + {first_step}, {len(step_rows) - first_step}}}}}')
    base_rows = [f'{{{quote(row.get("BaseItemId"))}, {quote(row.get("BaseType"))}, {float(row.get("Quality")):.6f}F}}' for row in bases]
    herb_rows = [f'{{{quote(fresh)}, {quote(dried)}}}' for fresh, dried in sorted(herbs.items())]
    lines.append('    namespace {')
    for name, kind, rows in (("kPredicates", "AlchemyPredicate", predicate_rows), ("kSteps", "AlchemyStep", step_rows), ("kPrograms", "AlchemyProgram", program_rows), ("kBases", "AlchemyBase", base_rows), ("kHerbVariants", "AlchemyHerbVariant", herb_rows)):
        lines.append(f'        constexpr {kind} {name}[] = {{')
        lines.extend(f'            {row},' for row in rows)
        lines += ['        };', '']
    lines[-1] = '    } // namespace'
    lines.append('')
    lines.append(f'    const std::string_view g_AlchemyRulesHash = "{digest.hexdigest()}";')
    lines.append('    const std::span<const AlchemyProgram> g_AlchemyPrograms = kPrograms;')
    lines.append('    const std::span<const AlchemyBase> g_AlchemyBases = kBases;')
    lines.append('    const std::span<const AlchemyHerbVariant> g_AlchemyHerbVariants = kHerbVariants;')
    lines += ['} // namespace KCDC::Shared::Game', '']
    output = Path(__file__).resolve().parents[1] / "code/shared/generated/alchemy_catalog.cpp"
    output.write_text("\n".join(lines))
    print(f"Wrote {len(recipes)} alchemy programs, {count} steps, {len(herbs)} herb variants; SHA256 {digest.hexdigest()}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game", type=Path, default=Path(DEFAULT_GAME))
    generate(parser.parse_args().game)
