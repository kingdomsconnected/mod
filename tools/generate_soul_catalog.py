#!/usr/bin/env python3
"""Generate the KCDC soul catalog from an installed Kingdom Come: Deliverance II.

A spawned actor takes its identity -- stats, faction and appearance -- from a
soul, selected at spawn time by its `soul_id` GUID. The game's own debug
tooling does exactly this: `Scripts/Debug/CombatDebug.lua` calls
`XGenAIModule.SpawnEntity{Name = ..., ClassName = ..., SharedSoulGuid = ...}`,
where the GUID is a `soul_id` from `Libs/Tables/rpg/soul__*.xml`.

The debug spawner therefore needs those GUIDs, plus names to browse them by.
The catalog is generated offline from the game's own tables and contains
names and metadata only.

Usage:
    python tools/generate_soul_catalog.py <game directory> [-o files/kcdc/souls.tsv]
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import zipfile

ARCHETYPE_TABLE = "Libs/Tables/rpg/soul_archetype.xml"
SOUL_TABLE_PREFIX = "Libs/Tables/rpg/soul__"

ARCHETYPE_RE = re.compile(
    r'soul_archetype_id="(\d+)"[^/]*?soul_archetype_name="([^"]+)"'
)
SOUL_ROW_RE = re.compile(r"<soul\b[^>]*/>")
ATTR_RE = re.compile(r'(\w+)="([^"]*)"')


def read_archetypes(tables: zipfile.ZipFile) -> dict[int, str]:
    raw = tables.read(ARCHETYPE_TABLE).decode("utf-8", "replace")
    return {int(m.group(1)): m.group(2) for m in ARCHETYPE_RE.finditer(raw)}


def read_souls(tables: zipfile.ZipFile, archetypes: dict[int, str]):
    seen: set[str] = set()
    rows = []

    for entry in sorted(tables.namelist()):
        if not entry.startswith(SOUL_TABLE_PREFIX) or not entry.endswith(".xml"):
            continue

        raw = tables.read(entry).decode("utf-8", "replace")
        for match in SOUL_ROW_RE.finditer(raw):
            attrs = dict(ATTR_RE.findall(match.group(0)))
            name = attrs.get("soul_name", "")
            if not name or name in seen:
                continue
            seen.add(name)

            archetype_id = attrs.get("soul_archetype_id")
            archetype = archetypes.get(int(archetype_id), "") if archetype_id else ""
            rows.append((name, archetype, attrs.get("soul_id", ""), attrs.get("skald_character_name", "")))

    rows.sort(key=lambda row: row[0].lower())
    return rows


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("game_dir", help="Kingdom Come: Deliverance II install directory")
    parser.add_argument(
        "-o",
        "--output",
        default=os.path.join("files", "kcdc", "souls.tsv"),
        help="output catalog path (default: files/kcdc/souls.tsv)",
    )
    args = parser.parse_args()

    tables_path = os.path.join(args.game_dir, "Data", "Tables.pak")
    if not os.path.isfile(tables_path):
        print(f"error: {tables_path} not found", file=sys.stderr)
        return 1

    with zipfile.ZipFile(tables_path) as tables:
        archetypes = read_archetypes(tables)
        souls = read_souls(tables, archetypes)

    if not souls:
        print("error: no souls found; is this a Kingdom Come: Deliverance II install?", file=sys.stderr)
        return 1

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("# KCDC soul catalog\n")
        handle.write("# Generated by tools/generate_soul_catalog.py from Data/Tables.pak.\n")
        handle.write("# soul_name<TAB>soul_archetype<TAB>soul_id<TAB>character\n")
        handle.write(f"# souls: {len(souls)}\n")
        for name, archetype, soul_id, character in souls:
            handle.write(f"{name}\t{archetype}\t{soul_id}\t{character}\n")

    counts: dict[str, int] = {}
    for _, archetype, _, _ in souls:
        counts[archetype] = counts.get(archetype, 0) + 1

    print(f"wrote {args.output}: {len(souls)} souls")
    for archetype, count in sorted(counts.items(), key=lambda kv: -kv[1]):
        print(f"  {count:6d}  {archetype or '(none)'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
