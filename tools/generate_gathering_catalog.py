#!/usr/bin/env python3
"""Compile the harvestable plant kinds into the shared gathering catalog.

The client reports a picked plant by its pickable area id; the server needs
only what that kind yields and how long it takes to regrow.
"""

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile

from generate_gate_catalog import DEFAULT_GAME, zread


def generate(game, output):
    with zipfile.ZipFile(game / "Data/Tables.pak") as archive:
        definitions = zread(archive, "Libs/Tables/item/pickable_area_desc.xml")
    kinds = {int(row.get("id")): (row.get("guid_item_picked"), int(row.get("amount")), float(row.get("respawn_time"))) for row in ET.fromstring(definitions)[0]}
    lines = ['#include "shared/game/gathering_catalog.h"', '', '// Generated by tools/generate_gathering_catalog.py. Do not edit by hand.', '', 'namespace KCDC::Shared::Game {', '    const std::vector<GatheringKind> g_GatheringKinds = {']
    for kind, (item, amount, respawn) in sorted(kinds.items()):
        lines.append(f'        {{{kind}, "{item}", {amount}, {respawn:.6f}F}},')
    lines += ['    };', '', '    const GatheringKind *FindGatheringKind(std::uint8_t kind) {', '        for (const auto &entry : g_GatheringKinds) {', '            if (entry.id == kind) return &entry;', '        }', '        return nullptr;', '    }', '} // namespace KCDC::Shared::Game', '']
    output.write_text('\n'.join(lines))
    print('Wrote', len(kinds), 'kinds')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--game', type=Path, default=Path(DEFAULT_GAME))
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'code/shared/generated/gathering_catalog.cpp')
    args = parser.parse_args()
    generate(args.game, args.output)
