#!/usr/bin/env python3
"""Compile the shipped skill/stat/perk identities for explicit soul profiles.

This declares which inputs must be present; it does not infer default levels,
XP, modifiers, perk ownership, or native runtime formulas.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import uuid
import xml.etree.ElementTree as ET
import zipfile


def extract(pak):
    groups = {'skill': {}, 'stat': {}, 'perk': {}}
    sources = []
    for name in sorted(pak.namelist()):
        match = re.fullmatch(r'Libs/Tables/rpg/(skill|stat|perk)(?:__[\w]+)?\.xml', name, re.I)
        if not match:
            continue
        kind = match[1].lower()
        data = pak.read(name)
        sources.append((name, hashlib.sha256(data).hexdigest()))
        for row in ET.fromstring(data).findall(f'./{kind}s/{kind}'):
            identity = str(uuid.UUID(row.attrib[f'{kind}_id'])) if kind == 'perk' else int(row.attrib[f'{kind}_id'])
            if kind != 'perk' and not 0 <= identity < 2**32:
                raise ValueError(f'Invalid {kind} identity: {identity}')
            value = row.attrib[f'{kind}_name']
            if identity in groups[kind]:
                raise ValueError(f'Duplicate {kind} identity: {identity}')
            groups[kind][identity] = value
    if any(not group for group in groups.values()):
        raise ValueError('Missing soul profile identity table')
    return groups, hashlib.sha256(json.dumps(sources, separators=(',', ':')).encode()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('game_directory', type=Path)
    parser.add_argument('--output', type=Path, default=Path('code/shared/generated/soul_profile_catalog.cpp'))
    args = parser.parse_args()
    with zipfile.ZipFile(args.game_directory / 'Data/Tables.pak') as pak:
        groups, digest = extract(pak)
    lines = ['// Generated by tools/generate_soul_profile_catalog.py; do not edit.', '#include "shared/game/soul_profile_catalog.h"', '', 'namespace KCDC::Shared::Game {', f'    const std::string_view g_SoulProfileCatalogHash = "{digest}";']
    for kind, typ, var in [('skill', 'SoulNumericDefinition', 'g_SoulSkills'), ('stat', 'SoulNumericDefinition', 'g_SoulStats'), ('perk', 'SoulPerkDefinition', 'g_SoulPerks')]:
        lines.append(f'    const std::vector<{typ}> {var} = {{')
        for identity, name in sorted(groups[kind].items()):
            key = json.dumps(identity) if kind == 'perk' else f'{identity}U'
            lines.append(f'        {{{key}, {json.dumps(name)}}},')
        lines.append('    };')
    lines += ['} // namespace KCDC::Shared::Game', '']
    args.output.write_text('\n'.join(lines), encoding='utf-8')
    print(', '.join(f'{len(values)} {kind}' for kind, values in groups.items()))

if __name__ == '__main__':
    main()
