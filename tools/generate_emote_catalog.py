"""Generate the KCD2 emote catalog from Tables.pak."""

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile
import zlib


SELECTION = (
    (1, "Wave", "GreetingsUpperBody", "waveSmall", "l_noweapon+waveSmall"),
    (2, "Big wave", "GreetingsUpperBody", "waveBig", "l_noweapon+waveBig"),
    (3, "Nod", "GreetingsUpperBody", "nod", "l_noweapon+nod"),
    (4, "Respectful nod", "GreetingsUpperBody", "nodSubmissive", "l_noweapon+nodSubmissive"),
    (5, "Bow", "Greetings", "bowBig", "bowBig"),
    (6, "Cheer", "TournamentCheersHappyGesture", "", ""),
)


def lowercase_crc(value):
    return zlib.crc32(value.lower().encode("ascii"))


def generate(game):
    with zipfile.ZipFile(game / "Data/Tables.pak") as pak:
        rows = ET.fromstring(pak.read("Libs/Tables/action/actor_anim_action.xml"))
    lines = [
        "// Generated by tools/generate_emote_catalog.py from Tables.pak.",
        '#include "shared/game/emote_catalog.h"', "", "namespace KCDC::Shared::Game {",
        "    const std::vector<EmoteEntry> g_Emotes = {",
    ]
    for ident, label, fragment, tag, row_tags in SELECTION:
        matches = [row for row in rows.iter("actor_anim_action")
                   if row.get("actor_class_hash") == "1578932418"
                   and row.get("mn_fragment_id") == fragment
                   and row.get("mn_tags", "") == row_tags
                   and row.get("mn_option_index") == "0"]
        if len(matches) != 1 or matches[0].get("isOneShot") != "true":
            raise ValueError(f"Expected exactly one one-shot human entry: {fragment}/{tag}")
        duration = float(matches[0].get("animation_duration"))
        if not 0 < duration < 10:
            raise ValueError(f"Unexpected duration for {label}: {duration}")
        # isfullbody is the game's own answer to whether the clip takes the
        # FullBody scope, and so whether the actor can keep walking under it.
        full_body = matches[0].get("isfullbody") == "true"
        lines.append(f'        {{{ident}, "{label}", "{fragment}", "{tag}", 0x{lowercase_crc(fragment):08X}U, 0x{lowercase_crc(tag):08X}U, {duration:.6f}F, {"true" if full_body else "false"}}},')
    lines += ["    };", "} // namespace KCDC::Shared::Game", ""]
    target = Path(__file__).resolve().parents[1] / "code/shared/generated/emote_catalog.cpp"
    target.write_text("\n".join(lines), encoding="ascii")
    print(f"Generated {len(SELECTION)} gestures: {target}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("game", type=Path)
    generate(parser.parse_args().game)
