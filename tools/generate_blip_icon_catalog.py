#!/usr/bin/env python3
"""Generate the KCDC blip icon table from an installed Kingdom Come: Deliverance II.

A blip draws with one of the game's own compass mark icons. Which icons exist
is the switch in `wh::guimodule::MarkTypeToIconName` (0x180C4D664), already
transcribed into the client SDK at
`code/client/src/sdk/wh/guimodule/e_compass_mark_type.h`; this reads the
names and values from there rather than keeping a second copy by hand.

Which of them the MAP SCREEN can draw is a different question, answered by the
game's files. `ApseMap.gfx`'s `PoiMarker.SetData` loads every POI row's art as

    img://Libs/UI/Textures/Icons/Map/<Icon>[_undiscovered]_icon.dds
    img://Libs/UI/Textures/Icons/Map/<Icon>_sh_icon.dds

taking the `_undiscovered` variant when the row's state is
`POI_STATE_UNDISCOVERED` (1). A texture that is not there renders as
Scaleform's broken-image placeholder, so a row may only use an icon whose
textures ship: the quest icons (`Main`, `Side`, `Micro`) and `Checkpoint`
have no shadow, because the game draws those through other map paths, and
several DLC icons have no undiscovered variant.

The table is compiled in as `code/shared/game/blip_icon_catalog.h`. See
AGENTS.md -- nothing mined out of the game is read from a file at runtime.

Usage:
    python tools/generate_blip_icon_catalog.py <game directory>
"""

from __future__ import annotations

import argparse
import glob
import os
import re
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SDK_HEADER = os.path.join(ROOT, "code", "client", "src", "sdk", "wh", "guimodule", "e_compass_mark_type.h")
OUTPUT = os.path.join(ROOT, "code", "shared", "game", "blip_icon_catalog.h")
MAP_ICON_DIR = "libs/ui/textures/icons/map/"


def read_icons():
    source = open(SDK_HEADER, encoding="utf-8").read()
    start = source.index("enum class E_CompassMarkType")
    enum = source[start:source.index("};", start)]
    values = {name: int(value) for name, value in re.findall(r"(\w+)\s*=\s*(\d+),", enum)}
    icons = []
    for identifier, name in re.findall(r'\{E_CompassMarkType::(\w+), "(\w+)"\}', source):
        icons.append((values[identifier], name))
    return icons, values["GeneralPoi"]


def read_map_textures(game_dir):
    textures = set()
    for pak in sorted(glob.glob(os.path.join(game_dir, "Data", "*.pak"))):
        try:
            archive = zipfile.ZipFile(pak)
        except zipfile.BadZipFile:
            continue
        with archive:
            for name in archive.namelist():
                lowered = name.lower()
                if lowered.startswith(MAP_ICON_DIR):
                    textures.add(lowered[len(MAP_ICON_DIR):])
    return textures


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("game_dir")
    args = parser.parse_args()

    icons, default_type = read_icons()
    textures = read_map_textures(args.game_dir)
    if not textures:
        sys.exit(f"no {MAP_ICON_DIR} textures found under {args.game_dir}")

    rows = []
    for value, name in icons:
        stem = name.lower()
        on_map = f"{stem}_icon.dds" in textures and f"{stem}_sh_icon.dds" in textures
        undiscovered = on_map and f"{stem}_undiscovered_icon.dds" in textures
        rows.append(f'        {{{value}, "{name}", {"true" if on_map else "false"}, {"true" if undiscovered else "false"}}},')

    header = f'''#pragma once

// Generated by tools/generate_blip_icon_catalog.py -- do not edit by hand.

#include <array>
#include <cstdint>
#include <string_view>

namespace KCDC::Shared::Game {{
    /** One icon a blip can be drawn with: the game's own mark type, its name for it, and what the map screen has art for. */
    struct BlipIcon {{
        std::uint8_t type;
        const char *name;

        /** The map screen ships this icon and its shadow, so a POI row can draw it. */
        bool onMap;

        /** The map screen also ships its undiscovered variant, drawn for state 1. */
        bool undiscoveredOnMap;
    }};

    /**
     * Every icon the game can draw a compass mark with, by the name
     * `wh::guimodule::MarkTypeToIconName` (0x180C4D664) gives it --
     * misspellings included, since those are the identifiers.
     *
     * The compass draws all of them. The map screen loads each row's art from
     * `Libs/UI/Textures/Icons/Map/` and shows a broken-image placeholder for
     * a texture that is not there, so only the icons with `onMap` may become
     * a map row, and state 1 only where `undiscoveredOnMap` holds.
     */
    inline constexpr std::array<BlipIcon, {len(rows)}> kBlipIcons {{{{
{chr(10).join(rows)}
    }}}};

    /** The icon a blip gets when nothing names one. */
    inline constexpr std::uint8_t kDefaultBlipIcon = {default_type};

    /** The state the map screen draws with its undiscovered art. */
    inline constexpr std::int32_t kMapUndiscoveredState = 1;

    /** The icon spelled `name`, compared exactly, or null. */
    inline const BlipIcon *FindBlipIcon(std::string_view name) {{
        for (const BlipIcon &icon : kBlipIcons) {{
            if (name == icon.name) {{
                return &icon;
            }}
        }}
        return nullptr;
    }}

    /** The icon with this type value, or null for one the game has no icon for. */
    inline const BlipIcon *BlipIconOf(std::uint8_t type) {{
        for (const BlipIcon &icon : kBlipIcons) {{
            if (icon.type == type) {{
                return &icon;
            }}
        }}
        return nullptr;
    }}
}} // namespace KCDC::Shared::Game
'''
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as out:
        out.write(header)

    missing = [name for (value, name), row in zip(icons, rows) if ", false, false}" in row]
    print(f"wrote {len(rows)} icons to {os.path.relpath(OUTPUT, ROOT)}; not on the map: {', '.join(missing)}")


if __name__ == "__main__":
    main()
