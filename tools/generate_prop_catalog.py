#!/usr/bin/env python3
"""Generate the KCDC prop model table from an installed Kingdom Come: Deliverance II.

A prop is a static mesh -- a `.cgf` -- that `IEntity::LoadGeometry` puts into a
render slot. The game ships them inside `Data/IPL_Objects-part*.pak`, which are
plain zip archives, so the set of spawnable meshes is exactly the set of `.cgf`
entries under `Objects/` in those paks.

Dropped: the level-of-detail siblings (`*_lod1.cgf`), the per-tile terrain
shadow casters under `Objects/special/shadow_proxy/`, and the whole-district
impostors in `uberlods`, `custom_hlods` and `panorama`. Everything else is
kept, odd corners included -- the panel is a debug tool.

The table is compiled in as `code/shared/generated/prop_models.cpp`: paths only,
never assets.

Usage:
    python tools/generate_prop_catalog.py <game directory>
"""

from __future__ import annotations

import argparse
import glob
import os
import posixpath
import re
import sys
import zipfile

OBJECT_PAK_GLOB = os.path.join("Data", "IPL_Objects-part*.pak")

LOD_RE = re.compile(r"_lod\d+\.cgf$", re.IGNORECASE)
EXCLUDED_RE = re.compile(r"^objects/(special/shadow_proxy|uberlods|custom_hlods|panorama)/", re.IGNORECASE)

DEFAULT_OUTPUT = os.path.join("code", "shared", "generated", "prop_models.cpp")

HEADER = """// Generated by tools/generate_prop_catalog.py from Data/IPL_Objects-part*.pak.
// Do not edit by hand.

#include "shared/game/prop_models.h"

namespace KCDC::Shared::Game {{
    namespace {{
        // A constant array rather than a std::vector initializer list: at
        // this size that compiles into per-element dynamic initialisation.
        // {count} static meshes across {groups} groups, from {paks} object paks.
        constexpr PropModelEntry kPropModels[] = {{
"""

FOOTER = """        };
    } // namespace

    const std::span<const PropModelEntry> g_PropModels = kPropModels;

    const PropModelEntry *FindPropModel(std::string_view path) {
        for (const auto &model : g_PropModels) {
            if (model.path == path) {
                return &model;
            }
        }
        return nullptr;
    }
} // namespace KCDC::Shared::Game
"""


def read_prop_models(pak_paths):
    """Every spawnable mesh in the paks, as (path, group, name)."""
    paths = set()
    for pak_path in pak_paths:
        with zipfile.ZipFile(pak_path) as pak:
            for entry in pak.namelist():
                entry = entry.replace("\\", "/")
                if not entry.lower().endswith(".cgf"):
                    continue
                if LOD_RE.search(entry) or EXCLUDED_RE.match(entry.lower()):
                    continue
                paths.add(entry.lower())

    models = []
    for path in paths:
        directory, filename = posixpath.split(path)
        # The bucket the browser groups by: the two path segments below
        # `objects/`, which is where the game's own taxonomy sits
        # (`manmade/structures`, `natural/vegetation`, ...).
        segments = directory.split("/")[1:3]
        models.append((path, "/".join(segments), posixpath.splitext(filename)[0]))
    return models


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("game_directory", help="Kingdom Come: Deliverance II install directory")
    parser.add_argument("-o", "--output", default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)

    pak_paths = sorted(glob.glob(os.path.join(args.game_directory, OBJECT_PAK_GLOB)))
    if not pak_paths:
        print("No object paks under {}".format(os.path.join(args.game_directory, OBJECT_PAK_GLOB)), file=sys.stderr)
        return 1

    models = read_prop_models(pak_paths)
    if not models:
        print("No .cgf models found in {} paks".format(len(pak_paths)), file=sys.stderr)
        return 1

    # Sorted by group then name so the browser's list is stable across
    # regenerations and every group is one contiguous run of rows.
    models.sort(key=lambda row: (row[1], row[2], row[0]))
    groups = len({row[1] for row in models})

    os.makedirs(os.path.dirname(args.output) or ".", exist_ok=True)
    with open(args.output, "w", encoding="us-ascii", errors="replace", newline="\n") as out:
        out.write(HEADER.format(count=len(models), groups=groups, paks=len(pak_paths)))
        for path, group, name in models:
            out.write('            {{"{}", "{}", "{}"}},\n'.format(path, group, name))
        out.write(FOOTER)

    print("Wrote {} prop models in {} groups from {} paks to {}".format(len(models), groups, len(pak_paths), args.output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
