#!/usr/bin/env python3
"""Generate the KCDC marker material table from an installed Kingdom Come: Deliverance II.

The two marker kinds need different materials, and mixing them fails silently.
A material declaring `%DECAL` renders in the deferred decal pass: on a mesh it
draws no surface and instead blends into the G-buffer of the geometry behind it,
so the marker is invisible and everything near it is lit wrongly. Each row
therefore carries which kind it is.

`decal` -- `Materials/decals/` entries declaring `%DECAL`. The engine preloads
that folder whole at startup, so every name in it resolves without a load.

`mesh` -- `Materials/special/` and `Materials/filters/`, plus the primitives'
own `editorprimitive`. These are what the engine draws its collision proxies
with, so they are authored as translucent coloured volumes.

Usage:
    python tools/generate_marker_catalog.py <game directory>
"""

from __future__ import annotations

import argparse
import os
import posixpath
import sys
import xml.etree.ElementTree as ET
import zipfile

GAME_DATA_PAK = posixpath.join("Data", "IPL_GameData.pak")

# The primitives' own material lives with the meshes rather than in Materials/.
OBJECT_PAK = posixpath.join("Data", "IPL_Objects-part5.pak")

DECAL_DIR = "materials/decals/"

MESH_DIRS = ("materials/special/", "materials/filters/")

MESH_EXTRA = ("objects/special/editorprimitive.mtl",)

DEFAULT_OUTPUT = os.path.join("code", "shared", "generated", "marker_catalog.cpp")

HEADER = """// Generated by tools/generate_marker_catalog.py from Data/IPL_GameData.pak
// and Data/IPL_Objects-part5.pak. Do not edit by hand.

#include "shared/game/marker_catalog.h"

namespace KCDC::Shared::Game {{
    // {count} materials: {decals} for projected markers, {meshes} for mesh ones.
    const std::vector<MarkerMaterialEntry> g_MarkerMaterials = {{
"""

FOOTER = """    };
} // namespace KCDC::Shared::Game
"""


def read_material(blob):
    """`(isDecal, opacity)` for one `.mtl`, or None when it is not a plain material."""
    try:
        root = ET.fromstring(blob)
    except ET.ParseError:
        return None
    if root.tag != "Material":
        return None

    # A multi-submaterial file has no shader of its own and would apply its
    # first child rather than what the name suggests.
    shader = root.get("Shader")
    if not shader:
        return None

    try:
        opacity = float(root.get("Opacity", "1"))
    except ValueError:
        opacity = 1.0

    return "%DECAL" in root.get("StringGenMask", ""), opacity


def collect(pak, prefixes, want_decal, explicit=()):
    rows = []
    names = [n for n in pak.namelist() if n.lower().endswith(".mtl") and (n.lower().startswith(prefixes) or n.lower() in explicit)]
    for archive_path in sorted(names):
        facts = read_material(pak.read(archive_path))
        if facts is None:
            continue
        is_decal, opacity = facts
        if is_decal != want_decal:
            continue

        # A material is named by its path with the extension dropped, which is
        # what the material manager takes and what the level data itself stores.
        stem = posixpath.splitext(archive_path)[0].lower()
        group = posixpath.dirname(stem).rsplit("/", 1)[-1]
        rows.append((stem, group, opacity, is_decal))
    return rows


def generate(game_directory, output):
    data_path = os.path.join(game_directory, *GAME_DATA_PAK.split("/"))
    object_path = os.path.join(game_directory, *OBJECT_PAK.split("/"))
    for path in (data_path, object_path):
        if not os.path.isfile(path):
            raise SystemExit(f"{path} does not exist; point the generator at a Kingdom Come: Deliverance II install")

    rows = []
    with zipfile.ZipFile(data_path) as pak:
        rows += collect(pak, (DECAL_DIR,), want_decal=True)
        rows += collect(pak, MESH_DIRS, want_decal=False)
    with zipfile.ZipFile(object_path) as pak:
        rows += collect(pak, (), want_decal=False, explicit=MESH_EXTRA)

    if not rows:
        raise SystemExit("no marker materials found; the pak layout has changed")

    rows.sort(key=lambda row: row[0])
    decals = sum(1 for row in rows if row[3])

    lines = [HEADER.format(count=len(rows), decals=decals, meshes=len(rows) - decals)]
    for name, group, opacity, is_decal in rows:
        lines.append(f'        {{"{name}", "{group}", {opacity:.3f}F, {"true" if is_decal else "false"}}},\n')
    lines.append(FOOTER)

    with open(output, "w", encoding="ascii", newline="\n") as handle:
        handle.writelines(lines)
    print(f"Generated {len(rows)} materials ({decals} decal, {len(rows) - decals} mesh): {output}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("game", help="Kingdom Come: Deliverance II install directory")
    parser.add_argument("--output", default=None, help=f"where to write the table (default {DEFAULT_OUTPUT})")
    arguments = parser.parse_args()

    output = arguments.output
    if output is None:
        output = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), DEFAULT_OUTPUT)
    generate(arguments.game, output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
