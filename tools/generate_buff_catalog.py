#!/usr/bin/env python3
"""Generate the KCDC buff table from an installed Kingdom Come: Deliverance II.

Every status effect the game can put on a soul is a row in
`Libs/Tables/rpg/buff*.xml`, keyed by a `buff_id` GUID -- the same GUID
`C_BuffManager::AddBuff` takes. The runtime loads those rows into a
`C_ObjectTableDatabase<S_BuffDefinition, S_BuffDefinitionDBData>` whose sorted
array is enumerable in process, but the server has no game module to enumerate
it from and both sides must agree on the name-to-GUID spelling, so the table is
generated offline and compiled in as `code/shared/generated/buff_catalog.cpp`.

Only the columns replication and scripting need are carried. `duration` comes
across in the unit the row is written in, and `worldTime` records which unit
that is -- see WORLD_TIME_IMPLEMENTATIONS below.

Usage:
    python tools/generate_buff_catalog.py <game directory>
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import xml.etree.ElementTree as ET
import zipfile

TABLES_PAK = os.path.join("Data", "Tables.pak")
BUFF_TABLE_RE = re.compile(r"^Libs/Tables/rpg/buff(__[a-zA-Z0-9_]+)?\.xml$", re.IGNORECASE)
AI_TAG_TABLE = "Libs/Tables/rpg/buff_ai_tag.xml"

DEFAULT_OUTPUT = os.path.join("code", "shared", "generated", "buff_catalog.cpp")

GUID_RE = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$")

# Where each of the 16 bytes of a CryGUID is spelled in the canonical 8-4-4-4-12
# text, as the index of its first hex digit. The game stores the first three
# fields as native little-endian integers and the last eight as single bytes in
# the order written, so those first three come out back to front.
#
# This is the same table `code/shared/game/cry_guid_text.h` carries, and the two
# have to agree: the catalog's `id` column is what `FindBuffById` compares an
# incoming wire id against, and the `static_assert` in `buff_catalog.h` pins
# both spellings to `food_poison`.
GUID_BYTE_DIGITS = (6, 4, 2, 0, 11, 9, 16, 14, 19, 21, 24, 26, 28, 30, 32, 34)


def guid_halves(guid):
    """The (low, high) halves of a CryGUID from its canonical text."""
    halves = [0, 0]
    for index, digit in enumerate(GUID_BYTE_DIGITS):
        halves[index // 8] |= int(guid[digit : digit + 2], 16) << ((index % 8) * 8)
    return halves[0], halves[1]


# The implementations whose `duration` is written in game seconds, because
# their update scales the frame delta by the world-time ratio before adding it.
# Three names omit "WorldTime", so matching that substring is insufficient.
WORLD_TIME_IMPLEMENTATIONS = frozenset(
    {
        "Cpp:WorldTimeTimed",
        "Cpp:PoisoningWorldTimeTimed",
        "Cpp:AdjustableFadingWorldTimeTimed",
        "Cpp:ForgeWellRested",
        "Cpp:Hangover",
        "Cpp:LastGaspShortTerm",
    }
)

HEADER = """// Generated by tools/generate_buff_catalog.py from Data/Tables.pak.
// Do not edit by hand.

#include "shared/game/buff_catalog.h"

namespace KCDC::Shared::Game {{
    // {count} buff definitions across {files} of the game's buff tables.
    const std::vector<BuffEntry> g_Buffs = {{
"""

FOOTER_HEAD = """    };

    // buff_ai_tag.xml, in id order. The index is the native tag id, which is
    // what C_Soul::HasBuffWithAITag and C_BuffManager::RemoveAllBuffsByAITag
    // both take.
    const std::vector<std::string_view> g_BuffAiTags = {
"""

FOOTER_TAIL = """    };
} // namespace KCDC::Shared::Game
"""


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def read_lookup(pak, path, id_attr, name_attr, row_tag):
    """A lookup table as a list indexed by its id column."""
    try:
        root = ET.fromstring(pak.read(path))
    except (KeyError, ET.ParseError) as error:
        print("Skipping {}: {}".format(path, error), file=sys.stderr)
        return []

    rows = {}
    for element in root.iter(row_tag):
        try:
            rows[int(element.get(id_attr))] = element.get(name_attr) or ""
        except (TypeError, ValueError):
            continue
    if not rows:
        return []
    return [rows.get(index, "") for index in range(max(rows) + 1)]


def read_buffs(pak_path):
    """Every buff row in the pak, plus the AI tag names, as (rows, tags, files)."""
    rows = []
    files = 0
    with zipfile.ZipFile(pak_path) as pak:
        for entry in sorted(pak.namelist()):
            if not BUFF_TABLE_RE.match(entry):
                continue

            try:
                root = ET.fromstring(pak.read(entry))
            except ET.ParseError as error:
                print("Skipping {}: {}".format(entry, error), file=sys.stderr)
                continue

            found = root.findall(".//buff")
            if not found:
                continue

            files += 1
            for element in found:
                row = element.attrib
                name = row.get("buff_name") or ""
                guid = (row.get("buff_id") or "").lower()
                if not name or not GUID_RE.match(guid):
                    continue
                rows.append(row)

        tags = read_lookup(pak, AI_TAG_TABLE, "buff_ai_tag_id", "buff_ai_tag_name", "buff_ai_tag")

    return rows, tags, files


def as_int(row, key, default):
    try:
        return int(row.get(key))
    except (TypeError, ValueError):
        return default


def as_float(row, key, default):
    try:
        return float(row.get(key))
    except (TypeError, ValueError):
        return default


def emit(rows, tags, files, output):
    rows = sorted(rows, key=lambda row: row["buff_name"])

    with open(output, "w", encoding="utf-8", newline="\n") as sink:
        sink.write(HEADER.format(count=len(rows), files=files))
        for row in rows:
            duration = as_float(row, "duration", -1.0)
            world = (row.get("implementation") or "") in WORLD_TIME_IMPLEMENTATIONS
            low, high = guid_halves(row["buff_id"].lower())
            sink.write(
                '        {{"{name}", "{guid}", {{0x{low:016X}ULL, 0x{high:016X}ULL}}, "{ui}", {cls}, {tag}, {family}, {excl}, {ui_type}, {lifetime}, {persistent}, {world}, {duration}f}},\n'.format(
                    name=escape(row["buff_name"]),
                    guid=row["buff_id"].lower(),
                    low=low,
                    high=high,
                    ui=escape(row.get("buff_ui_name") or ""),
                    cls=as_int(row, "buff_class_id", 0),
                    tag=as_int(row, "buff_ai_tag_id", -1),
                    family=as_int(row, "buff_family_id", -1),
                    excl=as_int(row, "buff_exclusivity_id", 1),
                    ui_type=as_int(row, "buff_ui_type_id", 0),
                    lifetime=as_int(row, "buff_lifetime_id", 0),
                    persistent="true" if (row.get("is_persistent") or "").lower() == "true" else "false",
                    world="true" if world else "false",
                    duration=repr(duration),
                )
            )
        sink.write(FOOTER_HEAD)
        for tag in tags:
            sink.write('        "{}",\n'.format(escape(tag)))
        sink.write(FOOTER_TAIL)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("game_directory", help="Kingdom Come: Deliverance II install directory")
    parser.add_argument("-o", "--output", default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)

    pak_path = os.path.join(args.game_directory, TABLES_PAK)
    if not os.path.isfile(pak_path):
        print("No {} under {}".format(TABLES_PAK, args.game_directory), file=sys.stderr)
        return 1

    rows, tags, files = read_buffs(pak_path)
    if not rows:
        print("No buff rows found in {}".format(pak_path), file=sys.stderr)
        return 1

    names = set()
    guids = set()
    for row in rows:
        if row["buff_name"] in names or row["buff_id"].lower() in guids:
            print("Duplicate buff key: {}".format(row["buff_name"]), file=sys.stderr)
            return 1
        names.add(row["buff_name"])
        guids.add(row["buff_id"].lower())

    emit(rows, tags, files, args.output)
    print("Wrote {} buffs and {} AI tags from {} tables to {}".format(len(rows), len(tags), files, args.output))
    return 0


if __name__ == "__main__":
    sys.exit(main())
