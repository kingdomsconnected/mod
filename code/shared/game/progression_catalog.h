namespace KCDC::Shared::Game {
    enum class ProgressionTrackKind : std::uint8_t {
        Skill = 0, // E_SoulSkill, the soul's table at C_Soul+0x5E8
        Stat  = 1, // E_SoulStat, the soul's table at C_Soul+0x56C
    };

    /**
     * One skill or stat a player levels, with the curve its levels are bought
     * along.
     *
     * The curve is the engine's own: the XP from level L to L+1 is
     * `xpBase + xpDiff * (L + 1)` (`AdvanceSkillEntryByXP18046A5EC`,
     * `GetStatXPForNextLevel180469C64`), so reaching level L costs
     * `L * (xpBase + xpDiff) + xpDiff * L * (L - 1) / 2` in total
     * (`C_Soul::AddXPFromToSkillLevel`, slot 101).
     *
     * Generated by `tools/generate_progression_catalog.py`.
     */
    struct ProgressionTrack {
        std::string_view name; // skill_name / stat_name, e.g. "weapon_sword"
        ProgressionTrackKind kind;
        std::uint8_t native; // the E_SoulSkill or E_SoulStat the engine takes
        std::uint32_t xpBase;
        std::uint32_t xpDiff;
        std::uint8_t cap;
        std::string_view uiName; // the localisation key the character sheet shows
    };

    /** The side tables that decide what a perk becomes when applied. A perk can be in several. */
    namespace PerkKind {
        inline constexpr std::uint8_t kBuff      = 1 << 0; // perk_buff: a real buff, with the perk as its source
        inline constexpr std::uint8_t kScript    = 1 << 1; // perk_script: checked by name in Lua
        inline constexpr std::uint8_t kTechnique = 1 << 2; // perk_combat_technique: unlocks a move
        inline constexpr std::uint8_t kAbility   = 1 << 3; // perk_soul_ability
        inline constexpr std::uint8_t kParam     = 1 << 4; // perk_rpg_param_override: rewrites an RPG param
        inline constexpr std::uint8_t kCompanion = 1 << 5; // perk_companion: the dog
        inline constexpr std::uint8_t kRecipe    = 1 << 6; // perk_recipe: an alchemy recipe
        inline constexpr std::uint8_t kCodex     = 1 << 7; // perk_codex: a codex entry

        inline constexpr std::size_t kCount              = 8;
        inline constexpr std::string_view kNames[kCount] = {"buff", "script", "technique", "ability", "param", "companion", "recipe", "codex"};
    } // namespace PerkKind

    /** `perk_visibility.xml`. Only Visible perks are on the perk screen. */
    namespace PerkVisibility {
        inline constexpr std::uint8_t kSystemHidden   = 0;
        inline constexpr std::uint8_t kGameplayHidden = 1;
        inline constexpr std::uint8_t kVisible        = 2;
        inline constexpr std::uint8_t kObsolete       = 3;
    } // namespace PerkVisibility

    /** The `tree` of a perk with neither a stat nor a skill selector: the main-level bank. */
    inline constexpr std::int8_t kMainPerkTreeRow = -2;

    /**
     * One row of the game's perk tables (`S_Perk`, 0x78 bytes, column binder
     * `0x1801AEB30`), carrying the columns the server needs to rule on a learn
     * the way `C_PerkList::TryMakePerkAvailable` does.
     */
    struct PerkEntry {
        std::string_view name; // perk_name, unique across the tables
        std::string_view guid; // perk_id, canonical 8-4-4-4-12, lower case
        RPC::PerkGuid id;      // the same GUID as the engine's bytes
        std::string_view uiName;

        std::int16_t parent;        // catalog index of parent_id, or -1
        std::int8_t tree;           // track index of its selector, kMainPerkTreeRow, or -1 for a selector no track shows
        std::uint8_t statSelector;  // E_SoulStat, 10 for none
        std::uint8_t skillSelector; // E_SoulSkill, 35 for none
        std::uint8_t level;         // the tree level it needs
        std::uint8_t visibility;    // PerkVisibility
        std::uint8_t kinds;         // PerkKind bits
        bool autolearnable;
    };

    struct PerkExclusivity {
        std::uint16_t first;
        std::uint16_t second;
    };

    /** Skills then stats; the index is the wire's track. */
    extern const std::span<const ProgressionTrack> g_ProgressionTracks;

    /** Every perk the game ships, sorted by name; the index is the wire's perk. */
    extern const std::span<const PerkEntry> g_Perks;

    extern const std::span<const PerkExclusivity> g_PerkExclusivity;

    /** E_SoulSkill 2. Never earned: `RecomputeInducedSkill18046A684` derives it from the five weapon skills. */
    inline constexpr std::uint8_t kFencingSkill = 2;

    /** A track's index by its name, or -1. */
    inline int FindProgressionTrack(std::string_view name) {
        for (std::size_t index = 0; index < g_ProgressionTracks.size(); ++index) {
            if (g_ProgressionTracks[index].name == name) {
                return static_cast<int>(index);
            }
        }
        return -1;
    }

    /** The track the engine calls `native` of `kind`, or -1 for one the player's tables hide. */
    inline int FindProgressionTrack(ProgressionTrackKind kind, std::uint32_t native) {
        for (std::size_t index = 0; index < g_ProgressionTracks.size(); ++index) {
            if (g_ProgressionTracks[index].kind == kind && g_ProgressionTracks[index].native == native) {
                return static_cast<int>(index);
            }
        }
        return -1;
    }

    inline bool IsInducedTrack(std::size_t track) {
        return track < g_ProgressionTracks.size() && g_ProgressionTracks[track].kind == ProgressionTrackKind::Skill && g_ProgressionTracks[track].native == kFencingSkill;
    }

    /** Q7 XP from level 0 to `level`, the way `C_Soul::AddXPFromToSkillLevel` sums it. */
    inline std::uint64_t TotalXpQ7ForLevel(const ProgressionTrack &track, std::uint32_t level) {
        const std::uint64_t l = level;
        return (l * (track.xpBase + track.xpDiff) + (l > 0 ? track.xpDiff * l * (l - 1) / 2 : 0)) * 128;
    }

    /** Q7 XP a soul holding `state` has earned on the track since level 0. */
    inline std::uint64_t TotalXpQ7(const ProgressionTrack &track, const RPC::TrackState &state) {
        return TotalXpQ7ForLevel(track, state.level) + state.xpQ7;
    }

    /** Q7 XP from `level` to the next one. */
    inline std::uint64_t XpQ7ToNextLevel(const ProgressionTrack &track, std::uint32_t level) {
        return (static_cast<std::uint64_t>(track.xpBase) + static_cast<std::uint64_t>(track.xpDiff) * (level + 1)) * 128;
    }

    /** Canonical level and remainder, including cap: capped tracks hold zero remainder. */
    inline RPC::TrackState ProgressFromTotalXpQ7(const ProgressionTrack &track, std::uint64_t total) {
        RPC::TrackState state;
        while (state.level < track.cap && total >= XpQ7ToNextLevel(track, state.level)) {
            total -= XpQ7ToNextLevel(track, state.level);
            ++state.level;
        }
        state.xpQ7 = state.level < track.cap ? static_cast<std::uint32_t>(total) : 0;
        return state;
    }

    /** The perk-point bank a perk spends from, as `C_PerkLearningState::LearnPerk` picks it, or -1. */
    inline int PerkTreeOf(const PerkEntry &perk) {
        if (perk.tree == kMainPerkTreeRow) {
            return RPC::kMainPerkTree;
        }
        return perk.tree;
    }

    inline const PerkEntry *FindPerkByGuid(std::string_view guid) {
        for (const auto &perk : g_Perks) {
            if (perk.guid == guid) {
                return &perk;
            }
        }
        return nullptr;
    }

    inline const PerkEntry *FindPerkByName(std::string_view name) {
        for (const auto &perk : g_Perks) {
            if (perk.name == name) {
                return &perk;
            }
        }
        return nullptr;
    }

    /** A GUID or an exact name. */
    inline const PerkEntry *ResolvePerk(std::string_view query) {
        const PerkEntry *byGuid = FindPerkByGuid(query);
        return byGuid != nullptr ? byGuid : FindPerkByName(query);
    }

    inline std::uint16_t PerkIndexOf(const PerkEntry &perk) {
        return static_cast<std::uint16_t>(&perk - g_Perks.data());
    }

    inline const PerkEntry *PerkAt(std::size_t index) {
        return index < g_Perks.size() ? &g_Perks[index] : nullptr;
    }

    /**
     * The catalog index of an engine GUID, or `RPC::kNoPerk`.
     *
     * A binary search over an index sorted once on first use: the digest
     * asks it for every owned perk, and `C_Soul::HasPerk` on a puppet asks
     * it from whatever thread the game queries on. Magic statics initialise
     * thread-safely.
     */
    inline std::uint16_t FindPerkIndex(const RPC::PerkGuid &id) {
        static const std::vector<std::pair<RPC::PerkGuid, std::uint16_t>> byGuid = [] {
            std::vector<std::pair<RPC::PerkGuid, std::uint16_t>> index;
            index.reserve(g_Perks.size());
            for (std::size_t i = 0; i < g_Perks.size(); ++i) {
                index.emplace_back(g_Perks[i].id, static_cast<std::uint16_t>(i));
            }
            std::sort(index.begin(), index.end(), [](const auto &left, const auto &right) {
                return left.first.low != right.first.low ? left.first.low < right.first.low : left.first.high < right.first.high;
            });
            return index;
        }();

        const auto found = std::lower_bound(byGuid.begin(), byGuid.end(), id, [](const auto &entry, const RPC::PerkGuid &wanted) {
            return entry.first.low != wanted.low ? entry.first.low < wanted.low : entry.first.high < wanted.high;
        });
        return found != byGuid.end() && found->first == id ? found->second : RPC::kNoPerk;
    }

    /** The exclusive partner of a perk, or `RPC::kNoPerk`. */
    inline std::uint16_t ExclusivePartnerOf(std::uint16_t perk) {
        for (const PerkExclusivity &pair : g_PerkExclusivity) {
            if (pair.first == perk) {
                return pair.second;
            }
            if (pair.second == perk) {
                return pair.first;
            }
        }
        return RPC::kNoPerk;
    }

    inline constexpr RPC::PerkGuid PerkGuidFromText(std::string_view guid) {
        RPC::PerkGuid id;
        CryGuidFromText(guid, id.low, id.high);
        return id;
    }

    // Pinned on `Featherweight` as the perk table writes it, so a change that
    // breaks the encoding fails to compile.
    static_assert(PerkGuidFromText("010b08c7-5346-402c-a7cb-a084d624b62e") == RPC::PerkGuid {0x402C5346010B08C7ULL, 0x2EB624D684A0CBA7ULL}, "Perk GUID encoding does not match the game's own parser");
} // namespace KCDC::Shared::Game
