#pragma once

#include <string_view>
#include <vector>

namespace KCDC::Shared::Game {
    /** Somewhere in the world worth teleporting to. */
    struct PointOfInterest {
        std::string_view name;  // English name, what the browser lists
        std::string_view group; // browsing bucket: `Map locations`, or a settlement
        std::string_view level; // level pak name the coordinates belong to
        float x = 0.0F;
        float y = 0.0F;
        float z = 0.0F; // walkable ground, per the level's own navmesh
    };

    /**
     * Every point of interest the shipped levels describe.
     *
     * The map locations of `Libs/Tables/rpg/location.xml` and the settlement
     * districts of the levels' own `EditorLayer` paths, each placed on the
     * densest cluster of ground markers it contains.
     *
     * The coordinates are level-local and the three levels overlap, so a
     * point only means anything while its own level is loaded -- which is
     * what `level` is for.
     *
     * Sorted by level, then map locations before districts, then by group and
     * name, so a group is one contiguous run of rows.
     *
     * Generated by `tools/generate_poi_catalog.py`; the location tables are
     * level data, not something the running game exposes as a list.
     */
    extern const std::vector<PointOfInterest> g_PointsOfInterest;
} // namespace KCDC::Shared::Game
