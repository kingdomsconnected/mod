#pragma once

#include <cstdint>
#include <vector>

namespace KCDC::Shared::Game {
    /**
     * A Mannequin fragment a player's body plays that other players are shown:
     * a stance transition (`SitDown`, `StandUp`, `LieDown`, `GetUp`) or one of
     * the game's own interaction animations (`Picking`, `PickingHerbs`,
     * `WallLook`, ...). What is in the list and why the rest is not is written
     * down in `tools/generate_body_action_catalog.py`.
     */
    struct BodyActionEntry {
        // The CRC-32 of the fragment's lowercase name, which is how Mannequin
        // keys it and how it crosses the wire.
        std::uint32_t crc;
        const char *fragment;

        // Whether any variant loops. A looping action does not end by itself,
        // so receivers stop theirs when the owner's ends.
        bool looped;
    };

    // Generated by `tools/generate_body_action_catalog.py`, sorted by CRC.
    extern const std::vector<BodyActionEntry> g_BodyActions;

    /** The body action with that fragment CRC, or null. */
    inline const BodyActionEntry *FindBodyAction(std::uint32_t crc) {
        for (const auto &entry : g_BodyActions) {
            if (entry.crc == crc) {
                return &entry;
            }
        }
        return nullptr;
    }
} // namespace KCDC::Shared::Game
