#pragma once

#include "shared/game/prefab_property.h"

#include <cstddef>
#include <string_view>
#include <vector>

namespace KCDC::Shared::Game {
    /**
     * One entity of a cart, as its prefab describes it.
     *
     * The transform is prefab-local and relative to `parent`, or to the
     * prefab's origin when that is -1. Everything a spawner needs is here, so
     * a blueprint is walked front to back: a part's parent always precedes it.
     */
    struct CartPart {
        std::string_view name;        // the prefab's own name, for logs
        std::string_view entityClass; // `GeomEntity`, `WHCart` or `WHCartMountPoint`
        std::string_view geometry;    // `objects/...cgf`, empty for the two WH classes
        int parent = -1;              // index into the blueprint's parts, -1 for a root

        float posX = 0.0F, posY = 0.0F, posZ = 0.0F;
        float rotX = 0.0F, rotY = 0.0F, rotZ = 0.0F, rotW = 1.0F;
        float scaleX = 1.0F, scaleY = 1.0F, scaleZ = 1.0F;

        /** The prefab's `Properties`, given to the entity before it is initialised, as the level loader gives them. */
        const PrefabProperty *properties = nullptr;
        std::size_t propertyCount        = 0;
    };

    /** A cart the mod can spawn, and the tree it comes up as. */
    struct CartBlueprint {
        std::string_view name;       // the prefab's file stem, e.g. `wagon_b_covered_empty`
        std::string_view prefabGuid; // the editor's prefab id, for tracing a blueprint back
        const CartPart *parts = nullptr;
        std::size_t partCount = 0;
    };

    /**
     * Every cart and wagon the game ships a prefab for.
     *
     * A cart is a tree rather than an entity: an axel, a body, four wheels, the
     * `WHCart` entity whose extension owns the seats and the harness, and the
     * mount points that raise the game's own prompt. This is that tree, mined
     * out of `Prefabs/manmade/vehicles/` in `Data/IPL_GameData.pak`, minus the
     * AI fittings and the brush cargo a spawned cart cannot have.
     *
     * Generated by `tools/generate_cart_catalog.py`; the prefab library is
     * editor data with no in-process enumerator to read at runtime.
     */
    extern const std::vector<CartBlueprint> g_CartBlueprints;

    /** The blueprint of that name, or null when the catalog has no such cart. */
    const CartBlueprint *FindCartBlueprint(std::string_view name);

    /**
     * What a spawn falls back to when the caller names no blueprint.
     *
     * A covered wagon on a chassis that can be hitched, with a driver's bench.
     *
     * Of the twenty-seven blueprints, twenty-six are built on
     * `wagon_b_axel.cgf`, `wagon_b_axel_lowered.cgf` or
     * `cart_b_front_part.cgf`, and every one of those carries the
     * `slt_horse_left` and `slt_horse_right` helpers the engine hitches a
     * horse by. The odd one out is `wagon_b_covered_empty`, whose
     * `wagon_b_covered_axel.cgf` has no helpers at all, so no horse can be
     * put in front of it.
     */
    inline constexpr std::string_view kDefaultCartBlueprint = "wagon_b_covered";

    /**
     * The part the engine treats as the cart: the `GeomEntity` its `WHCart`
     * hangs off, one or two parents up. `C_Cart::SetupCartOnReset`
     * (`0x180F8F588`) walks from the `WHCart` to its parent, and one more step
     * when that parent has one, and builds the follower model only when the
     * part it lands on is a `GeomEntity`. Its world transform is the one the
     * engine's cart movement writes, so every other part rides on it.
     *
     * -1 when the blueprint has no `WHCart`, which the catalog test forbids.
     */
    inline int FindCartChassis(const CartBlueprint &blueprint) {
        for (std::size_t index = 0; index < blueprint.partCount; ++index) {
            const CartPart &part = blueprint.parts[index];
            if (part.entityClass != "WHCart" || part.parent < 0) {
                continue;
            }
            const CartPart &parent = blueprint.parts[part.parent];
            const int chassis      = parent.parent >= 0 ? parent.parent : part.parent;
            return blueprint.parts[chassis].entityClass == "GeomEntity" ? chassis : -1;
        }
        return -1;
    }

    /**
     * How many horses the chassis is harnessed for: the `slt_horse_left` and
     * `slt_horse_right` helpers its mesh carries, which is what
     * `C_Cart::HitchHorseToPath` needs for a slot (`HasHarnessHelper`,
     * `0x1828D4BB4`).
     *
     * Two for a wagon's pole, one for the two-wheeler's shafts, where the
     * game hitches a single animal on the left slot. None for
     * `wagon_b_covered_axel.cgf`, which ships no helpers: a wagon on that
     * chassis can be sat in but never pulled, because the engine ticks a
     * cart's movement from the horse in its shafts.
     */
    inline int CartHarnessSlots(const CartBlueprint &blueprint) {
        const int chassis = FindCartChassis(blueprint);
        if (chassis < 0) {
            return 0;
        }
        const std::string_view geometry = blueprint.parts[chassis].geometry;
        if (geometry.ends_with("wagon_b_covered_axel.cgf")) {
            return 0;
        }
        return geometry.ends_with("cart_b_front_part.cgf") ? 1 : 2;
    }
} // namespace KCDC::Shared::Game
