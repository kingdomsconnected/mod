#pragma once

#include "shared/game/appearance_catalog.h"

#include <span>
#include <string_view>

namespace KCDC::Shared::Game {
    /**
     * One of the game's own outfits: a named list of item class GUIDs, and
     * the gender it was authored for. The game refuses clothing on a soul
     * whose archetype gender the item's armor record does not allow
     * (`S_ArmorItemClass::IsWearableBySoul`, 0x1805CBD4C), so a preset only
     * dresses bodies of its own gender.
     */
    struct ClothingPresetEntry {
        std::string_view name;
        std::string_view guid;
        AppearanceGender gender;
        std::span<const std::string_view> itemGuids;
    };

    /**
     * Outfits a spawned actor can be dressed in.
     *
     * A KCD2 actor wears what its inventory holds and its equipment manager
     * has equipped; a soul supplies identity and appearance but no clothes.
     * These are the game's own presets from `Libs/Tables/item/clothing_preset*.xml`,
     * whose item class GUIDs are what `C_Inventory::CreateItems` takes.
     *
     * Generated by `tools/generate_clothing_catalog.py`; the preset database
     * has no recovered in-process enumerator to read at runtime.
     */
    extern const std::span<const ClothingPresetEntry> g_ClothingPresets;

    /** Preset for a `clothing_preset_id`, or null when the guid is unknown. */
    const ClothingPresetEntry *FindClothingPreset(std::string_view guid);
} // namespace KCDC::Shared::Game
