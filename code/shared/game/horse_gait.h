#pragma once

#include <algorithm>
#include <cmath>
#include <cstdint>
#include <string_view>
#include <vector>

namespace KCDC::Shared::Game {
    /**
     * One of a horse's move styles: the gaits the game picks between by
     * speed.
     *
     * `HorseRuntimeData::ApplyRuntimePaceAndDelta` (0x1806CF3D4) states a
     * horse's pace as `C_RPGMovement::GetMoveStyleForSpeed` (0x181FD3AB0) of
     * its runtime speed, plus one: the first style whose speed is at least
     * the runtime speed, or the last. The pace sets the style's Mannequin
     * tag, and the tag picks the gait's blendspace. So the gait a horse shows
     * follows the speed it is asked to move at, whatever its rider
     * commanded.
     *
     * Generated by `tools/generate_horse_gait_catalog.py` from the `Horse`
     * archetype's rows of `Libs/Tables/rpg/soul_archetype_movement.xml`.
     */
    struct HorseMoveStyleEntry {
        /** `logical_speed`: the style id a rider's command and the pace use; 0 walk .. 3 dash. */
        std::int32_t styleId;

        /** `mn_tag`: the Mannequin tag the style's pace sets -- walk, run, sprint, dash. */
        std::string_view gait;

        /**
         * `real_speed_min` and `real_speed_max`: what a soul's own speed in this
         * style is clamped between (`C_RPGMovement::GetMoveStyleSpeed`,
         * 0x181FD3420). Its maximum is where the next style takes over for a
         * horse with full speed; a slower soul's switch comes sooner.
         */
        float realSpeedMin;
        float realSpeedMax;
    };

    /**
     * One locomotion blendspace the horse's Mannequin database plays for a
     * gait, and what it can show.
     *
     * Each is one clip at a range of playback scales over a MoveSpeed and a
     * TurnSpeed axis. CryEngine clamps the parameters to the axis range.
     * Outside that range, the animation stays at its end value while the
     * body moves at the requested speed, so the feet slide. These axis
     * ranges are narrowed to the examples that state their own value.
     *
     * Generated by `tools/generate_horse_gait_catalog.py` from
     * `kcd_horse_database.adb` and the `.bspace` files the horse's
     * `.chrparams` points at.
     */
    struct HorseGaitBlendspaceEntry {
        std::string_view blendspace;

        /** The fragment's tags: the gait's, and `player+smoothRider` or `cart` for a variant. */
        std::string_view tags;

        /** Which move style's tag among them. */
        std::string_view gait;

        float moveSpeedMin;
        float moveSpeedMax;
        float turnSpeedMin;
        float turnSpeedMax;
    };

    extern const std::vector<HorseMoveStyleEntry> g_HorseMoveStyles;
    extern const std::vector<HorseGaitBlendspaceEntry> g_HorseGaitBlendspaces;

    /**
     * What a ridden or riderless horse in one move style can be shown doing
     * without its feet sliding: the speeds every non-cart blendspace of the
     * gait covers, held inside the speeds that keep the game on the same
     * style, and the turn rate all of them cover.
     */
    struct HorseGaitBand {
        std::int32_t styleId = -1;
        float moveSpeedMin   = 0.0F;
        float moveSpeedMax   = 0.0F;
        float turnSpeedMax   = 0.0F; // rad/s either way
    };

    /** The move style the game moves a horse at `speed` in, with the table's own switch speeds. */
    std::int32_t HorseMoveStyleForSpeed(float speed);

    /** The band of a move style; a style id past the table is taken as the last. */
    HorseGaitBand HorseGaitBandFor(std::int32_t styleId);

    /**
     * The speed a horse's copy is asked for, `wanted` being its owner's speed
     * with the gap along the owner's path closed in it, kept inside what the
     * gait can show.
     *
     * Moving, the band is the one the owner's speed is in, widened to the
     * owner's speed itself where that is outside it -- the copy never slides
     * more than its owner does. The rest of the gap is left for the next
     * frames and, past the snap, a placement.
     *
     * With the owner halted the copy is either standing or walking up to
     * where it stands, and a walk has a slowest pace: anything slower than
     * the walk band but more than nothing is walked at that pace.
     */
    inline float ClampHorseFollowSpeed(float ownerSpeed, bool ownerHalted, float wanted, const HorseGaitBand &band) {
        if (!(wanted > 0.0F)) {
            return 0.0F;
        }
        const float floor   = ownerHalted ? band.moveSpeedMin : std::min(band.moveSpeedMin, ownerSpeed);
        const float ceiling = ownerHalted ? band.moveSpeedMax : std::max(band.moveSpeedMax, ownerSpeed);
        return std::clamp(wanted, floor, ceiling);
    }

    /**
     * The facing a copy is turned to this frame: `current` moved toward
     * `target` by no more than `maxRate` (rad/s) over `dtSeconds`.
     * Past `snapRadians` of error the target is taken whole: the clip
     * cannot animate a turn
     * that size anyway, and chasing it at the gait's rate left a copy
     * facing the wrong way for a second. Angles in radians; a frame of no
     * length leaves the facing where it is.
     */
    inline float StepHorseHeading(float current, float target, float maxRate, float dtSeconds, float snapRadians) {
        const float error = std::remainderf(target - current, 6.2831853F);
        if (std::fabs(error) >= snapRadians) {
            return target;
        }
        if (!(dtSeconds > 0.0F)) {
            return current;
        }
        const float step = maxRate * dtSeconds;
        return current + std::clamp(error, -step, step);
    }

    /**
     * Moves the copy's steering bend -- the angle its heading is turned off
     * the owner's toward the owner's line -- toward `wantedBend`, no faster
     * than the gait's turn range leaves over once the owner's own turn is
     * played. `ownerTurnRate` is in rad/s, `dtSeconds` the frame's length;
     * a frame of no length leaves the bend where it was.
     */
    inline float LimitHorseSteerBend(float previousBend, float wantedBend, float ownerTurnRate, float dtSeconds, const HorseGaitBand &band) {
        if (!(dtSeconds > 0.0F)) {
            return previousBend;
        }
        const float headroom = std::max(0.0F, band.turnSpeedMax - std::fabs(ownerTurnRate));
        const float step     = headroom * dtSeconds;
        return previousBend + std::clamp(wantedBend - previousBend, -step, step);
    }
} // namespace KCDC::Shared::Game
