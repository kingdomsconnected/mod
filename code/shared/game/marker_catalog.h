#pragma once

#include <cstddef>
#include <string_view>
#include <vector>

namespace KCDC::Shared::Game {
    /** One material a marker can be drawn with. */
    struct MarkerMaterialEntry {
        /** `materials/decals/chalk_cross` -- a material path with the extension dropped. */
        std::string_view name;

        /** The folder it came out of, for listing rather than lookup. */
        std::string_view group;

        /** Authored `Opacity`. The signage materials sit at 0.3 and wash out over bright ground. */
        float opacity;

        /**
         * Whether this declares `%DECAL` and so renders in the deferred decal
         * pass.
         *
         * The two kinds are not interchangeable and the failure is silent: a
         * decal material on a mesh draws no surface and instead blends into the
         * G-buffer of the geometry behind it, which reads as the lighting of
         * everything nearby going wrong rather than as a missing marker.
         */
        bool decal;
    };

    /**
     * Every material a marker can use, sorted by name.
     *
     * The index into this vector is what crosses the wire, so appending is safe
     * and reordering is a wire break. The catalog exists because the server has
     * no material manager to ask.
     *
     * Decals come from `Materials/decals/`, which the engine preloads whole, so
     * every row resolves without a load. Mesh materials come from the game's
     * designer-visualisation sets, which are authored as translucent coloured
     * volumes.
     *
     * Generated by `tools/generate_marker_catalog.py`.
     */
    extern const std::vector<MarkerMaterialEntry> g_MarkerMaterials;

    inline constexpr std::size_t kNoMarkerMaterial = static_cast<std::size_t>(-1);

    /** The row at `index`, or null once it is off the end of the catalog. */
    inline const MarkerMaterialEntry *MarkerMaterialAt(std::size_t index) {
        return index < g_MarkerMaterials.size() ? &g_MarkerMaterials[index] : nullptr;
    }

    /** The row named exactly `name`, or `kNoMarkerMaterial`. Exact: these are the strings the game's own data spells. */
    inline std::size_t FindMarkerMaterialIndex(std::string_view name) {
        if (name.empty()) {
            return kNoMarkerMaterial;
        }

        for (std::size_t index = 0; index < g_MarkerMaterials.size(); ++index) {
            if (g_MarkerMaterials[index].name == name) {
                return index;
            }
        }
        return kNoMarkerMaterial;
    }

    /** Whether `index` names a material the shape asking for it can be drawn with. */
    inline bool MarkerMaterialSuits(std::size_t index, bool wantDecal) {
        const MarkerMaterialEntry *entry = MarkerMaterialAt(index);
        return entry != nullptr && entry->decal == wantDecal;
    }
} // namespace KCDC::Shared::Game
