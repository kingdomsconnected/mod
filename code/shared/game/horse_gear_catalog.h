#pragma once

#include "shared/item_stack.h"

#include <cstddef>
#include <cstdint>
#include <string>
#include <span>
#include <string_view>

namespace KCDC::Shared::Game {
    /**
     * The four places the game's horse inventory screen puts gear.
     *
     * `equipment_slot.xml`'s horse_saddle, horse_head, horse_torso and
     * horse_shoe, in the order a horse is dressed: a caparison needs a saddle
     * under it (`RequiresFilledSlot="horse_saddle"`), so the saddle goes first.
     */
    enum class HorseGearSlot : std::uint8_t {
        Saddle = 0,
        Head   = 1,
        Torso  = 2,
        Shoe   = 3,
    };

    inline constexpr std::size_t kHorseGearSlotCount = 4;

    /**
     * One item class a horse can wear.
     *
     * Horse gear is plain `<Armor>`, rendered by the clothing system the way a
     * person's clothes are, so what makes an item gear is only that its
     * clothing lives under the `Horse` component of `CharacterComponent.xml`.
     * The slot is the one the archetype it inherits there names. There is no
     * saddlebag item: the bags are joints on the saddle's own model, and the
     * capacity they add is the saddle's equip buff.
     *
     * Generated by `tools/generate_horse_gear_catalog.py`.
     */
    struct HorseGearEntry {
        /** The item class name, e.g. `BasicSaddle01_m01`. */
        std::string_view name;

        /** The item class GUID, as the tables write it. */
        std::string_view guid;

        HorseGearSlot slot;
    };

    extern const std::span<const HorseGearEntry> g_HorseGear;

    /**
     * One of the game's own sets of horse tack: a clothing preset made of
     * horse gear alone. The game hands them out through inventory presets on
     * its level horses -- a named horse's shares its soul's name
     * (`kgru_buresHorse`), a generic one draws a child of
     * `equipment_horse_common` -- and every one of them fits the slot rules.
     */
    struct HorseGearPresetEntry {
        std::string_view name;
        std::span<const std::string_view> itemGuids;
    };

    extern const std::span<const HorseGearPresetEntry> g_HorseGearPresets;

    /** What `equipment_horse_common` draws one of: the tack of the game's generic horses. */
    extern const std::span<const std::string_view> g_CommonHorseGearPresets;

    /** `saddle`, `head`, `torso` or `shoe`: what a script names a slot. */
    std::string_view HorseGearSlotName(HorseGearSlot slot);

    /** The slot a script named, false for anything else. */
    bool ParseHorseGearSlot(std::string_view name, HorseGearSlot &out);

    /** The gear with this item class, or null when it is not horse gear. */
    const HorseGearEntry *FindHorseGear(const RPC::ItemClassId &itemClass);

    /** The gear with this item class name or GUID (case-insensitive), or null. */
    const HorseGearEntry *FindHorseGear(std::string_view nameOrGuid);

    /** What one horse wears: at most one piece per slot. */
    struct HorseGear {
        const HorseGearEntry *slots[kHorseGearSlotCount] = {};

        const HorseGearEntry *&At(HorseGearSlot slot) {
            return slots[static_cast<std::size_t>(slot)];
        }

        const HorseGearEntry *At(HorseGearSlot slot) const {
            return slots[static_cast<std::size_t>(slot)];
        }

        bool operator==(const HorseGear &) const = default;
    };

    /** Why a gear set was refused. */
    enum class HorseGearError : std::uint8_t {
        None,

        /** The packed text is not a whole number of item classes, or not hex. */
        Malformed,

        /** A class that is not horse gear. */
        NotHorseGear,

        /** Two pieces for one slot. */
        SlotTaken,

        /** A caparison with no saddle to lie on. */
        TorsoWithoutSaddle,
    };

    std::string_view HorseGearErrorText(HorseGearError error);

    /** Hex digits one item class takes in the packed wire string. */
    inline constexpr std::size_t kPackedHorseGearWidth = 32;

    /** The longest packed string a valid set can be. */
    inline constexpr std::size_t kMaxPackedHorseGear = kPackedHorseGearWidth * kHorseGearSlotCount;

    /**
     * The wire text for a gear set: each class as 32 hex digits, low then high
     * half, in slot order -- the format `HumanEntity::equipment` uses, so a
     * client dresses a horse with the same helper it dresses a person with.
     */
    std::string PackHorseGear(const HorseGear &gear);

    /** The item class the wire text holds at `offset`; false when malformed or short. */
    bool ReadPackedItemClass(std::string_view packed, std::size_t offset, RPC::ItemClassId &out);

    /**
     * Reads a packed set, checking every class is gear, one per slot, and a
     * torso only over a saddle. The order on the wire does not matter.
     */
    HorseGearError UnpackHorseGear(std::string_view packed, HorseGear &out);

    /** The same checks on a set built some other way. */
    HorseGearError ValidateHorseGear(const HorseGear &gear);

    /** The preset with this name (case-insensitive), or null. */
    const HorseGearPresetEntry *FindHorseGearPreset(std::string_view name);

    /** The gear a preset puts on, under the same checks as a report. */
    HorseGearError HorseGearFromPreset(const HorseGearPresetEntry &preset, HorseGear &out);
} // namespace KCDC::Shared::Game
