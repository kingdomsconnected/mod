#pragma once

#include <algorithm>
#include <cstddef>
#include <cstdint>
#include <string_view>
#include <vector>

namespace KCDC::Shared::Game {
    /**
     * Which body-description slot an option fills, as the game's own part
     * indices -- `C_Soul::SetBodyDescriptionPart` takes these directly.
     *
     * Index 4, `Underwear`, is absent: it names a Clothing component, and
     * clothing already replicates as equipped items.
     */
    enum class AppearancePart : std::uint8_t {
        Body  = 0,
        Head  = 1,
        Hair  = 2,
        Beard = 3,
        Count = 4,
    };

    /**
     * Which human root of the character-component tree an option came from.
     * A soul's gender is not part of its body description -- it comes from
     * the archetype -- but it partitions the tree, so every lookup is keyed
     * on both.
     */
    enum class AppearanceGender : std::uint8_t {
        Male   = 0,
        Female = 1,
    };

    /** One selectable node of the game's character-component tree. */
    struct AppearanceOption {
        /** Exactly what goes into the body-description slot. */
        std::string_view name;

        /**
         * The node this is derived from, empty at the top. Colour variants
         * share a group with the style they recolour.
         */
        std::string_view group;

        AppearancePart part;
        AppearanceGender gender;
    };

    /** Which of `g_AppearanceBeardSets` one head's assets carry. */
    struct AppearanceHeadBeards {
        /** A `Head` option's name. */
        std::string_view head;

        AppearanceGender gender;

        std::size_t beardSet;
    };

    /**
     * Every appearance a player can be given, for the two human roots.
     * Generated by `tools/generate_appearance_catalog.py`; the tree has no
     * recovered in-process enumerator.
     */
    extern const std::vector<AppearanceOption> g_AppearanceOptions;

    /**
     * The beard lists heads point at, deduplicated.
     *
     * A beard's `.skin` lives under the head's own folder, so the engine
     * builds its path from the face and one nobody modelled for that face
     * loads nothing at all. The 164 generic faces share one list of 24,
     * Henry's head carries the 15 the barber offers, and 14 heads carry none.
     */
    extern const std::vector<std::vector<std::string_view>> g_AppearanceBeardSets;

    /** Every head, and which of those lists it wears. */
    extern const std::vector<AppearanceHeadBeards> g_AppearanceHeadBeards;

    /**
     * What a soul with no head of its own resolves to, from the game's
     * `ClothingConfig`. Both human rows agree, so one name answers for the
     * gender.
     */
    extern const std::string_view kDefaultMaleHead;
    extern const std::string_view kDefaultFemaleHead;

    inline std::string_view DefaultAppearanceHead(AppearanceGender gender) {
        return gender == AppearanceGender::Female ? kDefaultFemaleHead : kDefaultMaleHead;
    }

    /** The option with this exact name, or null. */
    const AppearanceOption *FindAppearanceOption(AppearancePart part, AppearanceGender gender, std::string_view name);

    /**
     * Whether the game would resolve this name. Empty is valid and means
     * "leave the slot alone", so a partial appearance is a legitimate one.
     *
     * A beard also needs the head wearing it; that is `IsBeardOnHead`.
     */
    inline bool IsAppearanceName(AppearancePart part, AppearanceGender gender, std::string_view name) {
        return name.empty() || FindAppearanceOption(part, gender, name) != nullptr;
    }

    /**
     * The beards whose geometry the game shipped for one head, in catalog
     * order. An empty head means the one a soul with no head of its own
     * resolves to; a head outside the catalog, and the whole female tree,
     * have none.
     */
    const std::vector<std::string_view> &AppearanceBeardsForHead(AppearanceGender gender, std::string_view head);

    /** Whether this head can actually wear this beard. Empty is always yes. */
    inline bool IsBeardOnHead(AppearanceGender gender, std::string_view head, std::string_view beard) {
        if (beard.empty()) {
            return true;
        }
        const std::vector<std::string_view> &wearable = AppearanceBeardsForHead(gender, head);
        return std::find(wearable.begin(), wearable.end(), beard) != wearable.end();
    }
} // namespace KCDC::Shared::Game
