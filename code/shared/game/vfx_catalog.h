#pragma once

#include <cstddef>
#include <string_view>
#include <vector>

namespace KCDC::Shared::Game {
    /** One particle effect `CParticleManager::FindEffect` resolves. */
    struct VfxEffectEntry {
        /** `WH_Particels.fires.torch_a` -- what FindEffect takes, spelled as the library spells it. */
        std::string_view name;

        /** The part before the first dot. FindEffect loads `Libs/Particles/<library>.xml` on demand from it. */
        std::string_view library;

        /** The authored bucket inside the library -- `fires`, `smokes`, `combat` -- for listing, not for lookup. */
        std::string_view group;

        /** Largest `CameraMaxDistance` in the effect's tree, in metres, or 0 when no emitter declares one. */
        float viewDistance;

        /** Whether any emitter in the tree loops. A continuous effect never ends on its own. */
        bool continuous;
    };

    /**
     * Every particle effect the game ships, sorted by name.
     *
     * The index into this vector is what crosses the wire, so appending is safe
     * and reordering is a wire break. The catalog exists because the server has
     * no particle manager to ask: it is what lets one refuse a name no client
     * could have resolved, and size a burst's relay radius against the distance
     * the engine would have culled the effect at anyway.
     *
     * Generated by `tools/generate_vfx_catalog.py` from the libraries under
     * `Libs/Particles/` in `Data/IPL_GameData.pak`; the running game offers no
     * enumerator over them.
     */
    extern const std::vector<VfxEffectEntry> g_VfxEffects;

    /** Sentinel for a query naming no effect. */
    inline constexpr std::size_t kNoVfxEffect = static_cast<std::size_t>(-1);

    /** The row whose name is exactly `name`, or `kNoVfxEffect`. Exact: these are the strings the game's own data spells. */
    inline std::size_t FindVfxEffectIndex(std::string_view name) {
        if (name.empty()) {
            return kNoVfxEffect;
        }

        for (std::size_t index = 0; index < g_VfxEffects.size(); ++index) {
            if (g_VfxEffects[index].name == name) {
                return index;
            }
        }
        return kNoVfxEffect;
    }

    /** The row at `index`, or null once it is off the end of the catalog. */
    inline const VfxEffectEntry *VfxEffectAt(std::size_t index) {
        return index < g_VfxEffects.size() ? &g_VfxEffects[index] : nullptr;
    }
} // namespace KCDC::Shared::Game
