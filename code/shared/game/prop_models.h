#pragma once

#include <cstddef>
#include <span>
#include <string_view>

namespace KCDC::Shared::Game {
    /** One static mesh the mod can put into an entity's render slot. */
    struct PropModelEntry {
        std::string_view path;  // `objects/...cgf`, what LoadGeometry takes
        std::string_view group; // browsing bucket, e.g. `manmade/structures`
        std::string_view name;  // file stem, what the browser lists
    };

    /**
     * Every static mesh the game ships that is worth spawning.
     *
     * The path is what `BasicEntity`'s `Properties.object_Model` and
     * `IEntity::LoadGeometry` both take. Taken from the `.cgf` entries under
     * `Objects/` in `Data/IPL_Objects-part*.pak`, minus the level-of-detail
     * siblings, the terrain shadow proxies and the district-sized impostors,
     * and sorted by group then name.
     *
     * Generated by `tools/generate_prop_catalog.py`; the object database has
     * no recovered in-process enumerator to read at runtime.
     */
    extern const std::span<const PropModelEntry> g_PropModels;

    /** Model for a path, or null when the path is not in the catalog. */
    const PropModelEntry *FindPropModel(std::string_view path);

    /** Sentinel for a query naming no mesh, and for a prop with no model. */
    inline constexpr std::size_t kNoPropModel = static_cast<std::size_t>(-1);

    /**
     * The row a path or a file stem names, or `kNoPropModel`. A stem is not
     * unique across groups, so the first row wins.
     *
     * Inline because the translation unit `FindPropModel` lives in is
     * generated, and would lose this on the next run.
     */
    inline std::size_t FindPropModelIndex(std::string_view query) {
        if (query.empty()) {
            return kNoPropModel;
        }

        for (std::size_t index = 0; index < g_PropModels.size(); ++index) {
            if (g_PropModels[index].path == query) {
                return index;
            }
        }
        for (std::size_t index = 0; index < g_PropModels.size(); ++index) {
            if (g_PropModels[index].name == query) {
                return index;
            }
        }
        return kNoPropModel;
    }

    /** The row at `index`, or null once it is off the end of the catalog. */
    inline const PropModelEntry *PropModelAt(std::size_t index) {
        return index < g_PropModels.size() ? &g_PropModels[index] : nullptr;
    }
} // namespace KCDC::Shared::Game
