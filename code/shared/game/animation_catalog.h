namespace KCDC::Shared::Game {
    /**
     * One animation the game itself plays on a human body: a Mannequin
     * fragment and the tags that select its variant.
     *
     * A row of `actor_anim_action`, the table behind every actor animation
     * action, restricted to the two human classes and folded so each
     * fragment/tag combination appears once. `tags` mixes fragment tags with
     * global ones -- `r_bucket` is the right-hand manipulation group, not a
     * property of the fragment -- exactly as the table spells it, and
     * playback resolves each against whichever dictionary knows it.
     */
    struct AnimationEntry {
        const char *fragment;
        const char *tags;
        // The clip's length in seconds for option zero, the variant every
        // peer plays.
        float duration;
        // Whether the fragment ends by itself. A fragment that does not is a
        // loop and holds the body until something replaces it.
        bool oneShot;
        // The game's own `isfullbody`: whether the clip takes the FullBody
        // scope, which displaces locomotion and so needs the body held still.
        bool fullBody;
        // The item manipulation each hand is authored for, spelled as
        // `ItemManipulationType.xml` spells it (`bucket`, `axe_tool`), or
        // empty when that hand is free. This is what a prop has to match for
        // the animation to look like it is holding something.
        const char *rightHand;
        const char *leftHand;
        // Which bodies the table has it for: `kAnimationBodyMale`,
        // `kAnimationBodyFemale`, or both.
        std::uint8_t bodies;
        // The in/loop/out sequence the fragment is a part of, and which part:
        // `in`, `loop`, `out` or `variation`. Both are empty for a fragment
        // that is not one. The game never records a sequence; it is read from
        // the names (`BakerMillIn`, `BakerMillLoop`, `BakerMillOut`), and
        // `loop` is the middle part whether or not it ends by itself.
        const char *sequence;
        const char *phase;
        // The fragment the other actor of a Master/Slave pair plays against
        // this one (`TiedUpOut_Master` for `TiedUpOut_Slave`), or empty. Also
        // read from the names.
        const char *partner;
        // Whether the fragment, with these tags, also animates a second
        // character through the `SlaveChar` scope of the body's controller
        // definition -- a corpse carried, a horse groomed. That character
        // moves only once the game enslaves it to this body's controller.
        bool slaveBody;
    };

    inline constexpr std::uint8_t kAnimationBodyMale   = 1;
    inline constexpr std::uint8_t kAnimationBodyFemale = 2;

    /**
     * A static model an animation can be given to hold.
     *
     * Every item the game's `item.xml` gives both a `ManipulationType` and a
     * `.cgf` model -- the tools NPCs work with, and a few carried objects --
     * together with the default in-hand transform the manipulation type
     * declares. The model is authored for the hand slot it is carried in, so
     * most need no transform at all.
     */
    struct AnimationPropEntry {
        const char *name;
        const char *model;
        const char *manipulation;
        // Metres and radians, relative to the hand joint, straight out of
        // `ItemManipulationType.xml`'s default `ItemTransformation`.
        float position[3];
        float rotation[3];
    };

    /**
     * The way back to standing from one global `Stance` tag.
     *
     * A request that puts `sittingNoTable` or `lyingGround` among its tags
     * holds the body in that stance for as long as the tag is set, and taking
     * the tag away drops it straight into the standing idle. The game's own
     * way out is the transition its table authors from that stance to
     * standing, selected by the same tag: `StandUp` from the sitting ones,
     * `GetUp` from the lying ones. Its `ChangeStance` procedural clip applies
     * standing unconditionally, no seat needed.
     */
    struct AnimationStanceExitEntry {
        const char *stanceTag;
        const char *fragment;
    };

    // Generated by `tools/generate_animation_catalog.py`, sorted by fragment
    // then tags, by prop name, and by stance tag.
    extern const std::span<const AnimationEntry> g_Animations;
    extern const std::span<const AnimationPropEntry> g_AnimationProps;
    extern const std::span<const AnimationStanceExitEntry> g_AnimationStanceExits;

    /**
     * The exit for the first `Stance` tag among `tags` (`+`-separated, any
     * case) that has one, or null when none does -- a request with no stance
     * tag, or one like `beggarKneel` the game authors no way out of.
     */
    inline const AnimationStanceExitEntry *FindAnimationStanceExit(std::string_view tags) {
        const AnimationStanceExitEntry *found = nullptr;
        ForEachAnimationTag(tags, [&](std::string_view tag) {
            for (const auto &entry : g_AnimationStanceExits) {
                if (Framework::Utils::StringUtils::EqualsIgnoreCase(entry.stanceTag, tag)) {
                    found = &entry;
                    return false;
                }
            }
            return true;
        });
        return found;
    }

    /** The prop with that exact item name, or null. */
    inline const AnimationPropEntry *FindAnimationProp(std::string_view name) {
        for (const auto &entry : g_AnimationProps) {
            if (name == entry.name) {
                return &entry;
            }
        }
        return nullptr;
    }

    /**
     * Which bodies have a walk for carrying one kind of thing, as
     * `kAnimationBody*` bits, or 0.
     *
     * A carried item picks its walk through the hand tag its manipulation is
     * spelled as (`l_firewood`, `r_basket`), so only a kind with a
     * `MotionMovement` row under that tag walks as a carry; anything else is
     * held in a normal walk with the item floating at the hand. Read off the
     * table once.
     */
    inline std::uint8_t CarryWalkBodies(std::string_view manipulation) {
        static const std::unordered_map<std::string, std::uint8_t> byManipulation = [] {
            std::unordered_map<std::string, std::uint8_t> walks;
            for (const AnimationEntry &entry : g_Animations) {
                if (std::string_view(entry.fragment) != "MotionMovement") {
                    continue;
                }
                ForEachAnimationTag(entry.tags, [&](std::string_view tag) {
                    if (tag.size() > 2 && (tag.starts_with("l_") || tag.starts_with("r_"))) {
                        walks[std::string(tag.substr(2))] |= entry.bodies;
                    }
                    return true;
                });
            }
            return walks;
        }();
        const auto found = byManipulation.find(std::string(manipulation));
        return found != byManipulation.end() ? found->second : 0;
    }

    /** The same for an item class, through the prop its catalog name is; 0 for a class that is no prop. */
    inline std::uint8_t CarryWalkBodies(const RPC::ItemClassId &itemClass) {
        const ItemClassEntry *entry    = FindItemClass(itemClass);
        const AnimationPropEntry *prop = entry != nullptr ? FindAnimationProp(entry->name) : nullptr;
        return prop != nullptr ? CarryWalkBodies(prop->manipulation) : 0;
    }
} // namespace KCDC::Shared::Game
