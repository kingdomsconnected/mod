namespace KCDC::Shared::Game {
    /** One of the game's item classes: what an inventory can be told to make. */
    struct ItemClassEntry {
        std::string_view name;
        std::string_view guid;
        std::string_view category; // the table's element name: Armor, Food, ...
        // The authored `Price`, which C_Item::GetBasePrice (0x180469510)
        // answers; 0 where the table gives none.
        std::uint32_t price;
        // The `UIName` localization key the game shows the class's name
        // through, without the '@'. Shared by many classes; empty for none.
        std::string_view nameKey;
    };

    /** Categories the native equipment manager can wear. */
    inline constexpr bool IsEquippableCategory(std::string_view category) {
        return category == "Armor" || category == "Helmet" || category == "Hood" || category == "QuickSlotContainer" || category == "MeleeWeapon" || category == "MissileWeapon" || category == "Ammo";
    }

    /**
     * Every item class the game ships.
     *
     * The GUID is what `C_Inventory::CreateItems` takes, so this is the set of
     * things the mod can put into an inventory. Taken from the direct children
     * of `<ItemClasses>` in `Libs/Tables/item/item*.xml`.
     *
     * Generated by `tools/generate_item_catalog.py`; the item database has no
     * recovered in-process enumerator to read at runtime.
     */
    extern const std::span<const ItemClassEntry> g_ItemClasses;

    /** Item class for a GUID, or null when the guid is unknown. */
    const ItemClassEntry *FindItemClass(std::string_view guid);

    /** The compiled table alone, without the custom items or the streamed mods' classes. */
    const ItemClassEntry *FindShippedItemClass(std::string_view guid);

    /** Item class for the exact name the game's tables use, across the shipped table and the streamed mods' classes; null for none. */
    const ItemClassEntry *FindItemClassByName(std::string_view name);

    /** Every item class the session knows: the shipped table, then the streamed mods' classes. */
    void ForEachItemClass(const fu2::function<void(const ItemClassEntry &) const> &visit);

    /** Item class for a class as the wire carries it, or null when the catalog has none. */
    inline const ItemClassEntry *FindItemClass(const RPC::ItemClassId &itemClass) {
        const std::array<char, kCryGuidTextLength> text = CryGuidToText(itemClass.low, itemClass.high);
        return FindItemClass(std::string_view(text.data(), text.size()));
    }

    /**
     * The game's money item, `money` in the catalog. A purse is a stack of it,
     * and the trade screen counts every price in its units.
     */
    inline constexpr std::string_view kMoneyItemClassGuid = "5ef63059-322e-4e1b-abe8-926e100c770e";

    // C_ActorActionButchering::Enter creates rutina_eatingKnife. Its Exit
    // removes only this class with native creation reason 13.
    inline constexpr std::string_view kButcheringToolClassGuid = "5e1f8bc7-a8c6-4763-bdd9-843d73fcdc16";

    /**
     * The 128-bit class the engine addresses an item by, from its text.
     *
     * The catalog stores GUIDs as the game's tables write them, while the wire
     * and `S_ItemClassGUID` carry the 16 bytes behind them. `CryGuidFromText`
     * is the one conversion between the two, so the server can name a class it
     * has only in binary and put one on the wire that it has only as text.
     *
     * A malformed GUID gives `{0, 0}`, which reads as invalid here and which
     * `C_Inventory::CreateItems` refuses outright on the client.
     */
    inline constexpr RPC::ItemClassId ItemClassIdFromGuid(std::string_view guid) {
        RPC::ItemClassId itemClass;
        CryGuidFromText(guid, itemClass.low, itemClass.high);
        return itemClass;
    }

    // Ties the layout above to a value mined from the game by another route
    // entirely: `arrow_crude` as `g_MissileClasses` holds it. A change that
    // breaks the encoding fails to compile rather than spawning items nobody
    // can see.
    static_assert(ItemClassIdFromGuid("dfea5d01-b25c-414a-9ab4-6911a5f82118") == RPC::ItemClassId {0x414AB25CDFEA5D01ULL, 0x1821F8A51169B49AULL}, "Item class GUID encoding does not match the game's own parser");
    static_assert(ItemClassIdFromGuid("not-a-guid") == RPC::ItemClassId {}, "A malformed item class GUID must not produce a usable class");

} // namespace KCDC::Shared::Game
